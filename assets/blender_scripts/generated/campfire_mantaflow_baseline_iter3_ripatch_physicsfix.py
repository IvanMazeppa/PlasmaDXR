    bpy.ops.mesh.primitive_plane_add(size=4.0, location=(0.0, 0.0, 0.0))
    ground = bpy.context.object
    ground.name = 'GroundPlane'
    objs['ground'] = ground

    bpy.ops.mesh.primitive_cylinder_add(radius=0.23, depth=0.015, location=(0.0, 0.0, 0.0075))
    ash = bpy.context.object
    ash.name = 'AshBed'
    shade_smooth(ash)
    objs['ash'] = ash

    bpy.ops.mesh.primitive_uv_sphere_add(radius=0.17, location=(0.0, 0.0, 0.045))
    ember_bed = bpy.context.object
    ember_bed.name = 'EmberBed'
    ember_bed.scale = (1.0, 1.0, 0.16)
    apply_scale(ember_bed)
    shade_smooth(ember_bed)
    objs['ember_bed'] = ember_bed

    stones = []
    for index in range(8):
        angle = (math.tau / 8.0) * index + random.uniform(-0.09, 0.09)
        radius = random.uniform(0.28, 0.34)
        x = math.cos(angle) * radius
        y = math.sin(angle) * radius
        z = random.uniform(0.07, 0.10)
        bpy.ops.mesh.primitive_ico_sphere_add(subdivisions=2, radius=0.09, location=(x, y, z))
        stone = bpy.context.object
        stone.name = f'RingStone_{index:02d}'
        stone.scale = (
            random.uniform(0.85, 1.15),
            random.uniform(0.75, 1.15),
            random.uniform(0.60, 0.95),
        )
        shade_smooth(stone)
        stones.append(stone)
    objs['stones'] = stones

    logs = []
    charred_segments = []
    log_specs = [
        ((0.08, -0.02, 0.16), (math.radians(68), math.radians(6), math.radians(18))),
        ((-0.07, 0.03, 0.17), (math.radians(70), math.radians(-7), math.radians(134))),
        ((0.01, 0.08, 0.15), (math.radians(66), math.radians(5), math.radians(247))),
    ]
    for index, (location, rotation) in enumerate(log_specs):
        bpy.ops.mesh.primitive_cylinder_add(radius=0.04, depth=0.30, location=location, rotation=rotation)
        log = bpy.context.object
        log.name = f'CampLog_{index:02d}'
        shade_smooth(log)
        logs.append(log)

        axis = log.matrix_world.to_3x3() @ Vector((0.0, 0.0, 1.0))
        char_loc = log.location - (axis * 0.085)
        bpy.ops.mesh.primitive_cylinder_add(radius=0.041, depth=0.10, location=char_loc, rotation=rotation)
        char_piece = bpy.context.object
        char_piece.name = f'CampLogChar_{index:02d}'
        shade_smooth(char_piece)
        charred_segments.append(char_piece)
    objs['logs'] = logs
    objs['charred_segments'] = charred_segments

    sparks = []
    for index in range(7):
        sx = random.uniform(-0.07, 0.07)
        sy = random.uniform(-0.07, 0.07)
        sz = random.uniform(0.18, 0.42)
        bpy.ops.mesh.primitive_uv_sphere_add(radius=random.uniform(0.0035, 0.006), location=(sx, sy, sz))
        spark = bpy.context.object
        spark.name = f'Spark_{index:02d}'
        shade_smooth(spark)
        spark.visible_shadow = False
        spark.keyframe_insert(data_path='location', frame=1)
        spark.location.z += random.uniform(0.15, 0.32)
        spark.location.x += random.uniform(-0.04, 0.04)
        spark.location.y += random.uniform(-0.04, 0.04)
        spark.keyframe_insert(data_path='location', frame=60)
        sparks.append(spark)
    objs['sparks'] = sparks

    bpy.ops.mesh.primitive_plane_add(size=5.0, location=(0.0, 2.1, 1.25), rotation=(math.radians(90), 0.0, 0.0))
    backdrop = bpy.context.object
    backdrop.name = 'NightBackdrop'
    objs['backdrop'] = backdrop

    bpy.ops.mesh.primitive_uv_sphere_add(radius=0.14, location=(0.0, 0.0, 0.11))
    emitter = bpy.context.object
    emitter.name = 'CampfireEmitter'
    emitter.scale = (1.0, 1.0, 0.34)
    apply_scale(emitter)
    emitter.hide_render = True
    emitter.display_type = 'WIRE'
    objs['emitter'] = emitter

