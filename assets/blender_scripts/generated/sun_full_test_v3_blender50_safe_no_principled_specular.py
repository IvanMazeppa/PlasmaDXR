def setup_compositor_simple_bloom():
    scene = bpy.context.scene
    scene.use_nodes = True

    # Blender 5.0 compatibility: check if node_tree is available
    if not hasattr(scene, 'node_tree') or scene.node_tree is None:
        print("WARNING: Compositor node_tree not available, skipping bloom setup")
        return

    nt = scene.node_tree
    nodes = nt.nodes
    links = nt.links

    nodes.clear()

    rl = nodes.new('CompositorNodeRLayers')
    rl.location = (0, 0)

    # Blur the image and add back for a controllable bloom-like glow
    blur = nodes.new('CompositorNodeBlur')
    blur.location = (260, -120)
    blur.filter_type = 'GAUSS'
    blur.use_relative = True
    blur.size_x = 18
    blur.size_y = 18

    mix = nodes.new('CompositorNodeMixRGB')
    mix.location = (520, 0)
    mix.blend_type = 'ADD'
    mix.inputs['Fac'].default_value = 0.35

    comp = nodes.new('CompositorNodeComposite')
    comp.location = (760, 0)

    # Links
    links.new(rl.outputs['Image'], mix.inputs[1])
    links.new(rl.outputs['Image'], blur.inputs['Image'])
    links.new(blur.outputs['Image'], mix.inputs[2])
    links.new(mix.outputs['Image'], comp.inputs['Image'])


