def _look_at(obj, target: Vector, up=Vector((0.0, 0.0, 1.0))):
    # Simple look-at for lights/camera. Uses mathutils; avoids any RNA vector/float mismatch.
    loc = obj.location
    forward = (target - loc).normalized()
    right = forward.cross(up).normalized()
    true_up = right.cross(forward).normalized()
    rot = Matrix((right, true_up, -forward)).transposed().to_4x4()
    obj.matrix_world = Matrix.Translation(loc) @ rot


