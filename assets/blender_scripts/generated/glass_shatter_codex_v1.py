# Constraint network for progressive breaking
# ------------------------------------------------------------
impact_point = Vector((0.0, 0.0, 1.25))
constraint_objects = []
max_neighbors = 4
pair_keys = set()

planar_centers = {}
planar_sizes = {}
for shard in shards:
    planar_centers[shard.name] = Vector((shard.location.y, shard.location.z))
    planar_sizes[shard.name] = max(0.03, max(shard.dimensions.y, shard.dimensions.z) * 0.5)

for shard in shards:
    center_a = planar_centers[shard.name]
    nearby = []
    for other in shards:
        if other == shard:
            continue
        center_b = planar_centers[other.name]
        distance = (center_a - center_b).length
        connect_distance = max(0.06, (planar_sizes[shard.name] + planar_sizes[other.name]) * 0.9)
        if distance <= connect_distance:
            nearby.append((distance, other))

    nearby.sort(key=lambda item: item[0])
    for distance, other in nearby[:max_neighbors]:
        pair = tuple(sorted((shard.name, other.name)))
        if pair in pair_keys:
            continue
        pair_keys.add(pair)

        midpoint = (shard.location + other.location) * 0.5
        bpy.ops.object.empty_add(type='PLAIN_AXES', location=midpoint)
        constraint_obj = bpy.context.object
        constraint_obj.name = f"GlassConstraint_{len(constraint_objects):04d}"
        constraint_obj.empty_display_size = 0.025
        constraint_obj.hide_render = True

        bpy.ops.rigidbody.constraint_add(type='FIXED')
        rbc = constraint_obj.rigid_body_constraint
        rbc.type = 'FIXED'
        rbc.object1 = shard
        rbc.object2 = other
        rbc.disable_collisions = True
        rbc.use_breaking = True

        radial_distance = (Vector((midpoint.y, midpoint.z)) - Vector((impact_point.y, impact_point.z))).length
        radial_factor = min(radial_distance / 1.25, 1.0)
        base_threshold = 10.0 + (60.0 - 10.0) * radial_factor
        rbc.breaking_threshold = base_threshold * random.uniform(0.8, 1.2)

        constraint_objects.append(constraint_obj)

print(f"Generated {len(shards)} glass shards and {len(constraint_objects)} fixed breakable constraints.")

