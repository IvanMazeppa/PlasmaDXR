def make_open_cylinder(name, radius, depth, location=(0, 0, 0), vertices=64):
    bpy.ops.mesh.primitive_cylinder_add(vertices=vertices, radius=radius, depth=depth, location=location)
    obj = bpy.context.active_object
    obj.name = name

    # Remove top cap face (open top)
    me = obj.data
    bm = bmesh.new()
    bm.from_mesh(me)

    max_z = max(v.co.z for v in bm.verts) if bm.verts else 0.0
    to_delete = []
    for f in bm.faces:
        if f.normal.z > 0.9 and all(abs(v.co.z - max_z) < 1e-5 for v in f.verts):
            to_delete.append(f)
    if to_delete:
        bmesh.ops.delete(bm, geom=to_delete, context='FACES')

    bm.to_mesh(me)
    me.update()
    bm.free()

    return obj


