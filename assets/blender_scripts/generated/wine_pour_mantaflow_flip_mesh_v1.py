def create_wine_glass(collection=None):
    """Create a simple Bordeaux-style stemmed glass via lathe/spin."""
    bm = bmesh.new()

    # Profile in XZ plane (Y=0), from bottom center outward.
    # Units in meters; glass height ~0.22.
    # (x radius, z height)
    profile = [
        (0.0, 0.0),
        (0.03, 0.0),          # base radius
        (0.035, 0.01),
        (0.03, 0.015),
        (0.012, 0.02),        # stem radius
        (0.012, 0.10),
        (0.020, 0.12),
        (0.035, 0.14),
        (0.045, 0.18),
        (0.048, 0.205),
        (0.046, GLASS_HEIGHT) # rim
    ]

    verts = []
    for x, z in profile:
        v = bm.verts.new((x, 0.0, z))
        verts.append(v)
    bm.verts.ensure_lookup_table()

    edges = []
    for i in range(len(verts) - 1):
        edges.append(bm.edges.new((verts[i], verts[i + 1])))

    bm.edges.ensure_lookup_table()

    # Spin profile around Z axis
    geom = verts + edges
    ret = bmesh.ops.spin(
        bm,
        geom=geom,
        cent=(0.0, 0.0, 0.0),
        axis=(0.0, 0.0, 1.0),
        steps=96,
        angle=math.radians(360.0)
    )

    # Remove doubles along seam
    bmesh.ops.remove_doubles(bm, verts=bm.verts, dist=1e-5)

    # Fill faces between spun edges
    bmesh.ops.holes_fill(bm, edges=bm.edges, sides=0)

    # Recalculate normals
    bmesh.ops.recalc_face_normals(bm, faces=bm.faces)

    obj = new_mesh_object("WineGlass", bm, collection)
    obj.location = (0.0, 0.0, TABLE_Z)

    # Glass thickness + smoothing
    solid = obj.modifiers.new("Solidify", type='SOLIDIFY')
    solid.thickness = 0.002  # ~2mm
    solid.offset = -1.0

    subd = obj.modifiers.new("Subsurf", type='SUBSURF')
    subd.levels = 2
    subd.render_levels = 2

    shade = obj.modifiers.new("Smooth", type='SMOOTH')
    shade.iterations = 2
    shade.factor = 0.5

    return obj


