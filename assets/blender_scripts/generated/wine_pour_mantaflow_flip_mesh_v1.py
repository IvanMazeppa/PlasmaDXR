def build_scene():
    mkdir_p(OUTPUT_DIR)
    mkdir_p(CACHE_DIR)

    clear_scene()

    scene = bpy.context.scene
    setup_render(OUTPUT_DIR)
    setup_world()

    # Collection organization
    main_col = scene.collection
    sim_col = bpy.data.collections.new("SIM")
    set_col = bpy.data.collections.new("SET")
    main_col.children.link(sim_col)
    main_col.children.link(set_col)

    # Geometry
    table = create_table(set_col)
    glass = create_wine_glass(set_col)
    backdrop, bokeh_spheres = create_backdrop(set_col)

    # Materials
    wood_mat = make_wood_material()
    glass_mat = make_glass_material()
    wine_mat = make_wine_material()
    bokeh_mat = make_background_emission()

    table.data.materials.append(wood_mat)
    glass.data.materials.append(glass_mat)
    backdrop.data.materials.append(wood_mat)

    for sp in bokeh_spheres:
        sp.data.materials.append(bokeh_mat)

    # Fluid domain: tight-ish box around the action
    bm = bmesh.new()
    bmesh.ops.create_cube(bm, size=1.0)
    domain = new_mesh_object("Domain", bm, sim_col)

    # Domain dimensions: enough headroom for splashes and inflow
    domain.scale = (0.18, 0.18, 0.22)
    domain.location = (0.0, 0.0, 0.18)

    # Domain material can be wine (rendered liquid mesh often inherits this)
    domain.data.materials.append(wine_mat)

    # Inflow emitter (plane)
    inflow = create_inflow_emitter(sim_col)

    # Initial wine volume inside glass
    initial = create_initial_wine_volume(sim_col)

    # Fluid settings
    setup_fluid_domain(domain)

    # Inflow: negative velocity along +Z normal => downward pour
    setup_fluid_flow(
        inflow,
        behavior='INFLOW',
        velocity_normal=-FLOW_VELOCITY,
        sampling_substeps=FLOW_SAMPLING_SUBSTEPS,
        use_plane_init=True
    )

    # Initial fill as geometry flow (no plane init necessary, but harmless)
    setup_fluid_flow(
        initial,
        behavior='GEOMETRY',
        velocity_normal=0.0,
        sampling_substeps=0,
        use_plane_init=False
    )

    # Effectors: glass + table
    setup_fluid_effector(glass)
    setup_fluid_effector(table)

    # Camera & lighting
    cam = create_camera(set_col)
    scene.camera = cam
    create_lights(set_col)

    # Put backdrop and bokeh spheres into warm darkness
    backdrop.location.y = 0.45

    # Subtle scene composition adjustments
    table.location = (0.0, 0.0, -0.01)

    # Attempt bake (optional)
    bake_simulation(domain)

    # Render frame 40
    scene.frame_set(RENDER_FRAME)

    # NOTE: Render operator is required for a complete script.
    try:
        bpy.ops.render.render(write_still=True)
    except Exception as e:
        print(f"Render failed (context-dependent). Error: {e}")

    # Save .blend (required)
    blend_path = os.path.join(OUTPUT_DIR, f"{ASSET_NAME}.blend")
    try:
        bpy.ops.wm.save_as_mainfile(filepath=blend_path)
        print(f"Saved .blend to: {blend_path}")
    except Exception as e:
        print(f"Save .blend failed. Error: {e}")


