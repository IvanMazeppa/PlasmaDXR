def look_at(obj, target: Vector, up=Vector((0, 0, 1))):
    """Orient obj so its -Z axis looks at target (camera convention)."""
    loc = obj.matrix_world.to_translation()
    direction = (target - loc).normalized()

    # Create a rotation matrix where:
    # -Z points towards direction, Y is up-ish.
    z_axis = -direction
    x_axis = up.cross(z_axis).normalized()
    if x_axis.length < 1e-6:
        x_axis = Vector((1, 0, 0))
    y_axis = z_axis.cross(x_axis).normalized()

    rot = Matrix((x_axis, y_axis, z_axis)).transposed().to_4x4()
    obj.matrix_world = Matrix.Translation(loc) @ rot


