    # Density
    links.new(attr_density.outputs['Fac'], density_mult.inputs[0])
    if 'Density' in vol.inputs:
        links.new(density_mult.outputs['Value'], vol.inputs['Density'])

    # Blackbody fire intensity from flame
    links.new(attr_flame.outputs['Fac'], flame_gain.inputs[0])
    if 'Blackbody Intensity' in vol.inputs:
        links.new(flame_gain.outputs['Value'], vol.inputs['Blackbody Intensity'])

