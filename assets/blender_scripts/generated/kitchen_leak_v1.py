# Domain: larger than cabinet to allow drips outside front lip
DOMAIN_W = 0.82
DOMAIN_D = 0.95
DOMAIN_H = 0.75
DOMAIN_LOC = (0.0, 0.06, 0.28)

domain = add_cube(
    "FluidDomain",
    location=DOMAIN_LOC,
    scale=(DOMAIN_W, DOMAIN_D, DOMAIN_H),
    material=MAT_WATER,
)

# Add fluid modifier to domain
m_domain = domain.modifiers.new(name='Fluid', type='FLUID')
if m_domain is None:
    print("WARNING: Could not add Fluid modifier to domain")
else:
    m_domain.fluid_type = 'DOMAIN'
    ds = m_domain.domain_settings

    # Required constraints / starting params
    try:
        ds.domain_type = 'LIQUID'
    except Exception as e:
        print(f"WARNING: domain_settings.domain_type not set: {e}")

    try:
        ds.resolution_max = 96
    except Exception as e:
        print(f"WARNING: domain_settings.resolution_max not set: {e}")

    try:
        ds.cache_type = 'ALL'
    except Exception as e:
        print(f"WARNING: domain_settings.cache_type not set: {e}")

    try:
        ds.cache_directory = CACHE_DIR
    except Exception as e:
        print(f"WARNING: domain_settings.cache_directory not set: {e}")

    # Liquid mesh
    for attr, val in (
        ('use_mesh', True),
        ('use_flip_particles', True),
        ('flip_ratio', 1.0),
        ('particle_radius', 0.02),
        ('use_noise', False),
        ('noise_strength', 0.0),
        ('vorticity', 0.0),
    ):
        try:
            setattr(ds, attr, val)
        except Exception:
            pass

# Inflow spray emitter plane
spray_loc = (valve_hot_x, valve_y - 0.028, valve_z)
# Plane normal will define velocity direction when using velocity_normal.
spray_rot = (0.0, -math.pi / 2.0, math.radians(8))  # point toward -X with slight fan skew
spray = add_plane(
    "SprayEmitter",
    location=spray_loc,
    scale=(0.006, 0.018, 1.0),
    rotation=spray_rot,
)
# Keep emitter hidden in render
spray.hide_render = True

m_flow = spray.modifiers.new(name='Fluid', type='FLUID')
if m_flow is None:
    print("WARNING: Could not add Fluid modifier to SprayEmitter")
else:
    m_flow.fluid_type = 'FLOW'
    fs = m_flow.flow_settings

    for attr, val in (
        ('flow_type', 'LIQUID'),
        ('flow_behavior', 'INFLOW'),
        ('use_plane_init', True),
        ('sampling_substeps', 6),
        ('use_initial_velocity', True),
        ('velocity_normal', 1.75),
    ):
        try:
            setattr(fs, attr, val)
        except Exception as e:
            print(f"WARNING: Could not set flow setting {attr}: {e}")

    # Gas-only settings (safe no-op if absent)
    for attr, val in (
        ('temperature', 0.0),
        ('density', 1.0),
    ):
        try:
            setattr(fs, attr, val)
        except Exception:
            pass

