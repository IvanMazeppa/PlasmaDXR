def setup_camera(scene, focus_location=(0.0, 0.0, 0.0)):
    bpy.ops.object.camera_add(location=(0.07, -0.055, 0.19))
    cam = bpy.context.active_object
    cam.name = 'MacroCam'
    cam.rotation_euler = (math.radians(78), 0.0, math.radians(52))
    cam.data.lens = 110
    cam.data.sensor_width = 36

    bpy.ops.object.empty_add(type='PLAIN_AXES', location=focus_location)
    focus = bpy.context.active_object
    focus.name = 'FocusTarget'

    cam.data.dof.use_dof = True
    cam.data.dof.focus_object = focus
    cam.data.dof.aperture_fstop = 0.7

    scene.camera = cam
    return cam, focus


def create_flame_light(location=(0.0, 0.0, 0.0)):
    bpy.ops.object.light_add(type='POINT', location=location)
    light = bpy.context.active_object
    light.name = 'FlameLight'
    light.data.energy = 22
    light.data.color = (1.0, 0.72, 0.35)

    if hasattr(light.data, 'shadow_soft_size'):
        light.data.shadow_soft_size = 0.008

    # Very slow flicker
    light.data.keyframe_insert(data_path='energy', frame=1)
    light.data.energy = 19
    light.data.keyframe_insert(data_path='energy', frame=40)
    light.data.energy = 23
    light.data.keyframe_insert(data_path='energy', frame=80)
    light.data.energy = 20
    light.data.keyframe_insert(data_path='energy', frame=120)

    return light


