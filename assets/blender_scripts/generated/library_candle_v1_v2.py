    links.new(attr_flame.outputs.get('Fac'), ramp.inputs.get('Fac'))

    strength = nodes.new('ShaderNodeMath')
    strength.operation = 'MULTIPLY'
    strength.inputs[1].default_value = 18.0
    links.new(attr_flame.outputs.get('Fac'), strength.inputs[0])

    # Socket names can vary; use .get() to avoid KeyError.
