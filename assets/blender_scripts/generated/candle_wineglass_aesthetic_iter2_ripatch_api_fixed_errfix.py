def setup_volume_material(domain_obj, effect_type='BOTH'):
    mat = bpy.data.materials.new(name='VolumeShader')
    nodes = mat.node_tree.nodes
    links = mat.node_tree.links
    nodes.clear()

    output = nodes.new('ShaderNodeOutputMaterial')
    volume = nodes.new('ShaderNodeVolumePrincipled')

    attr_density = nodes.new('ShaderNodeAttribute')
    attr_density.attribute_name = 'density'
    attr_density.attribute_type = 'GEOMETRY'

    density_mult = nodes.new('ShaderNodeMath')
    density_mult.operation = 'MULTIPLY'
    density_mult.inputs[1].default_value = 3.5

    links.new(attr_density.outputs['Fac'], density_mult.inputs[0])
    links.new(density_mult.outputs['Value'], volume.inputs['Density'])

    if effect_type in ('FIRE', 'BOTH'):
        attr_flame = nodes.new('ShaderNodeAttribute')
        attr_flame.attribute_name = 'flame'
        attr_flame.attribute_type = 'GEOMETRY'

        flame_mult = nodes.new('ShaderNodeMath')
        flame_mult.operation = 'MULTIPLY'
        flame_mult.inputs[1].default_value = 8.0

        links.new(attr_flame.outputs['Fac'], flame_mult.inputs[0])
        links.new(flame_mult.outputs['Value'], volume.inputs['Blackbody Intensity'])
        volume.inputs['Blackbody Tint'].default_value = (1.0, 0.82, 0.56, 1.0)

    volume.inputs['Color'].default_value = (0.11, 0.07, 0.05, 1.0)
    links.new(volume.outputs['Volume'], output.inputs['Volume'])

    if domain_obj.data.materials:
        domain_obj.data.materials[0] = mat
    else:
        domain_obj.data.materials.append(mat)



