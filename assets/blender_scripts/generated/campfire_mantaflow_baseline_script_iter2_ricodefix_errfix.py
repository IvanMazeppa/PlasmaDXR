    add_effector(objects['ash'])
    add_effector(objects['stump'])
    add_effector(objects['lantern_base'])
    for log in objects['logs']:
        add_effector(log)
    for stone in objects['stones']:
        add_effector(stone)

    domain_mod = objects['domain'].modifiers.new(name='Fluid', type='FLUID')
