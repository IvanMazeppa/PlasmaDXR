    flame_mul.inputs[1].default_value = 22.0

    volume.inputs['Blackbody Tint'].default_value = (1.0, 0.66, 0.28, 1.0)

    links.new(density_attr.outputs['Fac'], density_mul.inputs[0])
    links.new(density_mul.outputs['Value'], volume.inputs['Density'])
    links.new(flame_attr.outputs['Fac'], flame_mul.inputs[0])
    links.new(flame_mul.outputs['Value'], volume.inputs['Blackbody Intensity'])
    links.new(volume.outputs['Volume'], output.inputs['Volume'])

