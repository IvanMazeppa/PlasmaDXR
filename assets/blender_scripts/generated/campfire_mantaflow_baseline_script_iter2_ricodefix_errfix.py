def setup_physics(scene, objects):
    def add_effector(obj):
        mod = obj.modifiers.new(name='Fluid', type='FLUID')
        if mod is None:
            print(f"WARNING: Could not add Fluid modifier to {obj.name}")
        else:
            mod.fluid_type = 'EFFECTOR'

