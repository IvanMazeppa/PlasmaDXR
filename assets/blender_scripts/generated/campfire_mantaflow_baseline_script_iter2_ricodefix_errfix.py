def setup_physics(scene, objects):
    bpy.ops.mesh.primitive_cube_add(size=1.0, location=(0.0, 0.0, 2.15))
    domain = bpy.context.active_object
    domain.name = 'FireDomain'
    domain.scale = (3.4, 3.4, 4.0)
    domain.display_type = 'WIRE'
    domain.visible_shadow = False

    domain_mod = domain.modifiers.new(name='Fluid', type='FLUID')
    if domain_mod is None:
        raise RuntimeError('Could not create Fluid modifier for domain')
    domain_mod.fluid_type = 'DOMAIN'

    dset = domain_mod.domain_settings
    dset.domain_type = 'GAS'
    dset.resolution_max = 96
    dset.cache_type = 'ALL'
    dset.cache_frame_start = scene.frame_start
    dset.cache_frame_end = scene.frame_end
    dset.cache_directory = CACHE_DIR
    dset.flame_smoke = 1.25
    dset.flame_vorticity = 0.35
    dset.burning_rate = 0.9

    setup_volume_material(domain, effect_type='FIRE')

    for obj in [objects['ground'], objects['stump'], objects['backdrop'], *objects['logs'], *objects['stones']]:
        add_effector(obj)

    flows = []
    flow_specs = [
        ((0.0, 0.0, 0.22), 0.14, 1.6),
        ((0.12, -0.03, 0.28), 0.1, 1.8),
        ((-0.1, 0.06, 0.26), 0.09, 1.5),
    ]
    for idx, (loc, radius, temp) in enumerate(flow_specs, start=1):
        bpy.ops.mesh.primitive_ico_sphere_add(subdivisions=2, radius=radius, location=loc)
        flow = bpy.context.active_object
        flow.name = f'FireFlow_{idx:02d}'
        flow.data.materials.append(objects['logs'][0].data.materials[0])

        flow_mod = flow.modifiers.new(name='Fluid', type='FLUID')
        if flow_mod is None:
            print(f'WARNING: Could not add Fluid modifier to {flow.name}')
        else:
            flow_mod.fluid_type = 'FLOW'
            fset = flow_mod.flow_settings
            fset.flow_type = 'BOTH'
            fset.density = 1.0
            fset.temperature = temp
        flows.append(flow)

    bpy.context.view_layer.update()
    scene.frame_current = scene.frame_start
    bpy.context.view_layer.update()

    bpy.ops.object.select_all(action='DESELECT')
    domain.select_set(True)
    bpy.context.view_layer.objects.active = domain
    bpy.context.view_layer.update()

    with bpy.context.temp_override(active_object=domain, object=domain):
        bpy.ops.fluid.bake_all()

    return domain, flows


