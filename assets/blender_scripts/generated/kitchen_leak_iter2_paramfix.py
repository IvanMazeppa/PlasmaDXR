# Post-bake: locate generated fluid mesh/particle objects and assign materials
# -------------------------------------------------------------

def assign_materials_to_fluid_children(domain_obj, water_mat):
    # Mantaflow typically creates child objects or objects named with domain prefix.
    candidates = []
    for obj in bpy.data.objects:
        if obj == domain_obj:
            continue
        n = obj.name.lower()
        if domain_obj.name.lower() in n and ("mesh" in n or "spray" in n or "foam" in n or "bubble" in n or "particles" in n):
            candidates.append(obj)

    # Also check children explicitly
    for obj in bpy.data.objects:
        if obj.parent == domain_obj:
            candidates.append(obj)

    # Unique
    unique = []
    seen = set()
    for c in candidates:
        if c.name not in seen:
            unique.append(c)
            seen.add(c.name)

    for c in unique:
        if c.type == 'MESH':
            assign_material(c, water_mat)

    return unique


