def build_plumbing_and_emitters(mats):
    """Creates a simple pipe with a burst fitting and a set of small cone emitters
    arranged to approximate a sideways fan spray."""

    # Main pipe (horizontal)
    pipe = create_mesh_object(
        "Pipe_Main",
        bm_cylinder(radius=0.018, depth=0.9, segments=42),
        location=(0.0, -0.22, 0.55),
        rotation=(0.0, math.radians(90), 0.0),
    )
    shade_smooth(pipe)
    assign_material(pipe, mats['metal'])

    # Fitting (thicker sleeve)
    fitting = create_mesh_object(
        "Pipe_Fitting",
        bm_cylinder(radius=0.03, depth=0.07, segments=42),
        location=(-0.16, -0.22, 0.55),
        rotation=(0.0, math.radians(90), 0.0),
    )
    shade_smooth(fitting)
    assign_material(fitting, mats['metal'])

    # Burst hole location; emitters sit slightly outside fitting
    burst_pos = Vector((-0.13, -0.22, 0.55))

    # Create a small fan of cone emitters
    emitters = []
    count = 7
    for i in range(count):
        # Cones oriented roughly towards +X (right wall) with spread in Y/Z
        t = (i / (count - 1)) * 2.0 - 1.0  # -1..1
        spread_y = math.radians(10.0) * t
        spread_z = math.radians(9.0) * (t * 0.8)

        cone = create_mesh_object(
            f"Leak_Emitter_{i:02d}",
            bm_cone(radius1=0.012, radius2=0.002, depth=0.03, segments=24, cap_ends=True),
            location=(burst_pos.x, burst_pos.y, burst_pos.z),
            rotation=(math.radians(90) + spread_z, spread_y, math.radians(90)),
        )
        shade_smooth(cone)
        assign_material(cone, mats['metal'])

        # Slight position offsets so they aren't perfectly coincident
        cone.location += Vector((0.01, 0.005 * t, 0.004 * math.sin(i)))

        # Animate burst: emit full size until LEAK_ON_END_FRAME, then shrink down
        cone.scale = Vector((1.0, 1.0, 1.0))
        cone.keyframe_insert(data_path="scale", frame=FRAME_START)
        cone.keyframe_insert(data_path="scale", frame=LEAK_ON_END_FRAME)

        cone.scale = Vector((0.001, 0.001, 0.001))
        cone.keyframe_insert(data_path="scale", frame=LEAK_ON_END_FRAME + 1)

        emitters.append(cone)

    return pipe, fitting, emitters


