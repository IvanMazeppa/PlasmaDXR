def main():
    clear_scene()
    setup_scene()

    # Materials
    mats = {
        'wood': material_wood(),
        'metal': material_painted_metal(),
        'rubber': material_rubber(),
        'water': material_water(),
        'wallpaint': material_wall_paint(),
        'plastic_blue': material_plastic("Mat_Plastic_Blue", base_color=(0.05, 0.10, 0.75, 1.0)),
        'plastic_red': material_plastic("Mat_Plastic_Red", base_color=(0.75, 0.08, 0.06, 1.0)),
        'plastic_yellow': material_plastic("Mat_Plastic_Yellow", base_color=(0.9, 0.82, 0.06, 1.0)),
        'plastic_gray': material_plastic("Mat_Plastic_Gray", base_color=(0.25, 0.25, 0.27, 1.0)),
    }

    # Camera + lights
    create_camera()
    create_lights()

    # Environment
    colliders = build_cabinet_environment(mats)

    # Plumbing + leak
    pipe, fitting, emitters = build_plumbing_and_emitters(mats)
    colliders.extend([pipe, fitting])

    # Domain
    domain_obj = create_domain_bounds()
    # keep domain invisible but selectable in viewport (render: hidden)
    domain_obj.hide_render = True
    domain_obj.display_type = 'WIRE'

    add_fluid_domain(domain_obj)

    # Flow emitters (inflow)
    for em in emitters:
        add_liquid_flow(em, behavior='INFLOW', velocity_normal=LEAK_VELOCITY_NORMAL)

    # Outflow (drain) to prevent domain filling up
    outflow_obj = create_outflow()
    outflow_obj.hide_render = True
    outflow_obj.display_type = 'WIRE'
    add_liquid_flow(outflow_obj, behavior='OUTFLOW', velocity_normal=0.0)

