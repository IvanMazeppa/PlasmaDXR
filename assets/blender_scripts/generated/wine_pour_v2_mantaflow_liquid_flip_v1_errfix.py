def bake_domain(domain_obj):
    scene = bpy.context.scene
    view_layer = bpy.context.view_layer

    # Ensure object mode for baking
    try:
        bpy.ops.object.mode_set(mode='OBJECT')
    except Exception:
        pass

    bpy.context.view_layer.update()

    bpy.ops.object.select_all(action='DESELECT')
    domain_obj.select_set(True)
    view_layer.objects.active = domain_obj

    override = {
        'scene': scene,
        'view_layer': view_layer,
        'active_object': domain_obj,
        'object': domain_obj,
        'selected_objects': [domain_obj],
        'selected_editable_objects': [domain_obj],
    }

    try:
        with bpy.context.temp_override(**override):
            bpy.ops.fluid.bake_all()
    except RuntimeError as e:
        print(f"WARNING: Fluid bake failed: {e}")


