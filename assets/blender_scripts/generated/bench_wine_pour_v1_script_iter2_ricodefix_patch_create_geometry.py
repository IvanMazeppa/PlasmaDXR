def add_light(light_type, name, location, rotation=(0.0, 0.0, 0.0), energy=10.0, color=(1.0, 1.0, 1.0)):
    bpy.ops.object.light_add(type=light_type, location=location, rotation=rotation)
    lobj = bpy.context.object
    lobj.name = name
    light = lobj.data
    light.energy = energy
    light.color = color
    return lobj


