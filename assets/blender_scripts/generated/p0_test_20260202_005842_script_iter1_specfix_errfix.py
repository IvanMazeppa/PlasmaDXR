def bake_fluid(domain_obj):
    # Context: domain must be active and selected
    deselect_all()
    domain_obj.select_set(True)
    set_active(domain_obj)

    # Ensure depsgraph is up to date
    try:
        bpy.context.view_layer.depsgraph.update()
    except Exception:
        # Some builds may not expose this method; safe to ignore.
        pass

    # NOTE: Ops are not listed as verified, but baking is required.
    # Use try/except to avoid fatal failures if ops are unavailable.
    try:
        pass  # Blender 5.0: free_all() removed - causes 'grids still in use'
    except Exception as e:
        print(f"fluid.free_all skipped: {e}")

    try:

        # ==== API FIXER: Bake Frame Range Alignment ====
        # Mantaflow cache_frame_start/cache_frame_end default to 1-120 independent of scene.frame_end.
        # Mismatched ranges waste bake time or cause missing frames.
        _api_fixer_scene = bpy.context.scene
        for _api_fixer_obj in bpy.data.objects:
            for _api_fixer_mod in _api_fixer_obj.modifiers:
                if _api_fixer_mod.type == 'FLUID' and hasattr(_api_fixer_mod, 'fluid_type') and _api_fixer_mod.fluid_type == 'DOMAIN':
                    _ds = _api_fixer_mod.domain_settings
                    _ds.cache_frame_start = _api_fixer_scene.frame_start
                    _ds.cache_frame_end = _api_fixer_scene.frame_end
                    print(f"[API Fixer] Aligned bake range: {_ds.cache_frame_start}-{_ds.cache_frame_end} (scene: {_api_fixer_scene.frame_start}-{_api_fixer_scene.frame_end})")
                    break
        # ==== END API FIXER: Bake Frame Range Alignment ====


        bpy.ops.fluid.bake_all()
    except Exception as e:
        print(f"fluid.bake_all failed or skipped: {e}")


def render_frames(scene: bpy.types.Scene):
    # Render each frame as a still (explicit write_still)
    for f in [min(FRAME_START + 5, FRAME_END), (FRAME_START + FRAME_END) // 2, FRAME_END]:  # Representative frames
        scene.frame_set(f)
        scene.render.filepath = os.path.join(OUTPUT_DIR, f"{ASSET_NAME}_{f:04d}.png")
        bpy.ops.render.render(write_still=True)


