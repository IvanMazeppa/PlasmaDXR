def main():
    ensure_dir(OUTPUT_DIR)

    clear_scene_factory()

    scene = bpy.context.scene
    setup_render(scene)
    setup_world(scene)
    setup_compositor(scene)

    env_col = get_or_create_collection("ENV")
    asset_col = get_or_create_collection("ASSET")
    sim_col = get_or_create_collection("SIM")
    light_col = get_or_create_collection("LIGHTS")

    # Build
    desk, wall, books = build_environment(env_col)
    asset = build_candle(asset_col)

    # Domain centered above wick
    dom_center = Vector((asset["wick"].location.x, asset["wick"].location.y, asset["wick"].location.z + 0.03))
    domain_obj = build_domain(sim_col, dom_center)

    # Materials
    wax = mat_beeswax()
    brass = mat_brass()
    wood = mat_mahogany()
    books_mat = mat_books()
    wick_mat = mat_wick()
    dom_mat = mat_domain_volume()

    assign_mat(asset["candle"], wax)
    assign_mat(asset["pool"], wax)
    assign_mat(asset["wick"], wick_mat)

    assign_mat(asset["holder_base"], brass)
    assign_mat(asset["holder_stem"], brass)
    assign_mat(asset["holder_cup"], brass)

    assign_mat(desk, wood)
    assign_mat(wall, books_mat)
    for b in books:
        assign_mat(b, books_mat)

    assign_mat(domain_obj, dom_mat)

    # Camera
    cam_loc = Vector((asset["wick"].location.x - 0.035, asset["wick"].location.y - 0.06, asset["wick"].location.z + 0.01))
    cam_target = Vector((asset["wick"].location.x, asset["wick"].location.y, asset["wick"].location.z + 0.02))
    create_camera(scene, cam_loc, cam_target)

    # Candle light
    light_loc = Vector((asset["wick"].location.x, asset["wick"].location.y, asset["wick"].location.z + 0.012))
    candle_light = create_candle_light(light_col, light_loc)
    animate_subtle_flicker(candle_light)

    # Fluid
    setup_fluid_domain(domain_obj)
    setup_fluid_flow(asset["emitter"])

    # Slight motion for slow breathing flame
    animate_emitter_breathe(asset["emitter"])

    # Bake
    bake_fluid(domain_obj)

    # Render
    render_frames(scene)

    # Save .blend
    blend_path = os.path.join(OUTPUT_DIR, f"{ASSET_NAME}.blend")
    bpy.ops.wm.save_as_mainfile(filepath=blend_path)
    print(f"Saved .blend to: {blend_path}")


if __name__ == "__main__":
    main()
