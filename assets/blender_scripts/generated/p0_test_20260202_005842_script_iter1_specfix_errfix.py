    candle_h = 0.18
    candle = create_cone(
        "Candle",
        radius1=0.010,
        radius2=0.008,
        depth=candle_h,
        location=(base_x, base_y, base_z + candle_h * 0.5),
        segments=96,
        collection=asset_col,
    )
    shade_smooth(candle)

    # Wax pool at top
    pool = create_cylinder(
        "WaxPool",
        radius=0.0075,
        depth=0.004,
        location=(base_x, base_y, base_z + candle_h - 0.0015),
        segments=96,
        collection=asset_col,
    )
    shade_smooth(pool)

    # Concavity
    bm = bmesh.new()
    bm.from_mesh(pool.data)
    for v in bm.verts:
        r = math.sqrt(v.co.x * v.co.x + v.co.y * v.co.y)
        if r < 0.0016:
            v.co.z -= 0.0012
        elif r < 0.0032:
            v.co.z -= 0.0007
    bm.to_mesh(pool.data)
    bm.free()

    # Wick
    wick = create_cylinder(
        "Wick",
        radius=0.0007,
        depth=0.006,
        location=(base_x, base_y, base_z + candle_h + 0.002),
        rotation=(math.radians(16.0), math.radians(6.0), 0.0),
        segments=24,
        collection=asset_col,
    )
    shade_smooth(wick)

    # Flow emitter around wick tip
    emitter = create_cylinder(
        "FlameEmitter",
        radius=0.0030,
        depth=0.008,
        location=(wick.location.x, wick.location.y, wick.location.z + 0.002),
        segments=32,
        collection=asset_col,
    )
    shade_smooth(emitter)
    emitter.hide_render = True
    emitter.display_type = 'WIRE'

    # Holder (simple ornate stack)
    holder_base = create_cylinder(
        "HolderBase",
        radius=0.06,
        depth=0.02,
        location=(base_x, base_y, base_z * 0.5 + 0.01),
        segments=96,
        collection=asset_col,
    )
    shade_smooth(holder_base)
    add_bevel(holder_base, width=0.002, segments=3)

    holder_stem = create_cylinder(
        "HolderStem",
        radius=0.012,
        depth=0.10,
        location=(base_x, base_y, 0.02 + 0.02 + 0.05),
        segments=64,
        collection=asset_col,
    )
    shade_smooth(holder_stem)
    add_bevel(holder_stem, width=0.0012, segments=2)

    holder_cup = create_cone(
        "HolderCup",
        radius1=0.03,
        radius2=0.02,
        depth=0.03,
        location=(base_x, base_y, 0.02 + 0.02 + 0.10 + 0.015),
        segments=96,
        collection=asset_col,
    )
    shade_smooth(holder_cup)
    add_bevel(holder_cup, width=0.001, segments=2)

    # Parenting
