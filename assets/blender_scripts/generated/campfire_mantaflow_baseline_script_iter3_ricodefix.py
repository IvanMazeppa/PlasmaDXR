    # A couple of dark background silhouettes to help depth without needing a full environment
    bpy.ops.mesh.primitive_uv_sphere_add(radius=0.16, location=(-0.85, 0.65, 0.08))
    mound_a = bpy.context.active_object
    mound_a.name = "BackgroundMound_A"
