def setup_physics(created, materials):
    scene = bpy.context.scene
    domain = created['domain']
    emitter = created['emitter']

    # Domain setup
    domain_mod = domain.modifiers.new(name='Fluid', type='FLUID')
    if domain_mod is None:
        print(f"WARNING: Could not add Fluid modifier to {domain.name}")
    else:
        domain_mod.fluid_type = 'DOMAIN'
        ds = domain_mod.domain_settings
        ds.domain_type = 'GAS'
        ds.resolution_max = 64
        ds.use_noise = True
        ds.noise_scale = 2
        ds.use_dissolve_smoke = True
        ds.dissolve_speed = 20
        ds.burning_rate = 0.7
        ds.flame_smoke = 0.10
        ds.flame_vorticity = 0.5
        ds.use_adaptive_timesteps = True
        ds.timesteps_max = 4
        ds.timesteps_min = 1
        ds.cfl_condition = 4.0
        ds.cache_type = 'ALL'
        ds.cache_directory = CACHE_DIR

    # Flow setup
    flow_mod = emitter.modifiers.new(name='Fluid', type='FLUID')
    if flow_mod is None:
        print(f"WARNING: Could not add Fluid modifier to {emitter.name}")
    else:
        flow_mod.fluid_type = 'FLOW'
        fs = flow_mod.flow_settings
        fs.flow_type = 'BOTH'
        fs.flow_behavior = 'INFLOW'
        fs.subframes = 2

    # Effectors: ground, logs, and stones help the fire sit in the ring and interact with the wood
    effector_objects = [created['ground'], created['ember_bed']] + created['logs'] + created['stones']
    for obj in effector_objects:
        effector_mod = obj.modifiers.new(name='Fluid', type='FLUID')
        if effector_mod is None:
            print(f"WARNING: Could not add Fluid modifier to {obj.name}")
        else:
            effector_mod.fluid_type = 'EFFECTOR'

    # Subtle wind and turbulence for lazy smoke curls
    bpy.ops.object.effector_add(type='WIND', location=(0.35, -0.35, 0.45))
    wind = bpy.context.active_object
    wind.name = "CampfireWind"
    wind.field.strength = 0.12
    wind.field.noise = 0.2
    wind.rotation_euler = (0.0, math.radians(86.0), math.radians(24.0))

    bpy.ops.object.effector_add(type='TURBULENCE', location=(0.0, 0.0, 0.72))
    turb = bpy.context.active_object
    turb.name = "CampfireTurbulence"
    turb.field.strength = 0.45

    bpy.context.view_layer.update()
    scene.frame_set(1)

    return domain


