def create_geometry(materials):
    random.seed(17)
    created = {}

    # Ground plane
    bpy.ops.mesh.primitive_plane_add(size=4.0, location=(0.0, 0.0, 0.0))
    ground = bpy.context.active_object
    ground.name = "Ground"
    assign_material(ground, materials['ground'])
    created['ground'] = ground

    # Ember bed
    bpy.ops.mesh.primitive_ico_sphere_add(subdivisions=3, radius=0.19, location=(0.0, 0.0, 0.035))
    ember_bed = bpy.context.active_object
    ember_bed.name = "EmberBed"
    ember_bed.scale = (1.0, 0.95, 0.18)
    assign_material(ember_bed, materials['ember'])
    created['ember_bed'] = ember_bed

    # Stone ring: 7 rough river stones around a 60cm diameter ring
    stones = []
    stone_count = 7
    ring_radius = 0.31
    for i in range(stone_count):
        angle = (math.tau / stone_count) * i + random.uniform(-0.08, 0.08)
        x = math.cos(angle) * ring_radius
        y = math.sin(angle) * ring_radius
        z = random.uniform(0.065, 0.09)
        bpy.ops.mesh.primitive_ico_sphere_add(subdivisions=1, radius=random.uniform(0.085, 0.11), location=(x, y, z))
        stone = bpy.context.active_object
        stone.name = f"RiverStone_{i:02d}"
        stone.scale = (
            random.uniform(0.9, 1.3),
            random.uniform(0.75, 1.1),
            random.uniform(0.6, 0.95),
        )
        stone.rotation_euler = (
            random.uniform(0.0, 1.2),
            random.uniform(0.0, 1.2),
            random.uniform(0.0, math.tau),
        )
        assign_material(stone, materials['stone'])
        stones.append(stone)
    created['stones'] = stones

    # Three birch logs in a loose teepee
    logs = []
    log_specs = [
        ((0.12, -0.05, 0.17), (0.0, math.radians(62.0), math.radians(34.0))),
        ((-0.12, -0.03, 0.17), (0.0, math.radians(-60.0), math.radians(-28.0))),
        ((0.0, 0.14, 0.17), (math.radians(61.0), 0.0, math.radians(92.0))),
    ]
    for idx, (location, rotation) in enumerate(log_specs):
        bpy.ops.mesh.primitive_cylinder_add(vertices=24, radius=0.04, depth=0.30, location=location, rotation=rotation)
        log = bpy.context.active_object
        log.name = f"BirchLog_{idx:02d}"
        assign_material(log, materials['bark'])
        logs.append(log)
    created['logs'] = logs

    # Frozen sparks for the still frame
    sparks = []
    spark_positions = [
        (0.02, 0.01, 0.22),
        (-0.03, 0.02, 0.27),
        (0.01, -0.04, 0.31),
        (0.04, -0.01, 0.38),
        (-0.02, -0.02, 0.47),
        (0.03, 0.03, 0.56),
    ]
    for idx, loc in enumerate(spark_positions):
        bpy.ops.mesh.primitive_uv_sphere_add(radius=0.006 + (idx * 0.0006), location=loc)
        spark = bpy.context.active_object
        spark.name = f"Spark_{idx:02d}"
