            if not _mesh_objs:
                continue
            from mathutils import Vector as _V
            _smin = _V((1e9, 1e9, 1e9))
            _smax = _V((-1e9, -1e9, -1e9))
            for _mo in _mesh_objs:
                for _c in _mo.bound_box:
                    _wc = _mo.matrix_world @ _V(_c)
