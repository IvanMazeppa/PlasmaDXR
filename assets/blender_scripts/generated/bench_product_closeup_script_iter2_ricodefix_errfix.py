def create_cyclorama(width=6.0, front_depth=4.0, height=3.2, radius=1.2, arc_steps=18):
    import bmesh

    mesh = bpy.data.meshes.new("Cyclorama")
    obj = bpy.data.objects.new("Cyclorama", mesh)
    bpy.context.collection.objects.link(obj)

    bm = bmesh.new()

    # Profile points in YZ plane
    profile = []

    # Floor segment (front to curve start)
    floor_steps = 6
    for i in range(floor_steps + 1):
        t = i / floor_steps
        y = -front_depth + (radius + front_depth) * t
        z = 0.0
        profile.append((y, z))

    # Arc segment from (r,0) to (0,r)
    for i in range(1, arc_steps):
        a = (i / arc_steps) * (math.pi / 2.0)
        y = radius * math.cos(a)
        z = radius * math.sin(a)
        profile.append((y, z))

    # Wall segment from (0,r) to (0,height)
    wall_steps = 8
    for i in range(wall_steps + 1):
        t = i / wall_steps
        y = 0.0
        z = radius + (height - radius) * t
        profile.append((y, z))

    # Create two rails of vertices and connect quads
    x0 = -width * 0.5
    x1 = width * 0.5

    v_left = []
    v_right = []
    for (y, z) in profile:
        v_left.append(bm.verts.new((x0, y, z)))
        v_right.append(bm.verts.new((x1, y, z)))

    bm.verts.ensure_lookup_table()

    for i in range(len(profile) - 1):
        v0 = v_left[i]
        v1 = v_left[i + 1]
        v2 = v_right[i + 1]
        v3 = v_right[i]
        try:
            bm.faces.new((v0, v1, v2, v3))
        except ValueError:
            # face exists
            pass

    # Cap ends (optional) by creating faces on left/right; keeps light from leaking
    # Left cap
    try:
        bm.faces.new(tuple(reversed(v_left)))
    except ValueError:
        pass
    # Right cap
    try:
        bm.faces.new(tuple(v_right))
    except ValueError:
        pass

    bmesh.ops.recalc_face_normals(bm, faces=bm.faces)

    bm.to_mesh(mesh)
    bm.free()

    # Slightly lift so floor isn't at z=0 (prevents z-fighting with bench props)
    obj.location = (0.0, 0.0, 0.0)

    # Smooth shading
    try:
        for p in obj.data.polygons:
            p.use_smooth = True
    except Exception:
        pass

    return obj


