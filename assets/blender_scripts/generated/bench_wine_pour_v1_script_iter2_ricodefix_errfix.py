def setup_physics(scene, objs, mats):
    # ----------------------------
    # Domain (LIQUID)
    # ----------------------------
    bpy.ops.mesh.primitive_cube_add(size=1.0, location=(0.0, 0.0, 0.35))
    domain = bpy.context.object
    domain.name = "LiquidDomain"
    domain.scale = (0.55, 0.55, 0.50)
    bpy.ops.object.transform_apply(location=False, rotation=False, scale=True)

    # Fluid modifier guard
    dmod = domain.modifiers.new(name='Fluid', type='FLUID')
    if dmod is None:
        print(f"WARNING: Could not add Fluid modifier to {domain.name}")
    else:
        dmod.fluid_type = 'DOMAIN'
        ds = dmod.domain_settings

        # Verified properties (from provided FluidDomainSettings list)
        ds.domain_type = 'LIQUID'
        ds.resolution_max = 96
        ds.simulation_method = 'FLIP'
        ds.use_adaptive_timesteps = True
        ds.timesteps_min = 1
        ds.timesteps_max = 6
        ds.cache_type = 'ALL'
        ds.cache_directory = CACHE_DIR
        ds.cache_frame_start = scene.frame_start
        ds.cache_frame_end = scene.frame_end

        # Liquid mesh
        ds.use_mesh = True
        ds.mesh_scale = 2
        ds.mesh_smoothen_pos = 1
        ds.mesh_smoothen_neg = 1

        # A touch of surface tension for wine-like cohesion
        ds.surface_tension = 0.35

    # Render the liquid surface with a wine material
    domain.active_material = mats['wine']

    # ----------------------------
    # Effectors (collision)
    # ----------------------------
    def add_effector(obj, surface_distance=0.0):
        emod = obj.modifiers.new(name='Fluid', type='FLUID')
        if emod is None:
            print(f"WARNING: Could not add Fluid modifier to {obj.name}")
            return
        emod.fluid_type = 'EFFECTOR'
        es = emod.effector_settings
        es.effector_type = 'COLLISION'
        es.use_effector = True
        es.surface_distance = surface_distance

    add_effector(objs['glass_collider'], surface_distance=0.0)
    add_effector(objs['table'], surface_distance=0.0)
    add_effector(objs['coaster'], surface_distance=0.0)

    # ----------------------------
    # Inflow (pour stream)
    # ----------------------------
    # A thin cylinder positioned at the bottle mouth, aimed toward the glass.
    bpy.ops.mesh.primitive_cylinder_add(radius=0.010, depth=0.20, location=(-0.18, 0.08, 0.32))
    inflow = bpy.context.object
    inflow.name = "WineInflow"
    inflow.rotation_euler = (math.radians(105.0), math.radians(5.0), math.radians(15.0))
    bpy.ops.object.transform_apply(location=False, rotation=True, scale=False)

    fmod = inflow.modifiers.new(name='Fluid', type='FLUID')
    if fmod is None:
        print(f"WARNING: Could not add Fluid modifier to {inflow.name}")
    else:
        fmod.fluid_type = 'FLOW'
        fs = fmod.flow_settings
        fs.flow_type = 'LIQUID'
        fs.use_plane_init = True  # Planar liquid emitter

        fs.flow_behavior = 'INFLOW'
        fs.use_inflow = True
        fs.use_absolute = True
        fs.subframes = 2
        fs.surface_distance = 0.6
        fs.use_initial_velocity = True
        fs.velocity_normal = -2.0
        fs.velocity_random = 0.2

        # Stop the pour after some time to get a clean still
        scene.frame_set(1)
        fs.use_inflow = True
        inflow.keyframe_insert(data_path='modifiers["Fluid"].flow_settings.use_inflow')
        scene.frame_set(55)
        fs.use_inflow = False
        inflow.keyframe_insert(data_path='modifiers["Fluid"].flow_settings.use_inflow')
        scene.frame_set(80)

    # Hide inflow mesh from render (but keep simulation)
    inflow.hide_render = True
    inflow.display_type = 'WIRE'

    # Ensure depsgraph updated before baking
    bpy.context.view_layer.update()

    return {'domain': domain, 'inflow': inflow}


