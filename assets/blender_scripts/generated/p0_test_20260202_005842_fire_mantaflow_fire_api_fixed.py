def setup_fluid_flow(flow_obj):
    mod = flow_obj.modifiers.new(name='Fluid', type='FLUID')
    mod.fluid_type = 'FLOW'
    fset = mod.flow_settings  # MUST be named 'fset'

    # ONLY these fset.* assignments are allowed (per VERIFIED API SPECIFICATION)
    fset.flow_type = 'BOTH'
    fset.flow_behavior = 'INFLOW'
    fset.temperature = 8.0
    fset.density = 0.07
    fset.use_initial_velocity = True
    fset.velocity_normal = 0.2

    return mod


