def animate_emitter(emitter_obj):
    """Small, slow emitter movement to create breathing flicker in the simulation."""
    rng = random.Random(123)

    # Slight lateral motion and rotation
    for f in (FRAME_START, int((FRAME_START + FRAME_END) * 0.5), FRAME_END):
        t = (f - FRAME_START) / max(1, (FRAME_END - FRAME_START))
        wobble = math.sin(t * math.pi * 2.0) * 0.0007
        wobble2 = math.cos(t * math.pi * 2.0) * 0.0004

        emitter_obj.location.x += wobble
        emitter_obj.location.y += wobble2
        emitter_obj.rotation_euler = Euler((
            math.radians(2.0) * (rng.random() - 0.5),
            math.radians(2.0) * (rng.random() - 0.5),
            math.radians(3.0) * math.sin(t * math.pi * 2.0)
        ))

        emitter_obj.keyframe_insert(data_path="location", frame=f)
        emitter_obj.keyframe_insert(data_path="rotation_euler", frame=f)


