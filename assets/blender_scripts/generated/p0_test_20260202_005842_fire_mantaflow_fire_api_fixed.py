def setup_lighting(scene: bpy.types.Scene, collection):
    # A very subtle fill to satisfy required lighting setup while keeping the
    # candle as the dominant source. Keep it extremely low.
    light_data = bpy.data.lights.new(name="TinyFill", type='AREA')
    light_data.energy = 0.2
    light_data.size = 0.25

    light_obj = bpy.data.objects.new(name="TinyFill", object_data=light_data)
    link_object(light_obj, collection)

    light_obj.location = Vector((0.0, -0.35, 0.35))
    light_obj.rotation_euler = Euler((math.radians(70), 0.0, math.radians(15)))

    return light_obj


