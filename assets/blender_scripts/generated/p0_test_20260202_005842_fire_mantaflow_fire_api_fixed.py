def main():
    ensure_dir(OUTPUT_DIR)

    clear_scene()

    scene = bpy.context.scene
    setup_render(scene)
    setup_world(scene)
    setup_compositor(scene)

    # Collections
    env_col = get_or_create_collection("ENV")
    asset_col = get_or_create_collection("ASSET")
    sim_col = get_or_create_collection("SIM")
    light_col = get_or_create_collection("LIGHTS")

    # Build environment and hero asset
    desk, books, wall = build_desk_and_books(env_col)
    asset = build_candle_and_holder(asset_col)

    # Simulation domain
    flame_center = (asset["wick"].location.x, asset["wick"].location.y, asset["wick"].location.z + 0.03)
    domain_obj = build_domain(sim_col, center=flame_center)

    # Materials
    build_materials_and_assign(asset, (desk, books, wall), domain_obj)

    # Camera
    cam_loc = (asset["wick"].location.x - 0.035, asset["wick"].location.y - 0.06, asset["wick"].location.z + 0.01)
    cam_target = (asset["wick"].location.x, asset["wick"].location.y, asset["wick"].location.z + 0.02)
    cam = create_camera("Camera", cam_loc, cam_target, focal_length_mm=110.0, fstop=1.4)
    scene.camera = cam

    # Lighting
    setup_lighting(scene, light_col)

    # Fluid simulation setup
    setup_fluid_domain(domain_obj)
    setup_fluid_flow(asset["emitter"])

    # Animate emitter for slow breathing flame
    animate_emitter(asset["emitter"])

    # Bake
    bake_fluid(domain_obj)

    # Render a few stills
    render_stills(scene, frames=(FRAME_START, int((FRAME_START + FRAME_END) * 0.5), FRAME_END))

    # Save .blend for inspection and rebaking
    blend_path = os.path.join(OUTPUT_DIR, f"{ASSET_NAME}.blend")
    bpy.ops.wm.save_as_mainfile(filepath=blend_path)
    print(f"Saved .blend to: {blend_path}")


if __name__ == "__main__":
    main()
