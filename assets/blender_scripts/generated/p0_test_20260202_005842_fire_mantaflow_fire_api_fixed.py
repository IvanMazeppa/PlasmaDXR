def assign_material(obj, mat):
    if obj.data is None or obj.type != 'MESH':
        return
    if obj.data.materials:
        obj.data.materials[0] = mat
    else:
        obj.data.materials.append(mat)


def build_materials_and_assign(asset, env_objs, domain_obj):
    mat_wax = material_beeswax()
    mat_brass = material_brass()
    mat_wood = material_mahogany()
    mat_books = material_books()
    mat_dom = material_domain_volume()

    assign_material(asset["candle"], mat_wax)
    assign_material(asset["pool"], mat_wax)

    # Wick: nearly black diffuse
    wick_mat = new_material("MAT_Wick")
    nt = wick_mat.node_tree
    nodes = nt.nodes
    links = nt.links
    out = nodes.new("ShaderNodeOutputMaterial")
    bsdf = nodes.new("ShaderNodeBsdfPrincipled")
    bsdf.inputs["Base Color"].default_value = (0.01, 0.01, 0.01, 1)
    bsdf.inputs["Roughness"].default_value = 0.9
    links.new(bsdf.outputs["BSDF"], out.inputs["Surface"])
    assign_material(asset["wick"], wick_mat)

    assign_material(asset["holder_base"], mat_brass)
    assign_material(asset["holder_stem"], mat_brass)
    assign_material(asset["holder_cup"], mat_brass)

    desk, books, wall = env_objs
    assign_material(desk, mat_wood)
    assign_material(wall, mat_books)
    for b in books:
        assign_material(b, mat_books)

    assign_material(domain_obj, mat_dom)


