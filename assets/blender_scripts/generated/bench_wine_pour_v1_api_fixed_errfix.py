def create_wine_glass(name="WineGlass", segments=72, thickness=0.0025):
    """Create a simple wine glass by lathing a profile (outer + inner) using bmesh."""
    import bmesh

    # Outer profile (radius, z) in meters
    # Lip -> bowl -> stem -> base
    outer = [
        (0.045, 0.155),
        (0.047, 0.150),
        (0.046, 0.135),
        (0.043, 0.115),
        (0.036, 0.090),
        (0.028, 0.070),
        (0.020, 0.055),
        (0.010, 0.030),
        (0.008, 0.010),
        (0.036, 0.006),
        (0.052, 0.002),
        (0.055, 0.000),
    ]

    # Inner profile: inset by thickness. Keep base sealed (inner doesn't go to ground)
    inner = []
    for r, z in outer:
        ri = max(r - thickness, 0.001)
        zi = z
        inner.append((ri, zi))
    # Lift inner bottom slightly so the base is solid
    inner[-1] = (inner[-1][0], 0.004)
    inner[-2] = (inner[-2][0], 0.0045)

    mesh = bpy.data.meshes.new(f"{name}Mesh")
    obj = bpy.data.objects.new(name, mesh)
    bpy.context.collection.objects.link(obj)

    bm = bmesh.new()

    def ring_verts(profile, flip=False):
        rings = []
        for r, z in profile:
            ring = []
            for i in range(segments):
                a = (i / segments) * math.tau
                x = r * math.cos(a)
                y = r * math.sin(a)
                v = bm.verts.new((x, y, z))
                ring.append(v)
            rings.append(ring)
        bm.verts.ensure_lookup_table()
        return rings

    outer_rings = ring_verts(outer)
    inner_rings = ring_verts(inner)

    def connect_rings(r0, r1, reverse=False):
        for i in range(segments):
            v00 = r0[i]
            v01 = r0[(i + 1) % segments]
            v10 = r1[i]
            v11 = r1[(i + 1) % segments]
            if reverse:
                bm.faces.new((v00, v10, v11, v01))
            else:
                bm.faces.new((v00, v01, v11, v10))

    # Side walls
    for idx in range(len(outer_rings) - 1):
        connect_rings(outer_rings[idx], outer_rings[idx + 1], reverse=False)
    for idx in range(len(inner_rings) - 1):
        connect_rings(inner_rings[idx + 1], inner_rings[idx], reverse=False)

    # Rim bridge: connect first ring of outer to first ring of inner
    connect_rings(outer_rings[0], inner_rings[0], reverse=False)

    # Bottom bridge: connect inner bottom to outer near-bottom ring (use last rings)
    connect_rings(inner_rings[-1], outer_rings[-1], reverse=False)

    bm.normal_update()
    bm.to_mesh(mesh)
    bm.free()

    # Shade smooth for glass
    for p in mesh.polygons:
        p.use_smooth = True

    return obj


