import bpy
import sys
import os
import math
from pathlib import Path

# =============================================================================
# Configuration
# =============================================================================

class Config:
    RESOLUTION = 64
    FRAME_START = 1
    FRAME_END = 50
    OUTPUT_DIR = "/home/maz3ppa/projects/PlasmaDXR/build/vdb_output/jelly_rabbit_v5"
    RENDER = True
    
    RENDER_RESOLUTION_X = 512
    RENDER_RESOLUTION_Y = 512
    RENDER_SAMPLES = 32

def parse_args():
    argv = sys.argv
    if "--" in argv:
        argv = argv[argv.index("--") + 1:]
    else:
        argv = []

    i = 0
    while i < len(argv):
        arg = argv[i]
        if arg == "--output_dir" and i + 1 < len(argv):
            Config.OUTPUT_DIR = argv[i + 1]
            i += 2
        else:
            i += 1

parse_args()

# =============================================================================
# Scene Setup
# =============================================================================

def clear_scene():
    bpy.ops.object.select_all(action='SELECT')
    bpy.ops.object.delete()

def setup_scene():
    scene = bpy.context.scene
    scene.frame_start = Config.FRAME_START
    scene.frame_end = Config.FRAME_END
    
    # World Background
    scene.world.use_nodes = True
    bg = scene.world.node_tree.nodes['Background']
    bg.inputs[0].default_value = (0.8, 0.8, 0.8, 1)

def create_material():
    mat = bpy.data.materials.new(name="JellyRed")
    mat.use_nodes = True
    nodes = mat.node_tree.nodes
    bsdf = nodes.get("Principled BSDF")
    
    bsdf.inputs['Base Color'].default_value = (1.0, 0.0, 0.1, 1)
    bsdf.inputs['Roughness'].default_value = 0.05
    bsdf.inputs['Transmission Weight'].default_value = 0.85 
    bsdf.inputs['IOR'].default_value = 1.33
    
    return mat

def create_procedural_rabbit():
    parts = []
    
    # Body
    bpy.ops.mesh.primitive_uv_sphere_add(radius=0.8, location=(0, 0, 0))
    body = bpy.context.active_object
    parts.append(body)
    
    # Head
    bpy.ops.mesh.primitive_uv_sphere_add(radius=0.5, location=(0, -0.6, 0.8))
    head = bpy.context.active_object
    parts.append(head)
    
    # Ears
    bpy.ops.mesh.primitive_uv_sphere_add(radius=0.2, location=(-0.3, -0.6, 1.4))
    ear_l = bpy.context.active_object
    ear_l.scale = (0.5, 0.5, 2.5)
    ear_l.rotation_euler = (math.radians(-20), math.radians(-15), 0)
    parts.append(ear_l)

    bpy.ops.mesh.primitive_uv_sphere_add(radius=0.2, location=(0.3, -0.6, 1.4))
    ear_r = bpy.context.active_object
    ear_r.scale = (0.5, 0.5, 2.5)
    ear_r.rotation_euler = (math.radians(-20), math.radians(15), 0)
    parts.append(ear_r)
    
    # Join
    bpy.ops.object.select_all(action='DESELECT')
    for p in parts:
        p.select_set(True)
    bpy.context.view_layer.objects.active = body
    bpy.ops.object.join()
    
    rabbit = bpy.context.active_object
    rabbit.name = "JellyRabbit"
    
    # Remesh - slightly finer to avoid bad topology
    bpy.ops.object.modifier_add(type='REMESH')
    remesh = rabbit.modifiers["Remesh"]
    remesh.mode = 'VOXEL'
    remesh.voxel_size = 0.06
    remesh.adaptivity = 0.0
    bpy.ops.object.modifier_apply(modifier="Remesh")
    
    # Smooth
    bpy.ops.object.shade_smooth()
    
    # Transform
    rabbit.location = (0, 0, 3)
    bpy.ops.object.transform_apply(location=True, rotation=True, scale=True)
    
    # --- Soft Body Setup ---
    bpy.ops.object.modifier_add(type='SOFT_BODY')
    sb = rabbit.modifiers["Softbody"]
    
    # Solver Steps (CRITICAL for stability)
    sb.settings.step_min = 20
    sb.settings.step_max = 100
    
    # Edges
    sb.settings.use_edges = True
    sb.settings.pull = 0.5
    sb.settings.push = 0.5
    sb.settings.damping = 2.0  # High damping prevents explosion
    sb.settings.bend = 0.5
    
    # Goal (Structure)
    sb.settings.goal_default = 0.2
    sb.settings.goal_min = 0.0
    sb.settings.goal_max = 1.0
    sb.settings.goal_spring = 0.3
    
    # Collision
    sb.settings.use_self_collision = True
    sb.settings.ball_size = 0.6  # Collision ball size
    
    # FORCE MEMORY CACHE
    sb.point_cache.use_disk_cache = False
    
    mat = create_material()
    rabbit.data.materials.append(mat)
    
    return rabbit

def create_floor():
    bpy.ops.mesh.primitive_plane_add(size=10, location=(0, 0, 0))
    floor = bpy.context.active_object
    floor.name = "Floor"
    
    bpy.ops.object.modifier_add(type='COLLISION')
    coll = floor.modifiers["Collision"]
    coll.settings.thickness_outer = 0.1  # Margin
    
    mat = bpy.data.materials.new(name="FloorMat")
    mat.use_nodes = True
    nodes = mat.node_tree.nodes
    bsdf = nodes.get("Principled BSDF")
    bsdf.inputs['Base Color'].default_value = (0.2, 0.2, 0.2, 1)
    floor.data.materials.append(mat)
    
    return floor

def setup_camera():
    bpy.ops.object.camera_add(location=(6, -6, 4))
    cam = bpy.context.active_object
    cam.name = "Camera"
    bpy.context.scene.camera = cam
    
    track = cam.constraints.new(type='TRACK_TO')
    track.target = bpy.data.objects["JellyRabbit"]
    track.track_axis = 'TRACK_NEGATIVE_Z'
    track.up_axis = 'UP_Y'

def setup_light():
    bpy.ops.object.light_add(type='SUN', location=(5, 5, 10))
    sun = bpy.context.active_object
    sun.data.energy = 5.0

def run_live_render_loop():
    print("[script] Starting LIVE simulation/render loop...")
    scene = bpy.context.scene
    output_dir = Path(Config.OUTPUT_DIR)
    output_dir.mkdir(parents=True, exist_ok=True)
    
    scene.render.engine = 'CYCLES'
    scene.cycles.samples = Config.RENDER_SAMPLES
    scene.render.resolution_x = Config.RENDER_RESOLUTION_X
    scene.render.resolution_y = Config.RENDER_RESOLUTION_Y
    scene.render.image_settings.file_format = 'PNG'
    
    rabbit = bpy.data.objects["JellyRabbit"]
    
    scene.frame_set(Config.FRAME_START)
    
    for frame in range(Config.FRAME_START, Config.FRAME_END + 1):
        scene.frame_set(frame)
        bpy.context.view_layer.update()
        
        # DEBUG CHECK
        depsgraph = bpy.context.evaluated_depsgraph_get()
        rabbit_eval = rabbit.evaluated_get(depsgraph)
        
        # Check center of mass or vertex
        # Note: If it exploded, values will be huge or nan
        v0 = rabbit_eval.data.vertices[0].co
        v0_world = rabbit_eval.matrix_world @ v0
        
        # Simple Nan Check
        if math.isnan(v0_world.z):
            print(f"[script] FRAME {frame} EXPLODED: NaN detected!")
        else:
            print(f"[script] Frame {frame}: Vertex Z = {v0_world.z:.4f}")
        
        render_path = output_dir / f"render_{frame:04d}.png"
        scene.render.filepath = str(render_path)
        
        if Config.RENDER:
            bpy.ops.render.render(write_still=True)
            print(f"[script] Saved {render_path}")

def main():
    print("=" * 60)
    print("Jelly Rabbit V5 (Stability Fix)")
    print("=" * 60)

    clear_scene()
    setup_scene()
    
    create_floor()
    create_procedural_rabbit()
    setup_camera()
    setup_light()
    
    output_dir = Path(Config.OUTPUT_DIR)
    output_dir.mkdir(parents=True, exist_ok=True)
    
    run_live_render_loop()
        
    blend_path = output_dir / "jelly_rabbit_v5_final.blend"
    bpy.ops.wm.save_as_mainfile(filepath=str(blend_path))
    print(f"[script] Saved blend: {blend_path}")

if __name__ == "__main__":
    main()
