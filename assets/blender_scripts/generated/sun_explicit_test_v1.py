def look_at(obj, target=(0.0, 0.0, 0.0)):
    # Aim -Z axis at target, Y up
    tx, ty, tz = target
    dx = tx - obj.location.x
    dy = ty - obj.location.y
    dz = tz - obj.location.z
    yaw = math.atan2(dx, -dy)
    dist_xy = math.sqrt(dx*dx + dy*dy)
    pitch = math.atan2(dz, dist_xy)
    obj.rotation_euler = (pitch, 0.0, yaw)


