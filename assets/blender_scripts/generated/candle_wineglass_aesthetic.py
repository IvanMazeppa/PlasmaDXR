def setup_physics():
    emitter = OBJECTS['flame_source']

    bpy.ops.object.select_all(action='DESELECT')
    emitter.select_set(True)
    bpy.context.view_layer.objects.active = emitter
    bpy.ops.object.quick_smoke()

    flow_mod = get_fluid_modifier(emitter, 'FLOW')
    if flow_mod is not None:
        fs = flow_mod.flow_settings
        fs.flow_type = 'BOTH'
        fs.flow_behavior = 'INFLOW'
        fs.density = 1.0
        fs.temperature = 2.5
        fs.use_absolute = True
        fs.use_inflow = True
        fs.subframes = 2
        fs.surface_distance = 0.0
        fs.fuel_amount = 1.0

    domain_obj = None
    domain_mod = None
    for obj in bpy.data.objects:
        mod = get_fluid_modifier(obj, 'DOMAIN')
        if mod is not None:
            domain_obj = obj
            domain_mod = mod
            break

    if domain_obj is None or domain_mod is None:
        raise RuntimeError('Quick Smoke did not create a Mantaflow domain.')

    domain_obj.name = 'CandleFireDomain'
    domain_obj.location = (0.0, 0.0, 0.6)
    domain_obj.scale = (0.6, 0.6, 1.2)
    domain_obj.display_type = 'WIRE'
    OBJECTS['domain'] = domain_obj

    ds = domain_mod.domain_settings
    ds.domain_type = 'GAS'
    ds.resolution_max = 128
    ds.use_noise = True
    ds.noise_strength = 1.0
    ds.noise_scale = 2
    ds.cache_type = 'ALL'
    ds.cache_directory = CACHE_DIR
    ds.cache_data_format = 'OPENVDB'
    ds.cache_noise_format = 'OPENVDB'
    ds.cache_frame_start = 1
    ds.cache_frame_end = 250
    ds.use_adaptive_domain = False
    ds.use_dissolve_smoke = True
    ds.use_dissolve_smoke_log = False
    ds.dissolve_speed = 30
    ds.use_adaptive_timesteps = True
    ds.timesteps_min = 1
    ds.timesteps_max = 4
    ds.vorticity = 2.5
    ds.flame_vorticity = 1.25
    ds.flame_smoke = 0.7

    assign_single_material(domain_obj, MATERIALS['domain_volume'])

    emitter.hide_render = True
    emitter.display_type = 'WIRE'

    add_fluid_effector(OBJECTS['table'])
    add_fluid_effector(OBJECTS['backdrop'])
    add_fluid_effector(OBJECTS['glass_bowl'])
    add_fluid_effector(OBJECTS['glass_stem'])
