    collision_targets.extend(objects['logs'])

    for obj in collision_targets:
        eff = obj.modifiers.new(name='Fluid', type='FLUID')
        if eff is None:
            print(f'WARNING: Could not add Fluid modifier to {obj.name}')
        else:
            eff.fluid_type = 'EFFECTOR'

    bpy.context.view_layer.update()
    try:
        bpy.context.evaluated_depsgraph_get().update()
    except Exception as exc:
        print(f'Depsgraph update warning: {exc}')

    return domain, emitter


