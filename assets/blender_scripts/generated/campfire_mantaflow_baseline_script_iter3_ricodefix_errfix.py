    emitter_nodes = emitter_mat.node_tree.nodes
    emitter_nodes.clear()
    emitter_out = emitter_nodes.new('ShaderNodeOutputMaterial')
    emitter_bsdf = emitter_nodes.new('ShaderNodeBsdfPrincipled')
