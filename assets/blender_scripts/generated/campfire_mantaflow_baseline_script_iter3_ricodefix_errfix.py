    ensure_material(emitter, emitter_mat)

    flow_mod = emitter.modifiers.new(name='Fluid', type='FLUID')
    if flow_mod is None:
        print('WARNING: Could not add Fluid modifier to emitter')
    else:
        flow_mod.fluid_type = 'FLOW'
        fs = flow_mod.flow_settings
        fs.flow_type = 'BOTH'
        fs.flow_behavior = 'INFLOW'
        fs.subframes = 2

    collision_targets = [objects['ground'], objects['stump'], objects['crate'], objects['canister'], objects['branch']]
