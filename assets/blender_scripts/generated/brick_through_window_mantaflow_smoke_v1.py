    brick.data.materials.append(brick_mat)

    # Apply scale for accurate physics
    deselect_all()
    set_active(brick)
    bpy.ops.object.transform_apply(location=False, rotation=False, scale=True)

    # Rigid body
    add_active_rb(brick, mass=BRICK_MASS_KG, friction=0.6, restitution=0.05, collision_shape='BOX')

    # Initial velocity (world X)
    try:
        brick.rigid_body.linear_velocity = (BRICK_INIT_SPEED, 0.0, 0.0)
        brick.rigid_body.angular_velocity = (0.0, random.uniform(-4, 4), random.uniform(-8, 8))
    except Exception:
        pass

