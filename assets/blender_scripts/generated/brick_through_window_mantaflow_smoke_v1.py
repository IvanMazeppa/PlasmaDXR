def try_bake_mantaflow(domain_obj):
    # Bake ops are not part of provided verified ops list; attempt anyway.
    # This script remains functional even if baking is skipped.
    scene = bpy.context.scene
    deselect_all()
    set_active(domain_obj)

    for op_name in ("bake_all", "bake_data"):
        try:
            op = getattr(bpy.ops.fluid, op_name)
        except Exception:
            op = None
        if op is None:
            continue
        try:
            print(f"Attempting bpy.ops.fluid.{op_name}()")
            op()
            print("Bake finished")
            return True
        except Exception as e:
            print(f"Bake op {op_name} failed:", e)

    print("No fluid bake performed (operator unavailable or context failure).")
    return False


