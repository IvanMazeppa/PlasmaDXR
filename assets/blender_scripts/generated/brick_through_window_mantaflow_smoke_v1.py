def setup_shards_rigidbody(shards, impact_point=Vector((0.0, 0.0, 1.0))):
    rng = random.Random(7)

    for i, s in enumerate(shards):
        # Ensure transforms are applied for stability
        deselect_all()
        set_active(s)
        try:
            bpy.ops.object.transform_apply(location=False, rotation=False, scale=True)
        except Exception:
            pass

        add_active_rb(s, mass=0.02, friction=0.05, restitution=0.25, collision_shape='CONVEX_HULL')

        # Disable shards until impact (activation trigger)
        if hasattr(s, "rigid_body") and s.rigid_body is not None:
            try:
                bpy.context.scene.frame_set(FRAME_START)
                s.rigid_body.enabled = False
                s.rigid_body.keyframe_insert(data_path="enabled", frame=FRAME_START)

                bpy.context.scene.frame_set(IMPACT_FRAME)
                s.rigid_body.enabled = True
                s.rigid_body.keyframe_insert(data_path="enabled", frame=IMPACT_FRAME)
            except Exception:
                pass

            # Give shards an initial kick at impact (radial + forward)
            try:
                bpy.context.scene.frame_set(IMPACT_FRAME)
                offset = (s.location - impact_point)
                radial = offset.normalized() if offset.length > 1e-6 else Vector((0.0, 1.0, 0.0))
                forward = Vector((1.0, 0.0, 0.0))

                # Smaller shards: faster spray (approx by random factor)
                speed = rng.uniform(2.0, 9.0)
                vel = forward * rng.uniform(3.5, 8.0) + radial * speed + Vector((0.0, 0.0, rng.uniform(-0.8, 1.2)))

                s.rigid_body.linear_velocity = (vel.x, vel.y, vel.z)
                s.rigid_body.angular_velocity = (rng.uniform(-25, 25), rng.uniform(-25, 25), rng.uniform(-25, 25))

                s.rigid_body.keyframe_insert(data_path="linear_velocity", frame=IMPACT_FRAME)
                s.rigid_body.keyframe_insert(data_path="angular_velocity", frame=IMPACT_FRAME)
            except Exception:
                pass

        # Hide shards before impact for clean pre-impact glass
        try:
            bpy.context.scene.frame_set(FRAME_START)
            s.hide_render = True
            s.hide_viewport = True
            s.keyframe_insert(data_path="hide_render", frame=FRAME_START)
            s.keyframe_insert(data_path="hide_viewport", frame=FRAME_START)

            bpy.context.scene.frame_set(IMPACT_FRAME)
            s.hide_render = False
            s.hide_viewport = False
            s.keyframe_insert(data_path="hide_render", frame=IMPACT_FRAME)
            s.keyframe_insert(data_path="hide_viewport", frame=IMPACT_FRAME)
        except Exception:
            pass


def animate_intact_glass_visibility(glass_intact):
    # Visible until impact, then hidden/disabled
    try:
        bpy.context.scene.frame_set(FRAME_START)
        glass_intact.hide_render = False
        glass_intact.hide_viewport = False
        glass_intact.keyframe_insert(data_path="hide_render", frame=FRAME_START)
        glass_intact.keyframe_insert(data_path="hide_viewport", frame=FRAME_START)

        bpy.context.scene.frame_set(IMPACT_FRAME)
        glass_intact.hide_render = True
        glass_intact.hide_viewport = True
        glass_intact.keyframe_insert(data_path="hide_render", frame=IMPACT_FRAME)
        glass_intact.keyframe_insert(data_path="hide_viewport", frame=IMPACT_FRAME)
    except Exception:
        pass

    # Disable rigidbody collision at impact too
    if hasattr(glass_intact, "rigid_body") and glass_intact.rigid_body is not None:
        try:
            bpy.context.scene.frame_set(FRAME_START)
            glass_intact.rigid_body.enabled = True
            glass_intact.rigid_body.keyframe_insert(data_path="enabled", frame=FRAME_START)
            bpy.context.scene.frame_set(IMPACT_FRAME)
            glass_intact.rigid_body.enabled = False
            glass_intact.rigid_body.keyframe_insert(data_path="enabled", frame=IMPACT_FRAME)
        except Exception:
            pass


