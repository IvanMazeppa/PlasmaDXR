def setup_camera(scene, hero_obj):
    cam_data = bpy.data.cameras.new("Camera")
    cam_obj = bpy.data.objects.new("Camera", cam_data)
    scene.collection.objects.link(cam_obj)
    scene.camera = cam_obj

    cam_obj.location = (0.0, -2.9, 0.95)

    direction = (hero_obj.location - cam_obj.location)
    cam_obj.rotation_euler = direction.to_track_quat('-Z', 'Y').to_euler()

    cam_data.lens = 55.0
    cam_data.clip_start = 0.05
    cam_data.clip_end = 1000.0

    # Depth of field (best effort; guard for API differences)
    try:
        cam_data.dof.use_dof = True
        cam_data.dof.focus_object = hero_obj
        cam_data.dof.aperture_fstop = 2.8
    except Exception as e:
        print(f"WARNING: Could not configure DOF: {e}")

    return cam_obj


def setup_compositor(scene):
    # Optional, but adds glow to emissives. Guarded.
    try:
        nt = scene.node_tree
        if nt is None:
            return
        nodes = nt.nodes
        links = nt.links
        nodes.clear()

        rl = nodes.new('CompositorNodeRLayers')
        glare = nodes.new('CompositorNodeGlare')
        comp = nodes.new('CompositorNodeComposite')

        glare.glare_type = 'FOG_GLOW'
        glare.quality = 'HIGH'
        glare.size = 7
        glare.mix = 0.15
        glare.threshold = 0.7

        links.new(rl.outputs.get('Image'), glare.inputs.get('Image'))
        links.new(glare.outputs.get('Image'), comp.inputs.get('Image'))
    except Exception as e:
        print(f"WARNING: Could not setup compositor: {e}")


