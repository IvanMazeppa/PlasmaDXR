def assign_mat(obj, mat):
    if obj.data is None:
        return
    if getattr(obj.data, "materials", None) is None:
        return
    if len(obj.data.materials) == 0:
        obj.data.materials.append(mat)
    else:
        obj.data.materials[0] = mat


