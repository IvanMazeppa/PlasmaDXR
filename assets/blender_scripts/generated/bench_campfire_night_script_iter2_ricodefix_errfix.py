    # Aim rim at hero
    direction = (hero_obj.location - rim_obj.location)
    rim_obj.rotation_euler = direction.to_track_quat('-Z', 'Y').to_euler()

    # Gentle fill (very low, to avoid crushed blacks)
    fill_data = bpy.data.lights.new(name="Fill", type='AREA')
    fill_data.shape = 'RECTANGLE'
    fill_data.size = 1.6
    fill_data.size_y = 1.2
    fill_data.energy = 12.0
    fill_data.color = (0.45, 0.55, 0.8)
