def setup_lighting(scene, hero_obj):
    # Key light (warm, from side)
    key_data = bpy.data.lights.new(name="Key", type='AREA')
    key_data.shape = 'RECTANGLE'
    key_data.size = 0.8
    key_data.size_y = 0.5
    key_data.energy = 60.0
    key_data.color = (1.0, 0.78, 0.55)
    key_obj = bpy.data.objects.new("Key", key_data)
    scene.collection.objects.link(key_obj)
    key_obj.location = (1.2, -0.7, 1.1)
    key_obj.rotation_euler = (math.radians(65.0), math.radians(0.0), math.radians(35.0))

    # Fire practical point light (inside flame)
    fire_data = bpy.data.lights.new(name="FireLight", type='POINT')
    fire_data.energy = 35.0
    fire_data.color = (1.0, 0.45, 0.18)
    fire_data.shadow_soft_size = 0.25
    fire_obj = bpy.data.objects.new("FireLight", fire_data)
    scene.collection.objects.link(fire_obj)
    fire_obj.location = (0.0, 0.0, 0.25)

    # Cool rim light for separation
    rim_data = bpy.data.lights.new(name="Rim", type='SPOT')
    rim_data.energy = 20.0
    rim_data.color = (0.65, 0.75, 1.0)
    rim_data.spot_size = math.radians(55.0)
    rim_data.spot_blend = 0.35
    rim_obj = bpy.data.objects.new("Rim", rim_data)
    scene.collection.objects.link(rim_obj)
