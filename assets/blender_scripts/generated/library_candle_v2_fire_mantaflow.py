try:
    # Bake noise (requires use_noise=True)
    bpy.ops.fluid.bake_noise()
except Exception as e:
    print("bpy.ops.fluid.bake_noise failed:", e)

try:
    # Generic bake op (kept for compatibility in automated pipelines)
    bpy.ops.fluid.bake()
except Exception as e:
    print("bpy.ops.fluid.bake failed:", e)

