# Canonical Section: setup_physics

def setup_physics(*args, **kwargs):
    scene = bpy.context.scene

    def collect_objects():
        collected = []

        def add_candidate(value):
            if value is None:
                return
            if isinstance(value, dict):
                for nested in value.values():
                    add_candidate(nested)
                return
            if isinstance(value, (list, tuple, set)):
                for nested in value:
                    add_candidate(nested)
                return
            if hasattr(value, "name") and hasattr(value, "modifiers"):
                collected.append(value)

        for arg in args:
            add_candidate(arg)
        for value in kwargs.values():
            add_candidate(value)
        for obj in bpy.data.objects:
            collected.append(obj)

        unique = []
        seen_names = set()
        for obj in collected:
            name = getattr(obj, "name", None)
            if name and name not in seen_names:
                seen_names.add(name)
                unique.append(obj)
        return unique

    def find_object_with_fluid_type(objects, fluid_type):
        for obj in objects:
            for mod in obj.modifiers:
                if hasattr(mod, "fluid_type") and mod.fluid_type == fluid_type:
                    return obj
        return None

    def find_named_object(objects, keywords):
        for obj in objects:
            name = obj.name.lower()
            if all(keyword in name for keyword in keywords):
                return obj
        for obj in objects:
            name = obj.name.lower()
            if any(keyword in name for keyword in keywords):
                return obj
        return None

    def ensure_volume_material(domain_obj):
        if domain_obj is None or domain_obj.data is None or not hasattr(domain_obj.data, "materials"):
            return

        mat = bpy.data.materials.get("CandleFireVolume")
        if mat is None:
            mat = bpy.data.materials.new(name="CandleFireVolume")

        nodes = mat.node_tree.nodes
        links = mat.node_tree.links
        nodes.clear()

        output = nodes.new('ShaderNodeOutputMaterial')
        output.location = (500, 0)

        volume = nodes.new('ShaderNodeVolumePrincipled')
        volume.location = (220, 0)
        volume.inputs['Color'].default_value = (0.65, 0.68, 0.74, 1.0)
        volume.inputs['Blackbody Tint'].default_value = (1.0, 0.78, 0.48, 1.0)
        volume.inputs['Temperature'].default_value = 1200.0

        attr_density = nodes.new('ShaderNodeAttribute')
        attr_density.location = (-420, 100)
        attr_density.attribute_name = 'density'
        attr_density.attribute_type = 'GEOMETRY'

        density_mul = nodes.new('ShaderNodeMath')
        density_mul.location = (-140, 100)
        density_mul.operation = 'MULTIPLY'
        density_mul.inputs[1].default_value = 7.5

        attr_flame = nodes.new('ShaderNodeAttribute')
        attr_flame.location = (-420, -80)
        attr_flame.attribute_name = 'flame'
        attr_flame.attribute_type = 'GEOMETRY'

        flame_mul = nodes.new('ShaderNodeMath')
        flame_mul.location = (-140, -80)
        flame_mul.operation = 'MULTIPLY'
        flame_mul.inputs[1].default_value = 4.0

        links.new(attr_density.outputs['Fac'], density_mul.inputs[0])
        links.new(density_mul.outputs['Value'], volume.inputs['Density'])
        links.new(attr_flame.outputs['Fac'], flame_mul.inputs[0])
        links.new(flame_mul.outputs['Value'], volume.inputs['Blackbody Intensity'])
        links.new(volume.outputs['Volume'], output.inputs['Volume'])

        if len(domain_obj.data.materials) == 0:
            domain_obj.data.materials.append(mat)
        else:
            domain_obj.data.materials[0] = mat

    objects = collect_objects()

    domain_obj = find_object_with_fluid_type(objects, 'DOMAIN')
    if domain_obj is None:
        domain_obj = find_named_object(objects, ['domain'])

    flow_obj = find_object_with_fluid_type(objects, 'FLOW')
    if flow_obj is None:
        flow_obj = find_named_object(objects, ['emitter'])
    if flow_obj is None:
        flow_obj = find_named_object(objects, ['flow'])
    if flow_obj is None:
        flow_obj = find_named_object(objects, ['flame'])
    if flow_obj is None:
        flow_obj = find_named_object(objects, ['wick'])

    if domain_obj is not None:
        domain_mod = domain_obj.modifiers.get("Fluid")
        if domain_mod is None:
            domain_mod = domain_obj.modifiers.new(name='Fluid', type='FLUID')
        if domain_mod is None:
            print(f"WARNING: Could not add Fluid modifier to {domain_obj.name}")
        else:
            domain_mod.fluid_type = 'DOMAIN'
            ds = domain_mod.domain_settings
            ds.domain_type = 'GAS'
            ds.resolution_max = 96
            ds.time_scale = 1.0
            ds.use_adaptive_timesteps = True
            ds.timesteps_min = 1
            ds.timesteps_max = 4
            ds.cache_type = 'ALL'
            ds.cache_directory = CACHE_DIR
            ds.cache_data_format = 'OPENVDB'
            ds.cache_noise_format = 'OPENVDB'
            ds.cache_frame_start = scene.frame_start
            ds.cache_frame_end = scene.frame_end
            ds.use_noise = True
            ds.noise_scale = 2
            ds.noise_strength = 0.6
            ds.noise_pos_scale = 1.5
            ds.noise_time_anim = 0.08
            ds.flame_vorticity = 0.35
            ds.vorticity = 0.15
            ds.flame_ignition = 1.1
            ds.flame_max_temp = 2.2
            ds.flame_smoke = 1.25
            ds.burning_rate = 0.85
            ds.alpha = 0.2
            ds.beta = 0.1
            ds.use_dissolve_smoke = True
            ds.use_dissolve_smoke_log = True
            ds.dissolve_speed = 18
            ensure_volume_material(domain_obj)
            domain_obj.visible_shadow = False

    if flow_obj is not None:
        flow_mod = flow_obj.modifiers.get("Fluid")
        if flow_mod is None:
            flow_mod = flow_obj.modifiers.new(name='Fluid', type='FLUID')
        if flow_mod is None:
            print(f"WARNING: Could not add Fluid modifier to {flow_obj.name}")
        else:
            flow_mod.fluid_type = 'FLOW'
            fs = flow_mod.flow_settings
            fs.flow_type = 'BOTH'
            fs.flow_behavior = 'INFLOW'
            fs.use_inflow = True
            fs.use_absolute = True
            fs.density = 1.15
            fs.fuel_amount = 1.4
            fs.temperature = 1.8
            fs.surface_distance = 0.05
            fs.use_initial_velocity = True
            fs.velocity_normal = 0.35
            fs.velocity_factor = 0.5
            fs.velocity_random = 0.03
            fs.subframes = 2
            if 'emitter' in flow_obj.name.lower() or 'flow' in flow_obj.name.lower() or 'flame' in flow_obj.name.lower():
                flow_obj.hide_render = True

    effector_keywords = ('table', 'glass', 'wine', 'candle')
    effector_objects = []
    for obj in objects:
        if obj == domain_obj or obj == flow_obj:
            continue
        lowered = obj.name.lower()
        if any(keyword in lowered for keyword in effector_keywords):
            effector_objects.append(obj)

    for obj in effector_objects:
        effector_mod = obj.modifiers.get("Fluid")
        if effector_mod is None:
            effector_mod = obj.modifiers.new(name='Fluid', type='FLUID')
        if effector_mod is None:
            print(f"WARNING: Could not add Fluid modifier to {obj.name}")
            continue
        effector_mod.fluid_type = 'EFFECTOR'
        es = effector_mod.effector_settings
        es.effector_type = 'COLLISION'
        es.surface_distance = 0.001
        es.use_effector = True
        es.subframes = 1

    bpy.context.view_layer.update()

    for arg in args:
        if isinstance(arg, dict):
            arg['fluid_domain'] = domain_obj
            arg['fluid_flow'] = flow_obj
            arg['fluid_effectors'] = effector_objects
            return arg

    return {
        'fluid_domain': domain_obj,
        'fluid_flow': flow_obj,
        'fluid_effectors': effector_objects,
    }


