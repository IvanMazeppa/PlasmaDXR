def create_constraint_network(bands, frame_parts, constraint_collection):
    spoke_count = len(bands[0])

    for band_index, band in enumerate(bands):
        for i in range(spoke_count):
            a = band[i]
            b = band[(i + 1) % spoke_count]
            mid = a.location.lerp(b.location, 0.5)
            threshold = 0.5 * (constraint_threshold(a["local_x"], a["local_z"]) + constraint_threshold(b["local_x"], b["local_z"]))
            add_constraint_between(a, b, mid, threshold, constraint_collection)

    for band_index in range(len(bands) - 1):
        inner = bands[band_index]
        outer = bands[band_index + 1]
        for i in range(spoke_count):
            a = inner[i]
            b = outer[i]
            mid = a.location.lerp(b.location, 0.5)
            threshold = 0.5 * (constraint_threshold(a["local_x"], a["local_z"]) + constraint_threshold(b["local_x"], b["local_z"]))
            add_constraint_between(a, b, mid, threshold, constraint_collection)

    outer_band = bands[-1]
    for shard in outer_band:
        frame_obj = frame_target_for_shard(shard, frame_parts)
        anchor_location = shard.location.lerp(frame_obj.location, 0.28)
        threshold = 26.0 + math.sqrt(shard["local_x"] ** 2 + shard["local_z"] ** 2) * 22.0
        add_constraint_between(shard, frame_obj, anchor_location, threshold, constraint_collection)


