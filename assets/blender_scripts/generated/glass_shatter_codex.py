def build_micro_chips(glass_mat, shard_collection):
    chip_objects = []
    for i in range(18):
        radius = random.uniform(0.03, 0.18)
        angle = random.uniform(0.0, math.pi * 2.0)
        center = Vector((math.cos(angle) * radius, math.sin(angle) * radius))
        scale = random.uniform(0.012, 0.028)
        tri = []
        corners = random.choice((3, 4))
        for k in range(corners):
            a = (math.pi * 2.0 * k / corners) + random.uniform(-0.4, 0.4)
            tri.append(center + Vector((math.cos(a) * scale, math.sin(a) * scale * random.uniform(0.5, 1.2))))
        chip = make_shard_object(f"MicroChip_{i:02d}", tri, WINDOW_THICKNESS * 0.7, glass_mat, shard_collection, WINDOW_CENTER.y)
        chip_objects.append(chip)
    return chip_objects


def setup_shard_rigid_bodies(shard_data):
    areas = [item[0]["area2d"] for item in shard_data]
    min_area = min(areas)
    max_area = max(areas)

    for shard, band_index, sector_index in shard_data:
        rb = add_rigid_body(shard, body_type='ACTIVE', collision_shape='CONVEX_HULL')
        if rb is None:
            continue
        area = shard["area2d"]
        if max_area > min_area:
            t = (area - min_area) / (max_area - min_area)
        else:
            t = 0.5
        rb.mass = 0.02 + (0.25 - 0.02) * t
        rb.friction = 0.25
        rb.restitution = 0.15
        rb.linear_damping = 0.02
        rb.angular_damping = 0.06
        rb.collision_margin = 0.001


