def polygon_area(points):
    area = 0.0
    for i, p in enumerate(points):
        q = points[(i + 1) % len(points)]
        area += p.x * q.y - q.x * p.y
    return abs(area) * 0.5


def polygon_centroid(points):
    return sum(points, Vector((0.0, 0.0))) / len(points)


def inset_polygon(points, inset_amount):
    center = polygon_centroid(points)
    inset_points = []
    for p in points:
        direction = p - center
        if direction.length > 1e-6:
            direction.normalize()
            inset_points.append(p - direction * inset_amount)
        else:
            inset_points.append(p.copy())
    return inset_points


def make_shard_object(name, poly2d, thickness, material, collection, y_center):
    poly = inset_polygon(poly2d, 0.0005)
    center = polygon_centroid(poly)
    local = [p - center for p in poly]
    n = len(local)
    half_t = thickness * 0.5

    verts = [(p.x, -half_t, p.y) for p in local] + [(p.x, half_t, p.y) for p in local]
    faces = [list(range(n)), list(range(2 * n - 1, n - 1, -1))]
    for i in range(n):
        j = (i + 1) % n
        faces.append([i, j, n + j, n + i])

    mesh = bpy.data.meshes.new(name + "Mesh")
    mesh.from_pydata(verts, [], faces)
    mesh.update()

    obj = bpy.data.objects.new(name, mesh)
    obj.location = (center.x, y_center, WINDOW_CENTER.z + center.y)
    collection.objects.link(obj)
    obj.data.materials.append(material)
    obj["local_x"] = center.x
    obj["local_z"] = center.y
    obj["area2d"] = polygon_area(poly)
    return obj


def rect_ray_intersection(angle, half_w, half_h):
    dx = math.cos(angle)
    dz = math.sin(angle)
    tx = half_w / abs(dx) if abs(dx) > 1e-6 else 1e9
    tz = half_h / abs(dz) if abs(dz) > 1e-6 else 1e9
    t = min(tx, tz)
    return Vector((dx * t, dz * t))


def fracture_glass(shard_collection, glass_mat):
    half_w = WINDOW_WIDTH * 0.5
    half_h = WINDOW_HEIGHT * 0.5
    spoke_count = 24
    ring_fractions = [0.12, 0.30, 0.58, 1.0]
    angle_step = (math.pi * 2.0) / spoke_count

    spoke_angles = []
    for i in range(spoke_count):
        jitter = random.uniform(-0.16, 0.16) * angle_step
        spoke_angles.append((i * angle_step) + jitter)
    spoke_angles.sort()

    rings = []
    for ring_index, fraction in enumerate(ring_fractions):
        ring = []
        for angle in spoke_angles:
            boundary = rect_ray_intersection(angle, half_w, half_h)
            tangent = Vector((-boundary.y, boundary.x))
            if tangent.length > 1e-6:
                tangent.normalize()
            radial = fraction * random.uniform(0.94, 1.05)
            if ring_index == len(ring_fractions) - 1:
                radial = 1.0
            point = boundary * radial + tangent * random.uniform(-0.018, 0.018) * (0.35 + fraction)
            point.x = max(-half_w + 0.003, min(half_w - 0.003, point.x))
            point.y = max(-half_h + 0.003, min(half_h - 0.003, point.y))
            ring.append(point)
        rings.append(ring)

    bands = []
    shard_data = []

    center_band = []
    for i in range(spoke_count):
        p1 = rings[0][i]
        p2 = rings[0][(i + 1) % spoke_count]
        shard = make_shard_object(f"GlassShard_C0_{i:02d}", [IMPACT_POINT_LOCAL.copy(), p1, p2], WINDOW_THICKNESS, glass_mat, shard_collection, WINDOW_CENTER.y)
        center_band.append(shard)
        shard_data.append((shard, 0, i))
    bands.append(center_band)

    for band_index in range(1, len(rings)):
        prev_ring = rings[band_index - 1]
        curr_ring = rings[band_index]
        band_objects = []
        for i in range(spoke_count):
            a = prev_ring[i]
            b = prev_ring[(i + 1) % spoke_count]
            c = curr_ring[(i + 1) % spoke_count]
            d = curr_ring[i]
            shard = make_shard_object(f"GlassShard_B{band_index}_{i:02d}", [a, b, c, d], WINDOW_THICKNESS, glass_mat, shard_collection, WINDOW_CENTER.y)
            band_objects.append(shard)
            shard_data.append((shard, band_index, i))
        bands.append(band_objects)

    return bands, shard_data


def add_constraint_between(obj_a, obj_b, location, threshold, constraint_collection):
    bpy.ops.object.select_all(action='DESELECT')
    bpy.ops.object.empty_add(type='PLAIN_AXES', location=location)
    empty = bpy.context.active_object
    empty.name = f"Constraint_{obj_a.name}_{obj_b.name}"
    empty.empty_display_size = 0.04
    empty.hide_render = True

    if constraint_collection not in empty.users_collection:
        constraint_collection.objects.link(empty)
        for old_col in list(empty.users_collection):
            if old_col != constraint_collection:
                old_col.objects.unlink(empty)

    bpy.ops.rigidbody.constraint_add()
    rbc = empty.rigid_body_constraint
    if rbc is not None:
        rbc.type = 'FIXED'
        rbc.object1 = obj_a
        rbc.object2 = obj_b
        rbc.use_breaking = True
        rbc.breaking_threshold = threshold
    return empty


def constraint_threshold(local_x, local_z):
    distance = math.sqrt(local_x * local_x + local_z * local_z)
    if distance < 0.4:
        return 8.0 + distance * 10.0
    return 12.0 + (distance - 0.4) * 35.0


