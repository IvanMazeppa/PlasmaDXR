def create_shard_object(name, poly_xz, thickness, material, location_offset, rotation_euler, mass):
    mesh = bpy.data.meshes.new(name + '_Mesh')
    obj = bpy.data.objects.new(name, mesh)
    collection.objects.link(obj)

    centroid = Vector((0.0, 0.0))
    for p in poly_xz:
        centroid += Vector((p[0], p[1]))
    centroid /= len(poly_xz)

    local_points = [(p[0] - centroid.x, p[1] - centroid.y) for p in poly_xz]
    verts = []
    faces = []
    count = len(local_points)

    for x, z in local_points:
        verts.append((x, -thickness * 0.5, z))
    for x, z in local_points:
        verts.append((x, thickness * 0.5, z))

    faces.append(list(range(count)))
    faces.append(list(range(count, count * 2))[::-1])
    for i in range(count):
        n = (i + 1) % count
        faces.append([i, n, count + n, count + i])

    mesh.from_pydata(verts, [], faces)
    mesh.update()

    obj.location = (centroid.x + location_offset[0], location_offset[1], centroid.y + location_offset[2])
    obj.rotation_euler = rotation_euler
    assign_material(obj, material)
    add_active_rigidbody(obj, mass=mass, shape='CONVEX_HULL')
    return obj


