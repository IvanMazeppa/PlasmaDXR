def make_shard_mesh(name, points_2d, thickness, material, center_3d, collection):
    cx = sum(p[0] for p in points_2d) / len(points_2d)
    cz = sum(p[1] for p in points_2d) / len(points_2d)
    shifted = [(p[0] - cx, p[1] - cz) for p in points_2d]

    verts_front = [(x, -thickness * 0.5, z) for x, z in shifted]
    verts_back = [(x, thickness * 0.5, z) for x, z in shifted]
    verts = verts_front + verts_back

    n = len(points_2d)
    faces = []
    faces.append(list(range(n)))
    faces.append(list(range(2 * n - 1, n - 1, -1)))

    for i in range(n):
        ni = (i + 1) % n
        faces.append([i, ni, n + ni, n + i])

    mesh = bpy.data.meshes.new(name + "_Mesh")
    mesh.from_pydata(verts, [], faces)
    mesh.update()

    obj = bpy.data.objects.new(name, mesh)
    collection.objects.link(obj)
    obj.location = (center_3d.x + cx, center_3d.y, center_3d.z + cz)
    obj.rotation_euler = (0.0, 0.0, 0.0)
    obj.data.materials.append(material)
    return obj, Vector((cx, 0.0, cz))


def build_radial_shards(center_3d, radius=0.84, thickness=0.022, sectors=18):
    random.seed(21)

    shard_collection = bpy.data.collections.new("Glass_Shards")
    scene.collection.children.link(shard_collection)

    angle_edges = [0.0]
    for i in range(1, sectors):
        base_angle = (math.tau * i) / sectors
        jitter = random.uniform(-0.055, 0.055)
        angle_edges.append(base_angle + jitter)
    angle_edges.append(math.tau)

    base_rings = [0.0, 0.14, 0.33, 0.58, radius]
    ring_fields = []
    ring_fields.append([0.0] * (sectors + 1))

    for ring_index in range(1, len(base_rings)):
        ring = []
        base_radius = base_rings[ring_index]
        for i in range(sectors):
            if ring_index == len(base_rings) - 1:
                ring.append(base_radius)
            else:
                ring.append(base_radius * random.uniform(0.90, 1.08))
        ring.append(ring[0])
        ring_fields.append(ring)

    def polar_point(r, angle):
        return (math.cos(angle) * r, math.sin(angle) * r)

    shards = []

    for i in range(sectors):
        pts = [
            (0.0, 0.0),
            polar_point(ring_fields[1][i], angle_edges[i]),
            polar_point(ring_fields[1][i + 1], angle_edges[i + 1]),
        ]
        shard_obj, centroid = make_shard_mesh(
            f"Shard_Center_{i:02d}",
            pts,
            thickness,
            glass_mat,
            center_3d,
            shard_collection,
        )
        shards.append((shard_obj, centroid, 0))

    for ring_index in range(1, len(base_rings) - 1):
        for i in range(sectors):
            pts = [
                polar_point(ring_fields[ring_index][i], angle_edges[i]),
                polar_point(ring_fields[ring_index][i + 1], angle_edges[i + 1]),
                polar_point(ring_fields[ring_index + 1][i + 1], angle_edges[i + 1]),
                polar_point(ring_fields[ring_index + 1][i], angle_edges[i]),
            ]
            shard_obj, centroid = make_shard_mesh(
                f"Shard_{ring_index:02d}_{i:02d}",
                pts,
                thickness,
                glass_mat,
                center_3d,
                shard_collection,
            )
            shards.append((shard_obj, centroid, ring_index))

    return shards


def animate_shards(shards, impact_x=0.0, impact_z=0.0):
    random.seed(84)

    for obj, centroid, ring_index in shards:
        hold_frame = 18 + (ring_index * 2) + random.randint(0, 1)
        end_frame = 29 + ring_index

        start_loc = obj.location.copy()
        start_rot = obj.rotation_euler.copy()

        obj.keyframe_insert(data_path="location", frame=1)
        obj.keyframe_insert(data_path="rotation_euler", frame=1)
        obj.keyframe_insert(data_path="location", frame=hold_frame)
        obj.keyframe_insert(data_path="rotation_euler", frame=hold_frame)

        dx = centroid.x - impact_x
        dz = centroid.z - impact_z
        length = math.sqrt((dx * dx) + (dz * dz))
        if length < 0.0001:
            dx = random.uniform(-0.25, 0.25)
            dz = 1.0
            length = math.sqrt((dx * dx) + (dz * dz))

        dx /= length
        dz /= length

        radial_push = 0.16 + (ring_index * 0.10) + random.uniform(0.03, 0.10)
        depth_push = 0.22 + ((2.5 - min(ring_index, 2.5)) * 0.12) + random.uniform(0.04, 0.16)
        vertical_lift = random.uniform(-0.06, 0.16)

        obj.location = (
            start_loc.x + (dx * radial_push),
            start_loc.y + depth_push,
            start_loc.z + (dz * radial_push) + vertical_lift,
        )
        obj.rotation_euler = (
            start_rot.x + random.uniform(-1.8, 1.8),
            start_rot.y + random.uniform(-1.4, 1.4),
            start_rot.z + random.uniform(-1.8, 1.8),
        )

        obj.keyframe_insert(data_path="location", frame=end_frame)
        obj.keyframe_insert(data_path="rotation_euler", frame=end_frame)
        set_linear_animation(obj)


