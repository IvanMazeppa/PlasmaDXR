    mat.use_nodes = True  # Deprecated in 5.0, but still works
    nt = mat.node_tree

    # Clear default nodes
    for n in list(nt.nodes):
        nt.nodes.remove(n)

    out = nt.nodes.new('ShaderNodeOutputMaterial')

    # Principled Volume
    pv = nt.nodes.new('ShaderNodeVolumePrincipled')
    pv.location = (400, 0)
    pv.inputs['Density'].default_value = 0.0
    pv.inputs['Anisotropy'].default_value = 0.2
    pv.inputs['Emission Strength'].default_value = 0.0

    # Sample Mantaflow grids
    attr_density = nt.nodes.new('ShaderNodeAttribute')
    attr_density.attribute_name = 'density'
    attr_density.location = (-700, 220)

    attr_flame = nt.nodes.new('ShaderNodeAttribute')
    attr_flame.attribute_name = 'flame'
    attr_flame.location = (-700, -80)

    # Density shaping
    den_mul = nt.nodes.new('ShaderNodeMath')
    den_mul.operation = 'MULTIPLY'
    den_mul.inputs[1].default_value = 3.0
    den_mul.location = (-300, 220)

    # Smoke tint
    smoke_color = nt.nodes.new('ShaderNodeRGB')
    smoke_color.outputs[0].default_value = (0.07, 0.07, 0.07, 1.0)
    smoke_color.location = (-300, 420)

    # Flame color ramp (black->orange->yellow)
    ramp = nt.nodes.new('ShaderNodeValToRGB')
    ramp.location = (-320, -80)
    ramp.color_ramp.elements[0].position = 0.05
    ramp.color_ramp.elements[0].color = (0.0, 0.0, 0.0, 1.0)
    ramp.color_ramp.elements[1].position = 0.35
    ramp.color_ramp.elements[1].color = (1.0, 0.25, 0.03, 1.0)
    ramp.color_ramp.elements.new(0.75)
    ramp.color_ramp.elements[2].color = (1.0, 0.85, 0.25, 1.0)

    # Flame emission strength
    flame_mul = nt.nodes.new('ShaderNodeMath')
    flame_mul.operation = 'MULTIPLY'
    flame_mul.inputs[1].default_value = 12.0
    flame_mul.location = (0, -220)

    # Mix smoke color with flame color for emission
    mix = nt.nodes.new('ShaderNodeMixRGB')
    mix.blend_type = 'MIX'
    mix.inputs['Fac'].default_value = 0.8
    mix.location = (40, -50)

    # Links
    nt.links.new(attr_density.outputs.get('Fac', attr_density.outputs[0]), den_mul.inputs[0])
    nt.links.new(den_mul.outputs[0], pv.inputs['Density'])
    nt.links.new(smoke_color.outputs[0], pv.inputs['Color'])

    nt.links.new(attr_flame.outputs.get('Fac', attr_flame.outputs[0]), ramp.inputs['Fac'])
    nt.links.new(attr_flame.outputs.get('Fac', attr_flame.outputs[0]), flame_mul.inputs[0])

    nt.links.new(ramp.outputs['Color'], mix.inputs['Color2'])
    nt.links.new(smoke_color.outputs[0], mix.inputs['Color1'])

    nt.links.new(mix.outputs['Color'], pv.inputs['Emission Color'])
    nt.links.new(flame_mul.outputs[0], pv.inputs['Emission Strength'])

    nt.links.new(pv.outputs['Volume'], out.inputs['Volume'])

    return mat


