def build_bowl_shell(name="Glass_Bowl", loc=(0.0, 0.0, 0.0), steps=96):
    """Build an open-top, thick-walled bowl shell using a spun profile."""
    mesh = bpy.data.meshes.new(name + "_M")
    obj = bpy.data.objects.new(name, mesh)
    scene.collection.objects.link(obj)
    obj.location = Vector(loc)

    bm = bmesh.new()

    # Profile in XZ plane (y=0). Open ends at rim (outer rim and inner rim).
    z0 = 0.0525  # bowl bottom height
    zR = 0.1420  # rim height

    outer = [
        (0.010, z0),
        (0.020, z0 + 0.010),
        (0.035, z0 + 0.030),
        (0.044, z0 + 0.060),
        (0.048, zR),
    ]
    inner = [
        (0.0445, zR - 0.003),
        (0.041, z0 + 0.060),
        (0.032, z0 + 0.030),
        (0.016, z0 + 0.010),
        (0.0075, z0),
    ]

    pts = []
    for r, z in outer:
        pts.append(bm.verts.new((r, 0.0, z)))
    # connect outer down to bottom then across to inner bottom and up
    pts.append(bm.verts.new((inner[-1][0], 0.0, inner[-1][1])))

    # Build the inner chain from bottom -> up to rim inner (reverse inner list)
    for r, z in reversed(inner[:-1]):
        pts.append(bm.verts.new((r, 0.0, z)))

    # Create edges along the profile
    for i in range(len(pts) - 1):
        bm.edges.new((pts[i], pts[i + 1]))

    geom = list(bm.verts) + list(bm.edges)
    bmesh.ops.spin(
        bm,
        geom=geom,
        angle=2.0 * math.pi,
        steps=steps,
        axis=(0.0, 0.0, 1.0),
        cent=(0.0, 0.0, 0.0),
    )

    bmesh.ops.remove_doubles(bm, verts=bm.verts, dist=1e-6)

    # Solidify-like rim smoothing by making normals consistent
    bmesh.ops.recalc_face_normals(bm, faces=bm.faces)

    bm.to_mesh(mesh)
    bm.free()

    return obj


