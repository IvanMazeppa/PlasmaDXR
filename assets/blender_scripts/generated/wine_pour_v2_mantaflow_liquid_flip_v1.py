def look_at(obj, target, up=Vector((0.0, 0.0, 1.0))):
    """Orient obj so its -Z looks at target."""
    loc = obj.location
    forward = (Vector(target) - loc).normalized()
    right = forward.cross(up).normalized()
    true_up = right.cross(forward).normalized()

    # Camera looks down -Z, with Y up
    rot = Matrix((
        right,
        true_up,
        -forward,
    )).transposed().to_4x4()
    obj.matrix_world = Matrix.Translation(loc) @ rot


