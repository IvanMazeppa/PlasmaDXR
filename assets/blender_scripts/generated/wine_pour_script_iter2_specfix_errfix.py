def create_glass(col):
    """Lathe-like glass with a simple profile. Robust and non-operator."""
    bm = bmesh.new()

    profile = [
        (0.0, 0.0),
        (0.030, 0.0),
        (0.036, 0.008),
        (0.030, 0.014),
        (0.012, 0.020),
        (0.012, 0.105),
        (0.020, 0.120),
        (0.034, 0.140),
        (0.044, 0.180),
        (0.048, 0.206),
        (0.046, GLASS_HEIGHT),
    ]

    verts = [bm.verts.new((x, 0.0, z)) for x, z in profile]
    bm.verts.ensure_lookup_table()

    edges = []
    for i in range(len(verts) - 1):
        edges.append(bm.edges.new((verts[i], verts[i + 1])))

    # Spin to create surface
    bmesh.ops.spin(
        bm,
        geom=verts + edges,
        cent=(0.0, 0.0, 0.0),
        axis=(0.0, 0.0, 1.0),
        steps=96,
        angle=math.radians(360.0),
    )

    # Weld seam
    bmesh.ops.remove_doubles(bm, verts=bm.verts, dist=1e-5)

    # IMPORTANT: Do not attempt to fill all holes blindly (can fail on some meshes).
    # The solidify modifier will create thickness, and the collider can work with open rim.
    bmesh.ops.recalc_face_normals(bm, faces=bm.faces)

    glass = new_mesh_object("WineGlass", bm, col)
    glass.location = (0.0, 0.0, TABLE_TOP_Z)

    solid = glass.modifiers.new("Solidify", type='SOLIDIFY')
    solid.thickness = 0.002
    solid.offset = -1.0

    subd = glass.modifiers.new("Subsurf", type='SUBSURF')
    subd.levels = 2
    subd.render_levels = 2

    sm = glass.modifiers.new("Smooth", type='SMOOTH')
    sm.iterations = 2
    sm.factor = 0.5

    return glass


