def create_lathed_glass(name="WineGlass", location=(0, 0, 0.0), segments=72):
    import bmesh

    mesh = bpy.data.meshes.new(name + "_Mesh")
    obj = bpy.data.objects.new(name, mesh)
    bpy.context.collection.objects.link(obj)

    # Profile points (radius, z) in meters.
    # Built to read as a crystal wine glass in close-up.
    profile = [
        (0.0, 0.000),
        (0.060, 0.000),
        (0.058, 0.008),
        (0.050, 0.012),
        (0.012, 0.095),
        (0.010, 0.135),
        (0.030, 0.150),
        (0.052, 0.170),
        (0.055, 0.205),
        (0.050, 0.238),
        (0.048, 0.245),  # rim
    ]

    bm = bmesh.new()
    rings = []

    for r, z in profile:
        if r <= 1e-6:
            rings.append([bm.verts.new((0.0, 0.0, z))])
        else:
            ring = []
            for s in range(segments):
                a = (2.0 * math.pi * s) / segments
                ring.append(bm.verts.new((r * math.cos(a), r * math.sin(a), z)))
            rings.append(ring)

    bm.verts.ensure_lookup_table()

    # Create faces between rings
    for i in range(len(rings) - 1):
        ra = rings[i]
        rb = rings[i + 1]

        if len(ra) == 1 and len(rb) > 1:
            c = ra[0]
            for s in range(segments):
                v0 = rb[s]
                v1 = rb[(s + 1) % segments]
                bm.faces.new((c, v0, v1))
        elif len(ra) > 1 and len(rb) == 1:
            c = rb[0]
            for s in range(segments):
                v0 = ra[s]
                v1 = ra[(s + 1) % segments]
                bm.faces.new((v1, v0, c))
        else:
            for s in range(segments):
                a0 = ra[s]
                a1 = ra[(s + 1) % segments]
                b1 = rb[(s + 1) % segments]
                b0 = rb[s]
                bm.faces.new((a0, a1, b1, b0))

    bm.normal_update()
    bm.to_mesh(mesh)
    bm.free()

    obj.location = Vector(location)

    # Smooth shading for crystal
    try:
        for p in mesh.polygons:
            p.use_smooth = True
    except Exception:
        pass

    # Modifiers: thickness + smoothing
    solid = obj.modifiers.new(name="Solidify", type='SOLIDIFY')
    if solid is not None:
        try:
            solid.thickness = 0.003
            solid.offset = 1.0
        except Exception:
            pass

    subd = obj.modifiers.new(name="Subsurf", type='SUBSURF')
    if subd is not None:
        try:
            subd.levels = 3
            subd.render_levels = 3
        except Exception:
            pass

    # A tiny bevel helps rim read as real glass (guarded)
    bev = obj.modifiers.new(name="Bevel", type='BEVEL')
    if bev is not None:
        try:
            bev.width = 0.0012
            bev.segments = 2
            bev.limit_method = 'ANGLE'
        except Exception:
            pass

    return obj


