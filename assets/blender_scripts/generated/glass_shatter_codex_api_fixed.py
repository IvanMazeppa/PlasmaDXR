for i, shard_a in enumerate(shards_sorted):
    pos_a = Vector((shard_a.location.x, shard_a.location.z))
    neighbor_candidates = []
    for j, shard_b in enumerate(shards_sorted):
        if j <= i:
            continue
        pos_b = Vector((shard_b.location.x, shard_b.location.z))
        dist = (pos_a - pos_b).length
        if dist < neighbor_radius:
            neighbor_candidates.append((dist, shard_b))
    neighbor_candidates.sort(key=lambda item: item[0])

    for dist, shard_b in neighbor_candidates[:max_neighbors]:
        pair_key = tuple(sorted((shard_a.name, shard_b.name)))
        if pair_key in pair_keys:
            continue
        pair_keys.add(pair_key)
        midpoint = (shard_a.location + shard_b.location) * 0.5
        dist_impact = (Vector((midpoint.x, midpoint.z)) - impact_xz).length
        threshold = 8.0 + dist_impact * 35.0
        empty = create_constraint_empty(
            f"Constraint_{shard_a.name}_{shard_b.name}",
            midpoint,
            shard_a,
            shard_b,
            threshold,
        )
        constraint_collection.objects.link(empty)
        bpy.context.scene.collection.objects.unlink(empty)
        constraint_objects.append(empty)

