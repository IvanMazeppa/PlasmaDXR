def make_active_rigidbody(obj, mass, collision_shape='CONVEX_HULL', friction=0.4, restitution=0.25,
                          linear_damping=0.04, angular_damping=0.1, margin=0.001):
    bpy.ops.object.select_all(action='DESELECT')
    obj.select_set(True)
    bpy.context.view_layer.objects.active = obj
    bpy.ops.rigidbody.object_add(type='ACTIVE')
    rb = obj.rigid_body
    rb.mass = mass
    rb.collision_shape = collision_shape
    rb.friction = friction
    rb.restitution = restitution
    rb.linear_damping = linear_damping
    rb.angular_damping = angular_damping
    rb.use_margin = True
    rb.collision_margin = margin
    rb.use_deactivation = False
    return rb


