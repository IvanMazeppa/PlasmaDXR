def add_volume_material(domain):
    """Add Principled Volume shader for fire/smoke visualization."""
    mat = bpy.data.materials.new(name="FireSmokeMaterial")
    mat.use_nodes = True
    nodes = mat.node_tree.nodes
    links = mat.node_tree.links

    nodes.clear()

    volume = nodes.new('ShaderNodeVolumePrincipled')
    volume.location = (0, 0)
    # SUN-SPECIFIC: Lower intensity to avoid white blow-out, rich orange-red
    volume.inputs['Color'].default_value = (1.0, 0.35, 0.08, 1.0)  # Deep orange-red
    volume.inputs['Density'].default_value = 15.0   # Higher density for visible structure
    volume.inputs['Anisotropy'].default_value = 0.3  # Moderate scattering
    volume.inputs['Blackbody Intensity'].default_value = 1.5  # LOW to avoid blow-out
    volume.inputs['Temperature'].default_value = 1800.0  # Orange-red temperature

    output = nodes.new('ShaderNodeOutputMaterial')
    output.location = (300, 0)

    links.new(volume.outputs['Volume'], output.inputs['Volume'])

    domain.data.materials.append(mat)
    print("[script] Volumetric material applied (high density + emission)")


