def setup_physics(scene_data):
    domain_obj = scene_data['domain']
    domain_mod = domain_obj.modifiers.new(name='Fluid', type='FLUID')
    if domain_mod is None:
        print(f"WARNING: Could not add Fluid modifier to {domain_obj.name}")
    else:
        domain_mod.fluid_type = 'DOMAIN'
        domain_settings = domain_mod.domain_settings
        domain_settings.domain_type = 'GAS'
        domain_settings.resolution_max = 96
        domain_settings.cache_type = 'ALL'
        domain_settings.cache_directory = CACHE_DIR
        domain_settings.cache_frame_start = 1
        domain_settings.cache_frame_end = bpy.context.scene.frame_end
        domain_settings.use_noise = True
        domain_settings.noise_scale = 2

    setup_volume_material(domain_obj, effect_type="BOTH")

    for collider in scene_data['colliders']:
        effector_mod = collider.modifiers.new(name='Fluid', type='FLUID')
        if effector_mod is None:
            print(f"WARNING: Could not add Fluid modifier to {collider.name}")
        else:
            effector_mod.fluid_type = 'EFFECTOR'

    for emitter in scene_data['emitters']:
        flow_mod = emitter.modifiers.new(name='Fluid', type='FLUID')
