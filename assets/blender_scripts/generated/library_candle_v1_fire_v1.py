def make_domain_volume_material(name="CandleFireVolume"):
    """Volume shader for Mantaflow GAS domain.

    Uses Volume Info outputs (Density/Flame/Temperature) as described in manual.
    """
    mat = bpy.data.materials.new(name)
    mat.use_nodes = True  # Deprecated in 5.0, but still works
    nt = mat.node_tree
    nodes = nt.nodes
    links = nt.links
    nodes.clear()

    out = nodes.new('ShaderNodeOutputMaterial')
    pv = nodes.new('ShaderNodeVolumePrincipled')
    volinfo = nodes.new('ShaderNodeVolumeInfo')

    # Smoke density (kept low for clean-burning candle)
    dens_mul = nodes.new('ShaderNodeMath')
    dens_mul.operation = 'MULTIPLY'
    dens_mul.inputs[1].default_value = 3.0

    # Flame-driven emission
    flame_mul = nodes.new('ShaderNodeMath')
    flame_mul.operation = 'MULTIPLY'
    flame_mul.inputs[1].default_value = 18.0

    # Temperature scaling (Volume Info temperature is 0..1 => 0..1000K)
    temp_mul = nodes.new('ShaderNodeMath')
    temp_mul.operation = 'MULTIPLY'
    temp_mul.inputs[1].default_value = 2200.0

    # Link grids
    if volinfo.outputs.get('Density'):
        links.new(volinfo.outputs['Density'], dens_mul.inputs[0])
    if volinfo.outputs.get('Flame'):
        links.new(volinfo.outputs['Flame'], flame_mul.inputs[0])
        # Principled Volume blackbody intensity for physically-colored flame
        if pv.inputs.get('Blackbody Intensity'):
            links.new(volinfo.outputs['Flame'], pv.inputs['Blackbody Intensity'])

    if volinfo.outputs.get('Temperature'):
        links.new(volinfo.outputs['Temperature'], temp_mul.inputs[0])
        if pv.inputs.get('Temperature'):
            links.new(temp_mul.outputs['Value'], pv.inputs['Temperature'])

    if pv.inputs.get('Density'):
        links.new(dens_mul.outputs['Value'], pv.inputs['Density'])

    # Warm smoke tint (very subtle)
    if pv.inputs.get('Color'):
        pv.inputs['Color'].default_value = (0.20, 0.18, 0.16, 1.0)

    # Emission boost so flame reads as the primary light source in close-up
    emiss_sock = pv.inputs.get('Emission Strength')
    if emiss_sock:
        links.new(flame_mul.outputs['Value'], emiss_sock)

    # Slightly forward-scattering for cinematic glow
    if pv.inputs.get('Anisotropy'):
        pv.inputs['Anisotropy'].default_value = 0.25

    links.new(pv.outputs['Volume'], out.inputs['Volume'])
    return mat


