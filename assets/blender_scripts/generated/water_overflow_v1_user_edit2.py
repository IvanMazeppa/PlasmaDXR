def render_frames(output_dir_rel="//renders_water_overflow_v1"):
    """Render representative frames for quality evaluation."""
    scene = bpy.context.scene
    abs_out_dir = bpy.path.abspath(output_dir_rel)
    safe_mkdir(abs_out_dir)

    # Representative frames: early (skip frame 1 which may be empty), middle, final
    frames = [
        min(scene.frame_start + 5, scene.frame_end),  # Early frame (frame 6)
        (scene.frame_start + scene.frame_end) // 2,   # Middle frame
        scene.frame_end                                # Final frame
    ]
    print(f"[Render] Rendering representative frames: {frames}")

    for f in frames:
        scene.frame_set(f)
        scene.render.filepath = os.path.join(abs_out_dir, f"water_overflow_v1_{f:04d}.png")
        print(f"[Render] Rendering frame {f}...")
        bpy.ops.render.render(write_still=True)


