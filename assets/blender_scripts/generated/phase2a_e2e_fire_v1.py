def look_at(obj, target, up=Vector((0.0, 0.0, 1.0))):
    """Orient obj so its -Z axis points at target (camera convention)."""
    loc = obj.location
    direction = (Vector(target) - Vector(loc)).normalized()
    # Camera looks down -Z, so align -Z with direction
    z = -direction
    x = up.cross(z).normalized()
    y = z.cross(x).normalized()
    obj.matrix_world = (Vector((x.x, y.x, z.x, 0.0)),
                        Vector((x.y, y.y, z.y, 0.0)),
                        Vector((x.z, y.z, z.z, 0.0)),
                        Vector((loc.x, loc.y, loc.z, 1.0)))


