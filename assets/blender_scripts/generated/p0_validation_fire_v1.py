def bake_fluid_if_possible(domain_obj):
    """Bake fluid cache if Blender exposes bake operators.

    If bake operators are missing/unavailable, we step frames to populate replay cache.
    """
    scene = bpy.context.scene

    # Ensure depsgraph updated
    bpy.context.view_layer.update()

    # Activate domain
    bpy.ops.object.select_all(action='DESELECT')
    domain_obj.select_set(True)
    bpy.context.view_layer.objects.active = domain_obj
    scene.frame_set(scene.frame_start)

    # Try bake ops (only if present)
    fluid_ops = getattr(bpy.ops, 'fluid', None)
    bake_attempted = False

    def try_op(op_name):
        nonlocal bake_attempted
        if fluid_ops is None:
            return False
        if not hasattr(fluid_ops, op_name):
            return False
        op = getattr(fluid_ops, op_name)
        try:
            if hasattr(op, 'poll') and not op.poll():
                return False
        except Exception:
            # If poll crashes, still try within override
            pass
        try:
            with bpy.context.temp_override(active_object=domain_obj, object=domain_obj):
                print(f"INFO: Running bpy.ops.fluid.{op_name}()")
                op()
            bake_attempted = True
            return True
        except Exception as e:
            print(f"WARN: Bake op {op_name} failed: {e}")
            return False

    # Prefer a full bake, else data+noise
    if try_op('bake_all'):
        return True
    if try_op('bake_data'):
        try_op('bake_noise')
        return True

    # Fallback: step frames to force evaluation
    print("WARN: No fluid bake ops available (or poll failed). Stepping frames to evaluate simulation.")
    for f in [min(scene.frame_start + 5, scene.frame_end), (scene.frame_start + scene.frame_end) // 2, scene.frame_end]:  # Representative frames
        scene.frame_set(f)
    return bake_attempted


