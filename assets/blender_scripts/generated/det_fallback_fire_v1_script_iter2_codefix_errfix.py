def scan_rna_properties(obj, include=(), prefer=()):
    """Return candidate RNA property identifiers containing all 'include' substrings."""
    names = []
    rna = getattr(obj, "rna_type", None)
    props = getattr(rna, "properties", None)
    if props is None:
        return names

    for p in props:
        ident = getattr(p, "identifier", "")
        low = ident.lower()
        if all(k in low for k in include):
            names.append(ident)

    def score(n):
        low = n.lower()
        return sum(1 for k in prefer if k in low)

    names.sort(key=score, reverse=True)
    return names


