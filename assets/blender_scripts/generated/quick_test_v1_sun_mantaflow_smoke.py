def create_uv_sphere(name: str, radius: float, segments=64, rings=32, location=(0, 0, 0)):
    mesh = bpy.data.meshes.new(name + "_mesh")

    # Build a UV sphere without bpy.ops
    # (Simple lat-long sphere)
    verts = []
    faces = []

    for r in range(rings + 1):
        v = r / rings
        phi = math.pi * v
        for s in range(segments):
            u = s / segments
            theta = 2.0 * math.pi * u
            x = radius * math.sin(phi) * math.cos(theta)
            y = radius * math.sin(phi) * math.sin(theta)
            z = radius * math.cos(phi)
            verts.append((x, y, z))

    def vid(r, s):
        return r * segments + (s % segments)

    for r in range(rings):
        for s in range(segments):
            a = vid(r, s)
            b = vid(r, s + 1)
            c = vid(r + 1, s + 1)
            d = vid(r + 1, s)
            if r != 0:
                faces.append((a, b, d))
            if r != rings - 1:
                faces.append((b, c, d))

    mesh.from_pydata(verts, [], faces)
    mesh.update()

    obj = new_object(name, mesh, location=location)
    return obj


