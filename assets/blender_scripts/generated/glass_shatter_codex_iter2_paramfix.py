def focused_edges(vmin, vmax, intervals, power=1.8):
    values = []
    for i in range(intervals + 1):
        t = i / intervals
        s = (2.0 * t) - 1.0
        if s < 0.0:
            focused = -((abs(s)) ** power)
        else:
            focused = (abs(s)) ** power
        v = ((focused + 1.0) * 0.5 * (vmax - vmin)) + vmin
        values.append(v)
    values[0] = vmin
    values[-1] = vmax
    return values


def build_window_shards(glass_material, shard_collection):
    y_edges = focused_edges((-WINDOW_WIDTH * 0.5) + FRAME_INSET, (WINDOW_WIDTH * 0.5) - FRAME_INSET, 25, power=1.85)
    z_local_edges = focused_edges((-WINDOW_HEIGHT * 0.5) + FRAME_INSET, (WINDOW_HEIGHT * 0.5) - FRAME_INSET, 22, power=1.8)

    grid = {}
    for i, y in enumerate(y_edges):
        for j, z_local in enumerate(z_local_edges):
            jy = 0.0
            jz = 0.0
            if 0 < i < len(y_edges) - 1 and 0 < j < len(z_local_edges) - 1:
                span_y = min(y_edges[i] - y_edges[i - 1], y_edges[i + 1] - y_edges[i])
                span_z = min(z_local_edges[j] - z_local_edges[j - 1], z_local_edges[j + 1] - z_local_edges[j])
                radial = math.sqrt((y * 1.1) ** 2 + (z_local * 1.2) ** 2)
                jitter_factor = 0.32 if radial < 0.33 else 0.18
                jy = random.uniform(-0.5, 0.5) * span_y * jitter_factor
                jz = random.uniform(-0.5, 0.5) * span_z * jitter_factor
            grid[(i, j)] = (y + jy, WINDOW_CENTER.z + z_local + jz)

    shards = []
    index = 0
    for i in range(len(y_edges) - 1):
        for j in range(len(z_local_edges) - 1):
            p00 = grid[(i, j)]
            p10 = grid[(i + 1, j)]
            p11 = grid[(i + 1, j + 1)]
            p01 = grid[(i, j + 1)]
            cell = [p00, p10, p11, p01]

            cy, cz = polygon_centroid_average(cell)
            radius = math.sqrt((cy - IMPACT_POINT.y) ** 2 + (cz - IMPACT_POINT.z) ** 2)
            if radius < 0.09:
                continue

            polygons = []
            if radius < 0.32:
                if ((i + j) % 2) == 0:
                    polygons.append([p00, p10, p11])
                    polygons.append([p00, p11, p01])
                else:
                    polygons.append([p00, p10, p01])
                    polygons.append([p10, p11, p01])
            else:
                polygons.append(cell)

            for poly in polygons:
                area = polygon_area(poly)
                if area < 0.00008:
                    continue
                shard_obj = create_shard_object(f"GlassShard_{index:04d}", poly, GLASS_THICKNESS, glass_material, shard_collection)
                shards.append((shard_obj, area, radius))
                index += 1

    print(f"Created {len(shards)} glass shards")
    return shards


