def polygon_area(points):
    area = 0.0
    for i in range(len(points)):
        y1, z1 = points[i]
        y2, z2 = points[(i + 1) % len(points)]
        area += y1 * z2 - y2 * z1
    return abs(area) * 0.5


def polygon_centroid_average(points):
    y = sum(p[0] for p in points) / len(points)
    z = sum(p[1] for p in points) / len(points)
    return y, z


def create_shard_object(name, polygon_yz, thickness, material, collection):
    cy, cz = polygon_centroid_average(polygon_yz)
    local_points = [(y - cy, z - cz) for y, z in polygon_yz]
    count = len(local_points)

    verts = []
    for y, z in local_points:
        verts.append((-thickness * 0.5, y, z))
    for y, z in local_points:
        verts.append((thickness * 0.5, y, z))

    faces = []
    faces.append(list(range(count)))
    faces.append(list(range((2 * count) - 1, count - 1, -1)))
    for i in range(count):
        i2 = (i + 1) % count
        faces.append([i, i2, count + i2, count + i])

    mesh = bpy.data.meshes.new(f"{name}_Mesh")
    mesh.from_pydata(verts, [], faces)
    mesh.update()

    obj = bpy.data.objects.new(name, mesh)
    obj.location = (0.0, cy, cz)
    collection.objects.link(obj)
    assign_material(obj, material)
    return obj


