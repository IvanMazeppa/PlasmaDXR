# ------------------------------------------------------------
# Constraint network between adjacent shards
# ------------------------------------------------------------
impact_point = Vector((0.18, 0.0, 1.62))
constraint_pairs = set()
max_neighbors = 4
connect_distance = 0.28

for shard in shards:
    other_distances = []
    shard_center = shard.matrix_world.translation.copy()
    for other in shards:
        if other == shard:
            continue
        other_center = other.matrix_world.translation.copy()
        distance = (other_center - shard_center).length
        other_distances.append((distance, other))
    other_distances.sort(key=lambda item: item[0])

    connected = 0
    for distance, other in other_distances:
        if distance > connect_distance:
            continue
        pair = tuple(sorted((shard.name, other.name)))
        if pair in constraint_pairs:
            continue

        midpoint = (shard.matrix_world.translation + other.matrix_world.translation) * 0.5
        bpy.ops.object.empty_add(type='PLAIN_AXES', location=midpoint)
        empty = bpy.context.object
        empty.name = f"Constraint_{len(constraint_pairs):03d}"
        bpy.ops.rigidbody.constraint_add()
        rbc = empty.rigid_body_constraint
        rbc.type = 'FIXED'
        rbc.object1 = shard
        rbc.object2 = other
        rbc.use_breaking = True

        local_factor = 1.0
        dist_to_impact = (midpoint - impact_point).length
        if dist_to_impact < 0.35:
            local_factor = 0.65
        elif dist_to_impact < 0.60:
            local_factor = 0.85

        rbc.breaking_threshold = 5.0 * random.uniform(0.8, 1.2) * local_factor
        try:
            rbc.disable_collisions = True
        except Exception:
            pass

        constraint_pairs.add(pair)
        connected += 1
        if connected >= max_neighbors:
            break

