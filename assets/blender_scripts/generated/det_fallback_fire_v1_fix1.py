def setup_fire_volume_material(domain_obj):
    mat = bpy.data.materials.new(name="FireDomainVolume")
    mat.use_nodes = True
    nt = mat.node_tree
    nodes = nt.nodes
    links = nt.links
    nodes.clear()

    out = nodes.new('ShaderNodeOutputMaterial')
    vol = nodes.new('ShaderNodeVolumePrincipled')

    # Density = density_attr * 0.3  (very low smoke)
    attr_density = nodes.new('ShaderNodeAttribute')
    attr_density.attribute_name = 'density'
    attr_density.attribute_type = 'GEOMETRY'

    dens_mul = nodes.new('ShaderNodeMath')
    dens_mul.operation = 'MULTIPLY'
    dens_mul.inputs[1].default_value = 0.3
    links.new(attr_density.outputs.get('Fac'), dens_mul.inputs[0])

    # Flame driving emission strength
    attr_flame = nodes.new('ShaderNodeAttribute')
    attr_flame.attribute_name = 'flame'
    attr_flame.attribute_type = 'GEOMETRY'

    strength_mul = nodes.new('ShaderNodeMath')
    strength_mul.operation = 'MULTIPLY'
    strength_mul.inputs[1].default_value = 40.0
    links.new(attr_flame.outputs.get('Fac'), strength_mul.inputs[0])

    # Flame driving emission color ramp (blue core -> cyan -> yellow tips)
    ramp = nodes.new('ShaderNodeValToRGB')
    elems = ramp.color_ramp.elements
    while len(elems) > 1:
        elems.remove(elems[0])
    e0 = elems[0]
    e0.position = 0.0
    e0.color = (0.05, 0.15, 1.0, 1.0)  # deep blue
    e1 = elems.new(0.55)
    e1.color = (0.2, 0.8, 1.0, 1.0)    # cyan
    e2 = elems.new(1.0)
    e2.color = (1.0, 0.85, 0.2, 1.0)   # warm yellow

    links.new(attr_flame.outputs.get('Fac'), ramp.inputs.get('Fac'))

    # Hook up principled volume
    dens_in = vol.inputs.get('Density')
    if dens_in:
        links.new(dens_mul.outputs.get('Value'), dens_in)

    emis_col_in = vol.inputs.get('Emission Color') or vol.inputs.get('Emission')
    if emis_col_in:
        links.new(ramp.outputs.get('Color'), emis_col_in)

    emis_str_in = vol.inputs.get('Emission Strength')
    if emis_str_in:
        links.new(strength_mul.outputs.get('Value'), emis_str_in)

    # Keep scattering low (clean burn)
    col_in = vol.inputs.get('Color')
    if col_in:
        col_in.default_value = (0.02, 0.03, 0.08, 1.0)

    links.new(vol.outputs.get('Volume'), out.inputs.get('Volume'))

    if domain_obj.data.materials:
        domain_obj.data.materials[0] = mat
    else:
        domain_obj.data.materials.append(mat)


