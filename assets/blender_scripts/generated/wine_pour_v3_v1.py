def look_at(obj, target, up=Vector((0, 0, 1))):
    """Point -Z of obj toward target."""
    loc = obj.location
    direction = (Vector(target) - Vector(loc)).normalized()
    # Camera looks down -Z, so align -Z to direction
    z_axis = -direction
    x_axis = up.cross(z_axis).normalized()
    if x_axis.length < 1e-6:
        x_axis = Vector((1, 0, 0))
    y_axis = z_axis.cross(x_axis).normalized()
    obj.matrix_world = (
        Matrix((
            (x_axis.x, y_axis.x, z_axis.x, loc.x),
            (x_axis.y, y_axis.y, z_axis.y, loc.y),
            (x_axis.z, y_axis.z, z_axis.z, loc.z),
            (0.0,      0.0,      0.0,      1.0)
        ))
    )


