def add_effector(obj, surface_distance=0.0):
    effector_mod = obj.modifiers.new(name='FluidEffector', type='FLUID')
    if effector_mod is None:
        print(f'WARNING: Could not add Fluid modifier to {obj.name}')
        return
    effector_mod.fluid_type = 'EFFECTOR'
    settings = effector_mod.effector_settings
    settings.effector_group = 'COLLISION'
    settings.fractions_distance = surface_distance
    # REMOVED: subframes not valid on FluidDomainSettings — settings.subframes = 1
    settings.use_speed_vectors = True


