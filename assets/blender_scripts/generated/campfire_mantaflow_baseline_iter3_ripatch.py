def setup_camera(objects):
    scene = bpy.context.scene
    bpy.ops.object.camera_add(location=(0.0, -1.2, 0.28))
    camera = bpy.context.active_object
    camera.name = "Camera"
    camera.data.lens = 50.0
    camera.data.clip_start = 0.1
    camera.data.clip_end = 30.0
    point_camera_at(camera, (0.0, 0.0, 0.18))
    scene.camera = camera

    try:
        camera.data.dof.use_dof = True
        camera.data.dof.focus_object = objects['ember_bed']
        camera.data.dof.aperture_fstop = 4.0
    except Exception as exc:
        print(f"DOF warning: {exc}")

    return camera


def bake_and_render(*args, **kwargs):
    scene = bpy.context.scene

    domain_obj = None
    for obj in bpy.data.objects:
        for mod in obj.modifiers:
            if mod.type == 'FLUID' and mod.fluid_type == 'DOMAIN':
                domain_obj = obj
                break
        if domain_obj is not None:
            break

    bpy.context.view_layer.update()

    if domain_obj is not None:
        bpy.ops.object.select_all(action='DESELECT')
        domain_obj.select_set(True)
        bpy.context.view_layer.objects.active = domain_obj
        with bpy.context.temp_override(active_object=domain_obj, object=domain_obj):
            bpy.ops.fluid.bake_all()

    render_path = globals().get('RENDER_PATH', scene.render.filepath)
    blend_path = globals().get('BLEND_PATH', '')

    scene.render.filepath = render_path
    bpy.ops.render.render(write_still=True)

    if blend_path:
        bpy.ops.wm.save_as_mainfile(filepath=blend_path)

    return domain_obj



def main():
    setup_scene()
    objects = create_geometry()
    setup_materials(objects)
    setup_physics(objects)
    setup_lighting(objects)
    setup_camera(objects)
    bake_and_render(objects['domain'])


if __name__ == "__main__":
    main()
