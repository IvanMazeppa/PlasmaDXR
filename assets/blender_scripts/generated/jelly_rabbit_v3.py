def bake_physics_explicitly(rabbit):
    """
    Force a bake using context overrides.
    This is required for headless mode where 'context' is missing.
    """
    print("[script] Starting Explicit Bake...")
    
    # Ensure directory exists
    Path(Config.OUTPUT_DIR).mkdir(parents=True, exist_ok=True)
    
    # Save file FIRST - caching often requires the blend file to exist on disk
    # to know where to save the cache folder (//blendcache_name)
    blend_path = Path(Config.OUTPUT_DIR) / "jelly_rabbit_v3_prebake.blend"
    bpy.ops.wm.save_as_mainfile(filepath=str(blend_path))
    
    # Deselect all, select rabbit
    bpy.ops.object.select_all(action='DESELECT')
    rabbit.select_set(True)
    bpy.context.view_layer.objects.active = rabbit
    
    # Find the Soft Body modifier
    modifier = rabbit.modifiers["Softbody"]
    
    # Context override for ptcache_bake
    # We need to simulate the user hovering over the physics settings
    ctx = bpy.context.copy()
    ctx['object'] = rabbit
    ctx['active_object'] = rabbit
    
    # Force bake
    # ptcache.bake(bake=True) can be tricky. 
    # The safest way in scripts is sometimes just playing the timeline if Disk Cache is off,
    # or using bake_all with override if Disk Cache is on.
    
    try:
        # Override is robust method
        with bpy.context.temp_override(object=rabbit, active_object=rabbit):
            bpy.ops.ptcache.bake_all(bake=True)
        print("[script] Bake operator finished.")
    except Exception as e:
        print(f"[script] Bake failed: {e}")
        print("[script] Fallback: stepping timeline to force calculation...")
        
        scene = bpy.context.scene
        for frame in range(Config.FRAME_START, Config.FRAME_END + 1):
            scene.frame_set(frame)
            bpy.context.view_layer.update()

def render_loop():
    print("[script] Starting render loop...")
    scene = bpy.context.scene
    output_dir = Path(Config.OUTPUT_DIR)
    
    scene.render.engine = 'CYCLES'
    scene.cycles.samples = Config.RENDER_SAMPLES
    scene.render.resolution_x = Config.RENDER_RESOLUTION_X
    scene.render.resolution_y = Config.RENDER_RESOLUTION_Y
    scene.render.image_settings.file_format = 'PNG'
    
    rabbit = bpy.data.objects["JellyRabbit"]
    
    for frame in range(Config.FRAME_START, Config.FRAME_END + 1):
        scene.frame_set(frame)
        
        # DEBUG: Print Rabbit Location
        loc = rabbit.matrix_world.translation
        print(f"[script] Frame {frame}: Rabbit Z-Loc = {loc.z:.4f}")
        
        render_path = output_dir / f"render_{frame:04d}.png"
        scene.render.filepath = str(render_path)
        
        if Config.RENDER:
            bpy.ops.render.render(write_still=True)
            print(f"[script] Saved {render_path}")

