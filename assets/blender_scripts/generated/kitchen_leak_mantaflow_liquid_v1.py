def main():
    clear_scene()
    scene = setup_scene()

    # Create geometry
    cabinet = create_cabinet_shell()
    plumbing = create_plumbing_and_hoses()
    props = create_props()

    # Materials
    mats = build_materials()

    # Assign materials to cabinet
    for k in ('floor', 'back', 'left', 'right', 'lip'):
        assign_material(cabinet[k], mats['wood'])
    assign_material(cabinet['slab'], mats['stone'])
    assign_material(cabinet['backsplash'], mats['tile'])

    # Plumbing materials
    assign_material(plumbing['drain_vertical'], mats['pvc'])
    assign_material(plumbing['drain_ptrap'], mats['pvc'])
    assign_material(plumbing['drain_exit'], mats['pvc'])

    for v in plumbing['valves']:
        assign_material(v, mats['chrome'])

    assign_material(plumbing['burst_gap'], mats['chrome'])

    # Hoses are curves; assign material via object data if possible
    try:
        if len(plumbing['hose_hot'].data.materials) == 0:
            plumbing['hose_hot'].data.materials.append(mats['braid'])
        else:
            plumbing['hose_hot'].data.materials[0] = mats['braid']

        if len(plumbing['hose_cold'].data.materials) == 0:
            plumbing['hose_cold'].data.materials.append(mats['braid'])
        else:
            plumbing['hose_cold'].data.materials[0] = mats['braid']
    except Exception:
        pass

    # Props materials
    assign_material(props['bucket'], mats['bucket'])
    assign_material(props['sponge'], mats['sponge'])
    assign_material(props['spray_bottle'], mats['bottle'])
    assign_material(props['spray_nozzle'], mats['bottle'])
    assign_material(props['glove_a'], mats['glove'])
    assign_material(props['glove_b'], mats['glove'])

    # Domain
    domain = create_domain_object()
    add_liquid_domain(domain, mats['water'])

    # Flows
    spray_emitters = create_spray_emitters(burst_location=(-0.075, -0.235, 0.11))
    for em in spray_emitters:
        add_liquid_flow(em, flow_behavior='INFLOW', use_plane_init=True, vel=1.8)

    # Initial puddle (geometry flow)
    puddle = create_initial_puddle()
    add_liquid_flow(puddle, flow_behavior='GEOMETRY', use_plane_init=False, vel=0.0)
    puddle.hide_render = True
    puddle.display_type = 'WIRE'

    # Effectors: cabinet walls/floor/slab + props/plumbing
    for obj in (
        cabinet['floor'], cabinet['back'], cabinet['left'], cabinet['right'], cabinet['lip'], cabinet['slab'],
        plumbing['drain_vertical'], plumbing['drain_ptrap'], plumbing['drain_exit'],
        *plumbing['valves'],
        props['bucket'], props['sponge'], props['spray_bottle'], props['spray_nozzle'], props['glove_a'], props['glove_b'],
    ):
        add_effector(obj)

    # Lighting and camera
    setup_lighting()
    cam = setup_camera(plumbing['burst_gap'])

    # Make sure we're in Object mode before baking
    try:
        bpy.ops.object.mode_set(mode='OBJECT')
    except Exception:
        pass

    # Ensure domain is active/selected for fluid bake operators
    set_active(domain)

    # Bake: clear then bake all
    # NOTE: baking may take significant time at resolution 96.
    try:
        bpy.ops.fluid.free_all()
    except Exception as e:
        print("free_all failed (continuing):", e)

    try:
        bpy.ops.fluid.bake_all()
    except Exception as e:
        print("bake_all failed (continuing):", e)

    # Render target frame
    scene.frame_set(40)
    scene.render.filepath = os.path.join(RENDER_DIR, f"{ASSET_NAME}_frame_0040.png")

    # Render still
    bpy.ops.render.render(write_still=True)

    # Save blend file for inspection and rebaking
    blend_path = os.path.join(OUTPUT_DIR, f"{ASSET_NAME}.blend")
    bpy.ops.wm.save_as_mainfile(filepath=blend_path)
    print(f"Saved .blend to: {blend_path}")
    print(f"Rendered still to: {scene.render.filepath}")


if __name__ == "__main__":
    main()
