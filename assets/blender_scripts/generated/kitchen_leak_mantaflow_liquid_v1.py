def bake_sim(domain_obj):
    # Select domain as active for baking
    for obj in bpy.context.scene.objects:
        obj.select_set(False)
    domain_obj.select_set(True)
    bpy.context.view_layer.objects.active = domain_obj

    # Ensure caches are cleared, then bake
    try:
        bpy.ops.fluid.free_all()
    except Exception as e:
        print("Warning: free_all failed:", e)

    try:
        bpy.ops.fluid.bake_all()
    except Exception as e:
        print("Bake failed:", e)


def render_frame(scene, frame, output_path):
    scene.frame_current = frame
    scene.render.filepath = output_path
    bpy.ops.render.render(write_still=True)


