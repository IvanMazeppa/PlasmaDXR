def create_domain_and_flows(mats, burst_loc):
    col = bpy.context.scene.collection

    # Domain should include the cabinet interior + extra in front/below for drips
    domain_w = CAB_W + 0.10
    domain_d = CAB_D + 0.35
    domain_h = CAB_H + 0.20

    domain = create_mesh_object("Liquid_Domain", bm_box(domain_w, domain_d, domain_h), col)

    # Center domain: slightly forward (towards camera) and slightly below floor for drips
    domain.location = (0.0, -0.10, (domain_h * 0.5) - 0.06)
    domain.display_type = 'WIRE'

    assign_mat(domain, mats['water'])

    mod, dset = add_domain(domain)

    # Initial established puddle (Geometry flow) - shallow layer across cabinet floor
    puddle_depth = 0.012
    puddle = create_mesh_object("Initial_Puddle", bm_box(CAB_W - 0.01, CAB_D - 0.01, puddle_depth), col)
    puddle.location = (0.0, 0.0, puddle_depth * 0.5 + 0.001)
    set_smooth(puddle, True)
    add_flow(puddle, flow_behavior='GEOMETRY', velocity_normal=0.0, use_plane_init=False, sampling_substeps=0)

    # Burst spray emitter: a stack of thin planes to approximate a fan
    emitter_group = []
    emitter_count = 7
    fan_height = 0.08
    for i in range(emitter_count):
        t = i / max(1, emitter_count - 1)
        z_off = (t - 0.5) * fan_height
        em = create_mesh_object(f"BurstEmitter_{i:02d}", bm_plane(0.010, 0.006), col)
        em.location = (burst_loc[0], burst_loc[1], burst_loc[2] + z_off)
        # Rotate plane so its normal points to -X (toward left cabinet wall)
        em.rotation_euler = (0.0, math.radians(90), 0.0)
        set_smooth(em, True)

        # Make it an inflow with plane init and normal velocity
        add_flow(
            em,
            flow_behavior='INFLOW',
            velocity_normal=INFLOW_VELOCITY,
            use_plane_init=True,
            sampling_substeps=FLOW_SUBSTEPS,
        )
        emitter_group.append(em)

    return {
        'domain': domain,
        'dset': dset,
        'puddle': puddle,
        'emitters': emitter_group,
    }


