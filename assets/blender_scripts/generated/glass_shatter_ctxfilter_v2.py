    distances = []
    for shard_b in shards:
        if shard_a == shard_b or shard_b.type != 'MESH':
            continue
        distance = (shard_a.location - shard_b.location).length
        distances.append((distance, shard_b))
    distances.sort(key=lambda item: item[0])

    links_for_this_shard = 0
    for distance, shard_b in distances:
        if distance > neighbor_distance:
            break
        pair_key = tuple(sorted((shard_a.name, shard_b.name)))
        if pair_key in existing_pairs:
            continue
        midpoint = (shard_a.location + shard_b.location) * 0.5
        if midpoint.x < pane_min_x or midpoint.x > pane_max_x or midpoint.z < pane_min_z or midpoint.z > pane_max_z:
            continue
        impact_falloff = min((midpoint - impact_point).length / 0.85, 1.0)
        threshold = 6.0 * (0.82 + impact_falloff * 0.38) * random.uniform(0.85, 1.15)
        add_breakable_constraint(
            f'ShardLink_{constraint_count:04d}',
            midpoint,
            shard_a,
            shard_b,
            threshold,
        )
        existing_pairs.add(pair_key)
        constraint_count += 1
        links_for_this_shard += 1
        if links_for_this_shard >= max_neighbors_per_shard:
            break

