def polygon_area(poly):
    area = 0.0
    for i in range(len(poly)):
        x1, z1 = poly[i]
        x2, z2 = poly[(i + 1) % len(poly)]
        area += x1 * z2 - x2 * z1
    return abs(area) * 0.5


def polygon_centroid(poly):
    signed_area = 0.0
    cx = 0.0
    cz = 0.0
    for i in range(len(poly)):
        x1, z1 = poly[i]
        x2, z2 = poly[(i + 1) % len(poly)]
        cross = x1 * z2 - x2 * z1
        signed_area += cross
        cx += (x1 + x2) * cross
        cz += (z1 + z2) * cross
    if abs(signed_area) < 1e-8:
        avg_x = sum(p[0] for p in poly) / len(poly)
        avg_z = sum(p[1] for p in poly) / len(poly)
        return (avg_x, avg_z)
    signed_area *= 0.5
    cx /= (6.0 * signed_area)
    cz /= (6.0 * signed_area)
    return (cx, cz)


