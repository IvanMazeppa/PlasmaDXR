def polygon_area(poly):
    area = 0.0
    for i in range(len(poly)):
        x1, y1 = poly[i]
        x2, y2 = poly[(i + 1) % len(poly)]
        area += x1 * y2 - x2 * y1
    return abs(area) * 0.5


def polygon_centroid(poly):
    x = sum(p[0] for p in poly) / len(poly)
    y = sum(p[1] for p in poly) / len(poly)
    return (x, y)


def clip_polygon_halfplane(poly, mid, normal):
    if not poly:
        return []

    def signed(p):
        return (p[0] - mid[0]) * normal[0] + (p[1] - mid[1]) * normal[1]

    result = []
    prev = poly[-1]
    prev_d = signed(prev)

    for curr in poly:
        curr_d = signed(curr)
        if curr_d <= 1e-7:
            if prev_d > 1e-7:
                t = prev_d / (prev_d - curr_d)
                inter = (prev[0] + (curr[0] - prev[0]) * t, prev[1] + (curr[1] - prev[1]) * t)
                result.append(inter)
            result.append(curr)
        elif prev_d <= 1e-7:
            t = prev_d / (prev_d - curr_d)
            inter = (prev[0] + (curr[0] - prev[0]) * t, prev[1] + (curr[1] - prev[1]) * t)
            result.append(inter)
        prev = curr
        prev_d = curr_d
    return result


def generate_voronoi_points(num_points=40, impact_radius=0.25):
    points = [(0.0, 0.0)]
    while len(points) < 24:
        ang = random.random() * math.tau
        r = impact_radius * math.sqrt(random.random())
        p = (math.cos(ang) * r, math.sin(ang) * r)
        if -1.0 <= p[0] <= 1.0 and -0.75 <= p[1] <= 0.75:
            points.append(p)
    while len(points) < num_points:
        p = (random.uniform(-1.0, 1.0), random.uniform(-0.75, 0.75))
        points.append(p)
    return points


def build_voronoi_cells(points):
    rect = [(-1.0, -0.75), (1.0, -0.75), (1.0, 0.75), (-1.0, 0.75)]
    cells = []
    for i, p in enumerate(points):
        poly = rect[:]
        for j, q in enumerate(points):
            if i == j:
                continue
            mid = ((p[0] + q[0]) * 0.5, (p[1] + q[1]) * 0.5)
            normal = (q[0] - p[0], q[1] - p[1])
            poly = clip_polygon_halfplane(poly, mid, normal)
            if len(poly) < 3:
                break
        if len(poly) >= 3 and polygon_area(poly) > 0.0008:
            cells.append(poly)
    return cells


def shrink_polygon(poly, gap=0.008):
    cx, cy = polygon_centroid(poly)
    shrunk = []
    for x, y in poly:
        dx = x - cx
        dy = y - cy
        dist = math.hypot(dx, dy)
        if dist > 1e-6:
            factor = max((dist - gap) / dist, 0.72)
            shrunk.append((cx + dx * factor, cy + dy * factor))
        else:
            shrunk.append((x, y))
    return shrunk


