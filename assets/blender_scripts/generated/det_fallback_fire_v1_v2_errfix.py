    flow = bpy.context.active_object
    flow.name = "FireFlowRing"
    flow.location = (0.0, 0.0, 0.005)

    # Domain: cube enclosing ~20cm area
    bpy.ops.mesh.primitive_cube_add(size=1.0, location=(0.0, 0.0, 0.06))
    domain = bpy.context.active_object
    domain.name = "FireDomain"
    domain.scale = (0.12, 0.12, 0.10)

    # Apply scale (important for fluid)
    bpy.ops.object.select_all(action='DESELECT')
    domain.select_set(True)
    bpy.context.view_layer.objects.active = domain
    bpy.ops.object.transform_apply(location=False, rotation=False, scale=True)

    bpy.ops.object.select_all(action='DESELECT')
    flow.select_set(True)
    bpy.context.view_layer.objects.active = flow
    bpy.ops.object.transform_apply(location=False, rotation=False, scale=True)

    # Fluid domain
    dom_mod = domain.modifiers.new(name='Fluid', type='FLUID')
    # Critical ordering: set fluid_type before accessing domain_settings
    safe_set(dom_mod, 'fluid_type', 'DOMAIN')
    ds = getattr(dom_mod, 'domain_settings', None)
    if ds is None:
        raise RuntimeError("domain_settings is None; Fluid modifier may not be configured as DOMAIN")
    configure_domain_settings(ds)

    # Fluid flow emitter
    flow_mod = flow.modifiers.new(name='Fluid', type='FLUID')
    safe_set(flow_mod, 'fluid_type', 'FLOW')
    fs = getattr(flow_mod, 'flow_settings', None)
    if fs is None:
        raise RuntimeError("flow_settings is None; Fluid modifier may not be configured as FLOW")
    configure_flow_settings(fs)

    return domain, flow


