def main():
    output_dir, frame_start, frame_end = parse_cli_args()
    ensure_dir(output_dir)
    ensure_dir(os.path.join(output_dir, "cache", "fire_domain"))

    clear_scene()

    set_scene_basics(frame_start, frame_end)
    setup_cycles(output_dir)
    setup_world_dark_library()
    setup_compositor_glow()

    # Desk + environment
    create_desk_and_books()

    # Candlestick + candle
    holder = create_candlestick()
    candle, pool, wick = create_candle_and_wick(parent=holder)

    # Fluid: domain + flow
    domain = create_fluid_domain(output_dir)
    create_flow_emitter(wick)

    # Camera and lights
    focus_target = create_focus_target()
    create_camera(focus_target)
    create_lights()

    # Verified operator: preset_add (optional)
    try:
        if bpy.ops.fluid.preset_add.poll():
            bpy.ops.fluid.preset_add(name="CandleFirePreset")
    except Exception:
        pass

    # Update depsgraph after setup (best-effort)
    try:
        bpy.context.view_layer.depsgraph.update()
    except Exception:
        pass

    # Bake + render
    safe_bake(domain)
    render_sequence(output_dir, frame_start, frame_end)

    # Save .blend for inspection/rebaking
    save_blend(output_dir)


if __name__ == "__main__":
    main()
