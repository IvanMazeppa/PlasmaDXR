def safe_bake(domain_obj):
    """Best-effort bake. Uses standard bpy.ops if available.

    NOTE: Some pipelines may restrict operators; if bakes fail, the
    .blend is still saved for manual baking.
    """

    # Ensure correct selection/active
    bpy.ops.object.select_all(action='DESELECT')
    domain_obj.select_set(True)
    bpy.context.view_layer.objects.active = domain_obj

    # Attempt to free and bake
    # (Wrapped to keep script robust in headless execution.)
    try:
        if hasattr(bpy.ops, "fluid") and hasattr(bpy.ops.fluid, "free_all"):
            if bpy.ops.fluid.free_all.poll():
                pass  # Blender 5.0: free_all() removed - causes 'grids still in use'
    except Exception as e:
        print("[WARN] Could not free fluid cache:", e)

    try:
        if hasattr(bpy.ops, "fluid") and hasattr(bpy.ops.fluid, "bake_all"):
            if bpy.ops.fluid.bake_all.poll():

                # ==== API FIXER: Bake Frame Range Alignment ====
                # Mantaflow cache_frame_start/cache_frame_end default to 1-120 independent of scene.frame_end.
                # Mismatched ranges waste bake time or cause missing frames.
                _api_fixer_scene = bpy.context.scene
                for _api_fixer_obj in bpy.data.objects:
                    for _api_fixer_mod in _api_fixer_obj.modifiers:
                        if _api_fixer_mod.type == 'FLUID' and hasattr(_api_fixer_mod, 'fluid_type') and _api_fixer_mod.fluid_type == 'DOMAIN':
                            _ds = _api_fixer_mod.domain_settings
                            _ds.cache_frame_start = _api_fixer_scene.frame_start
                            _ds.cache_frame_end = _api_fixer_scene.frame_end
                            print(f"[API Fixer] Aligned bake range: {_ds.cache_frame_start}-{_ds.cache_frame_end} (scene: {_api_fixer_scene.frame_start}-{_api_fixer_scene.frame_end})")
                            break
                # ==== END API FIXER: Bake Frame Range Alignment ====


                bpy.ops.fluid.bake_all()
            else:
                print("[WARN] Fluid bake_all poll failed (context) - skipping bake")
        else:
            print("[WARN] bpy.ops.fluid.bake_all not found - skipping bake")
    except Exception as e:
        print("[WARN] Fluid bake failed:", e)


def render_sequence(output_dir: str, frame_start: int, frame_end: int):
    scene = bpy.context.scene
    render_dir = os.path.join(output_dir, "renders")
    ensure_dir(render_dir)

    for fr in [min(frame_start + 5, frame_end), (frame_start + frame_end) // 2, frame_end]:  # Representative frames
        scene.frame_set(fr)
        scene.render.filepath = os.path.join(render_dir, f"{ASSET_NAME}_{fr:04d}.png")

        # ==== API FIXER: Camera Scale Normalization ====
        # look_at() functions using matrix_world can corrupt camera scale to (0, 0, 0),
        # causing black renders. Ensure all cameras have scale (1, 1, 1).
        for _api_fixer_obj in bpy.data.objects:
            if _api_fixer_obj.type == 'CAMERA':
                if _api_fixer_obj.scale[0] == 0 or _api_fixer_obj.scale[1] == 0 or _api_fixer_obj.scale[2] == 0:
                    _api_fixer_obj.scale = (1.0, 1.0, 1.0)
                    print(f"[API Fixer] Fixed camera scale on {_api_fixer_obj.name}")
        # ==== END API FIXER: Camera Scale Normalization ====


        bpy.ops.render.render(write_still=True)


def save_blend(output_dir: str):
    blend_path = os.path.join(output_dir, f"{ASSET_NAME}.blend")
    bpy.ops.wm.save_as_mainfile(filepath=blend_path)
    print(f"Saved .blend to: {blend_path}")


