def fracture_glass_and_style_shards(glass_obj, glass_material):
    try:
        addon_utils.enable('bl_ext.blender_org.cell_fracture', default_set=True, persistent=True)
    except Exception as exc:
        print(f'Cell Fracture enable warning: {exc}')

    activate_object(glass_obj)
    bpy.ops.object.transform_apply(location=False, rotation=False, scale=True)
    bpy.context.view_layer.update()

    bpy.ops.object.add_fracture_cell_objects(
        source={'PARTICLE_OWN'},
        source_limit=60,
        source_noise=0.05,
        margin=0.0005,
        use_smooth_faces=False,
        use_data_match=True,
        use_island_split=True,
    )

    bpy.context.view_layer.update()

    shards = [obj for obj in bpy.data.objects if obj.name.startswith('GlassPane_cell')]
    if not shards:
        shards = [obj for obj in bpy.data.objects if ('_cell' in obj.name and obj.type == 'MESH')]

    impact_point = Vector((0.42, 0.0, 1.58))
    for index, shard in enumerate(shards):
        assign_material(shard, glass_material)
        offset = Vector(shard.location) - impact_point
        dist = max(offset.length, 0.001)
        direction = offset.normalized() if offset.length > 0.0001 else Vector((1.0, 0.0, 0.15))
        blast = max(0.0, 1.25 - dist)
        lateral = Vector((
            random.uniform(0.25, 1.0),
            random.uniform(-0.55, 0.55),
            random.uniform(-0.10, 0.75),
        ))
        if blast > 0.0:
            shard.location += direction * blast * 0.18 + lateral * blast * 0.12
            shard.rotation_euler = (
                random.uniform(-0.7, 0.7),
                random.uniform(-0.7, 0.7),
                random.uniform(-1.2, 1.2),
            )
            if dist < 0.22:
                shard.location.x += 0.45
                shard.location.z += random.uniform(-0.12, 0.28)
        else:
            shard.location.x += 0.03 * math.sin(index)

    return shards


def add_rigid_body(obj, body_type='ACTIVE', shape='MESH', mass=1.0, friction=0.5, restitution=0.05, kinematic=False):
    activate_object(obj)
    bpy.ops.rigidbody.object_add()
    if obj.rigid_body is not None:
        obj.rigid_body.type = body_type
        obj.rigid_body.collision_shape = shape
        obj.rigid_body.mass = mass
        obj.rigid_body.friction = friction
        obj.rigid_body.restitution = restitution
        obj.rigid_body.use_margin = True
        obj.rigid_body.collision_margin = 0.002 if shape == 'MESH' else 0.02
        obj.rigid_body.linear_damping = 0.04
        obj.rigid_body.angular_damping = 0.1
        obj.rigid_body.kinematic = kinematic


