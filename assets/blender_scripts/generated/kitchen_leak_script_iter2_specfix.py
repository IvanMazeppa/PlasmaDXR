def setup_leak_emitters():
    # Emitters are volumetric (not planes) so we do NOT rely on use_plane_init.
    # We approximate a fan spray by using multiple small "inflow" volumes.

    emitters = []

    # Base location near a burst fitting (left/back/up)
    base = Vector((-0.23, -0.18, 0.41))

    # Create multiple small volumes in an arc pattern
    for i in range(7):
        # Spread in Y/Z slightly to create fan thickness
        y_off = (i - 3) * 0.012
        z_off = math.sin((i / 6.0) * math.pi) * 0.015

        e = mesh_box(f"Inflow_{i:02d}", size=(0.03, 0.025, 0.025))
        e.location = base + Vector((0.0, y_off, z_off))
        # Rotate so one face points roughly toward +X (right wall)
        e.rotation_euler = Euler((0.0, 0.0, math.radians(0.0)))

        mod = e.modifiers.new(name='Fluid', type='FLUID')
        mod.fluid_type = 'FLOW'
        fset = mod.flow_settings  # required variable name

        # -----------------------------
        # VERIFIED fset.* assignments ONLY
        # -----------------------------
        fset.flow_type = 'LIQUID'
        fset.use_plane_init = True  # Planar liquid emitter

        fset.flow_behavior = 'INFLOW'
        fset.use_initial_velocity = True
        fset.velocity_normal = 10.0
        fset.temperature = 0.0
        fset.density = 1.0

        emitters.append(e)

    # A simple collision "shield" behind the emitters to reduce backward spray
    shield = mesh_box("Nozzle_Shield", size=(0.02, 0.10, 0.10))
    shield.location = base + Vector((-0.03, 0.0, 0.02))
    apply_material(shield, mat_metal_pipe())
    add_effector(shield)

    return emitters + [shield]


