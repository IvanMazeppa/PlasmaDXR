def create_campfire_logs(center=(0.0, 0.0, 0.0)):
    """Create a simple crossed-log arrangement using stretched cubes."""
    wood_mat = make_wood_material()

    logs = []
    for i in range(3):
        log = create_cube(f"Log_{i:02d}", size=1.0)
        log.scale = (0.10, 0.55, 0.08)
        log.location = Vector(center) + Vector((0.0, 0.0, 0.08))
        log.rotation_euler = Euler((0.0, 0.0, math.radians(60.0 * i + 20.0)), 'XYZ')
        log.data.materials.append(wood_mat)
        logs.append(log)

    # Small ring of stones (very rough, optional)
    stones = []
    for i in range(8):
        ang = (i / 8.0) * math.tau
        stone = create_cube(f"Stone_{i:02d}", size=0.12)
        stone.scale = (1.0, 0.8, 0.5)
        stone.location = Vector(center) + Vector((math.cos(ang) * 0.35, math.sin(ang) * 0.35, 0.06))
        stone.rotation_euler = Euler((0.0, 0.0, ang), 'XYZ')
        stones.append(stone)

    return logs, stones


