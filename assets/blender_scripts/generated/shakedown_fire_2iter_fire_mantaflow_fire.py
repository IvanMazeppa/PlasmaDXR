def create_uv_sphere(name: str, radius=0.15, segments=16, rings=8):
    # Simple UV sphere generator (no bpy.ops)
    verts = []
    faces = []

    for r in range(rings + 1):
        v = r / rings
        phi = math.pi * v
        for s in range(segments):
            u = s / segments
            theta = 2.0 * math.pi * u
            x = radius * math.sin(phi) * math.cos(theta)
            y = radius * math.sin(phi) * math.sin(theta)
            z = radius * math.cos(phi)
            verts.append((x, y, z))

    def vidx(r, s):
        return r * segments + (s % segments)

    for r in range(rings):
        for s in range(segments):
            a = vidx(r, s)
            b = vidx(r, s + 1)
            c = vidx(r + 1, s + 1)
            d = vidx(r + 1, s)
            if r == 0:
                faces.append((a, c, d))
            elif r == rings - 1:
                faces.append((a, b, c))
            else:
                faces.append((a, b, c, d))

    return new_mesh_object(name, verts, faces)


