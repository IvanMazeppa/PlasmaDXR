def create_lathed_glass(mat_glass, height=0.22, rim_radius=0.046, base_radius=0.040, thickness=0.0017):
    # Profile points (radius, z)
    z0 = 0.0
    z_stem_top = height * 0.45
    z_bowl_mid = height * 0.72
    z_rim = height

    profile = [
        (base_radius, z0),
        (base_radius * 0.55, z0 + height * 0.02),
        (0.010, z0 + height * 0.08),
        (0.007, z_stem_top),
        (0.018, z_stem_top + height * 0.06),
        (0.032, z_bowl_mid),
        (rim_radius * 0.92, z_rim - height * 0.03),
        (rim_radius, z_rim),
    ]

    bm = bmesh.new()
    verts = []
    for r, z in profile:
        verts.append(bm.verts.new((r, 0.0, z)))
    bm.verts.ensure_lookup_table()

    for i in range(len(verts) - 1):
        bm.edges.new((verts[i], verts[i + 1]))

    geom = verts + list(bm.edges)
    bmesh.ops.spin(
        bm,
        geom=geom,
        angle=math.radians(360.0),
        steps=96,
        axis=(0.0, 0.0, 1.0),
        cent=(0.0, 0.0, 0.0),
    )

    bmesh.ops.remove_doubles(bm, verts=bm.verts, dist=0.00001)
    bmesh.ops.holes_fill(bm, edges=[e for e in bm.edges if e.is_boundary], sides=0)

    glass = new_mesh_object("WineGlass", bm)

    # Smooth shading
    for p in glass.data.polygons:
        p.use_smooth = True

    solid = glass.modifiers.new("Solidify", 'SOLIDIFY')
    solid.thickness = thickness
    solid.offset = 1.0

    subsurf = glass.modifiers.new("Subsurf", 'SUBSURF')
    subsurf.levels = 2
    subsurf.render_levels = 2

    bev = glass.modifiers.new("Bevel", 'BEVEL')
    bev.width = thickness * 0.75
    bev.segments = 2
    bev.profile = 0.7

    glass.data.materials.append(mat_glass)
    glass.location = (0.0, 0.0, 0.0)

    return glass


