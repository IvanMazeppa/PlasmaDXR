def bake(domain_obj):
    ensure_object_mode()

    # Ensure correct context before each op
    select_active(domain_obj)
    depsgraph_update_best_effort()
    bpy.ops.fluid.free_all()

    select_active(domain_obj)
    depsgraph_update_best_effort()
    bpy.ops.fluid.bake_data()

    select_active(domain_obj)
    depsgraph_update_best_effort()
    bpy.ops.fluid.bake_particles()

    select_active(domain_obj)
    depsgraph_update_best_effort()
    bpy.ops.fluid.bake_mesh()


