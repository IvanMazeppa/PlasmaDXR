def animate_flicker(flow_obj):
    # Gentle, slow keyframed variation to flow temperature/density.
    flow_mod = None
    for m in flow_obj.modifiers:
        if m.type == 'FLUID' and getattr(m, "fluid_type", None) == 'FLOW':
            flow_mod = m
            break

    if not flow_mod:
        print("No FLOW modifier found for flicker animation.")
        return

    fset_local = flow_mod.flow_settings

    base_temp = 5.0
    base_den = 0.08

    for f in range(FRAME_START, FRAME_END + 1, 8):
        t = (f - FRAME_START) / 24.0
        temp = base_temp + 0.55 * math.sin(t * 1.1) + 0.25 * math.sin(t * 2.4 + 1.2)
        den = base_den + 0.010 * math.sin(t * 1.6 + 2.1)

        bpy.context.scene.frame_set(f)
        fset_local.temperature = float(temp)
        fset_local.density = float(max(0.02, den))
        fset_local.keyframe_insert(data_path="temperature")
        fset_local.keyframe_insert(data_path="density")


def setup_mantaflow_fire(emitter_obj):
    """Setup Mantaflow fire via verified bpy.ops.object.quick_smoke.

    After that, change ONLY verified dset.* and fset.* attributes.
    """
    ensure_dir(CACHE_DIR)

    bpy.ops.object.select_all(action='DESELECT')
    emitter_obj.select_set(True)
    bpy.context.view_layer.objects.active = emitter_obj

    # Verified op
    bpy.ops.object.quick_smoke(style='FIRE', show_flows=False)

    # Find domain object
    domain_obj = None
    for ob in bpy.context.scene.objects:
        for m in ob.modifiers:
            if m.type == 'FLUID' and getattr(m, "fluid_type", None) == 'DOMAIN':
                domain_obj = ob
                break
        if domain_obj:
            break

    if domain_obj is None:
        raise RuntimeError("Quick Smoke did not create a DOMAIN object.")

    # Domain settings variable MUST be named dset
    domain_mod = None
    for m in domain_obj.modifiers:
        if m.type == 'FLUID' and getattr(m, "fluid_type", None) == 'DOMAIN':
            domain_mod = m
            break
    if domain_mod is None:
        raise RuntimeError("DOMAIN modifier not found on domain object.")

    dset = domain_mod.domain_settings  # REQUIRED NAME

    # ----- VERIFIED dset.* assignments ONLY -----
    dset.domain_type = 'GAS'
    dset.resolution_max = int(DOMAIN_RESOLUTION)

    dset.use_noise = True
    dset.noise_scale = 2
    dset.noise_strength = 1.15
    dset.noise_time_anim = 0.010

    dset.vorticity = 0.62

    dset.use_adaptive_timesteps = True
    dset.timesteps_max = 10

    dset.use_dissolve_smoke = True
    dset.dissolve_speed = 24

    dset.cache_directory = CACHE_DIR
    dset.cache_type = 'ALL'

    dset.openvdb_cache_compress_type = 'ZIP'

    # Transform domain (free API, not a fluid attribute)
    domain_obj.name = "MantaDomain"
    domain_obj.location = (0.0, 0.0, 0.23)
    domain_obj.scale = (0.10, 0.10, 0.16)

    # Flow settings variable MUST be named fset
    flow_mod = None
    for m in emitter_obj.modifiers:
        if m.type == 'FLUID' and getattr(m, "fluid_type", None) == 'FLOW':
            flow_mod = m
            break
    if flow_mod is None:
        raise RuntimeError("FLOW modifier not found on emitter object.")

    fset = flow_mod.flow_settings  # REQUIRED NAME

    # ----- VERIFIED fset.* assignments ONLY -----
    fset.flow_type = 'FIRE'
    fset.flow_behavior = 'INFLOW'
    fset.density = 0.08
    fset.temperature = 5.0

    fset.use_initial_velocity = True
    fset.velocity_normal = 0.22

    # Noise texture for flow
    noise_tex = bpy.data.textures.new("CandleNoiseTex", type='CLOUDS')
    noise_tex.noise_scale = 0.85
    fset.noise_texture = noise_tex

    # Domain shading
    fire_mat = make_fire_volume_material()
    if domain_obj.data.materials:
        domain_obj.data.materials[0] = fire_mat
    else:
        domain_obj.data.materials.append(fire_mat)

    return domain_obj, emitter_obj


