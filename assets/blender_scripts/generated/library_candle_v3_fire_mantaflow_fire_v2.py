def try_bake(domain_obj):
    """Attempt to bake using fluid operators if they exist.
    Some installations/context combinations may require manual baking.
    """

    # Select domain (commonly required)
    bpy.ops.object.select_all(action='DESELECT')
    set_active(domain_obj)

    # Clear previous caches if operator exists
    if hasattr(bpy.ops.fluid, "free_all"):
        try:
            if bpy.ops.fluid.free_all.poll():
                bpy.ops.fluid.free_all()
        except Exception:
            pass

    # Try bake_all
    if hasattr(bpy.ops.fluid, "bake_all"):
        try:
            if bpy.ops.fluid.bake_all.poll():
                bpy.ops.fluid.bake_all()
                print("Mantaflow: bake_all started/finished.")
                return True
        except Exception as e:
            print("Mantaflow bake_all failed:", e)

    print("Mantaflow bake operator not available or wrong context.")
    print("Manual fallback: Select Domain_GAS -> Physics > Fluid > Cache > Bake.")
    return False


