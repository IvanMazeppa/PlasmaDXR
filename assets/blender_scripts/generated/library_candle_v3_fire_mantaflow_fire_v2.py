    """Create a small inflow mesh around the wick for Fire+Smoke."""

    # Emitter geometry: small cone around wick to encourage upward plume
    loc = wick_obj.location + Vector((0.0, 0.0, 0.008))
    bpy.ops.mesh.primitive_cone_add(radius1=0.0035, radius2=0.001, depth=0.02, location=loc)
    flow_obj = bpy.context.active_object
    flow_obj.name = "Flow_Fire"

    # Align a bit to mimic candle flicker bias
    flow_obj.rotation_euler = Euler((0.12, -0.05, 0.0), 'XYZ')
    bpy.ops.object.transform_apply(location=False, rotation=True, scale=False)

    # Add fluid flow modifier
    mod = flow_obj.modifiers.new(name='Fluid', type='FLUID')
    mod.fluid_type = 'FLOW'
    fset = mod.flow_settings  # REQUIRED variable name

    # -------------------------
    # fset.* assignments (ONLY verified attributes)
    # -------------------------
    fset.flow_type = 'BOTH'         # Fire + Smoke
    fset.flow_behavior = 'INFLOW'

    # Candle: clean-burning -> minimal smoke
    fset.density = 0.07

    # Increase temperature to drive buoyancy (high temperature difference)
    fset.temperature = 3.0

    fset.use_initial_velocity = True
    fset.velocity_normal = 0.35

    # Keep the emitter invisible in renders
    flow_obj.hide_render = True
    flow_obj.display_type = 'WIRE'

    # Animate subtle "breathing" by scaling the emitter slightly (slow motion feel)
    for f, s in [(1, 1.00), (30, 1.05), (60, 0.98), (90, 1.06), (120, 1.00)]:
        flow_obj.scale = (s, s, s)
        flow_obj.keyframe_insert(data_path="scale", frame=f)

    return flow_obj


