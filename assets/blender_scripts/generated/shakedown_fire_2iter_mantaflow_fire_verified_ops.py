    for obj in bpy.data.objects:
        for m in obj.modifiers:
            if m.type == 'FLUID':
                if getattr(m, "fluid_type", None) == 'DOMAIN':
                    domain_obj = obj
                elif getattr(m, "fluid_type", None) == 'FLOW':
                    flow_obj = obj

