def main():
    clean_scene()
    scene = bpy.context.scene

    # Frame range
    scene.frame_start = 1
    scene.frame_end = 120
    scene.frame_set(1)

    ensure_world(scene)
    setup_cycles_gpu(scene)

    # Render settings
    scene.render.resolution_x = 1024
    scene.render.resolution_y = 1024
    scene.render.film_transparent = False

    # Build set
    create_desk()
    create_books_background()

    holder = create_candlestick_holder()
    candle, pool, wick = create_candle()

    # Place candle on holder
    candle.location = (0.0, 0.0, 0.095)
    pool.location = (0.0, 0.0, 0.186)
    wick.location = (0.0, 0.0, 0.189)

    # Slight offset so composition feels like "desk corner"
    for obj in (holder, candle, pool, wick):
        obj.location.x += 0.0
        obj.location.y += -0.10

    # Atmospheric haze volume
    haze = create_air_haze_cube()
    haze.location = (0.0, -0.12, 0.40)

    # Mantaflow
    domain = create_domain()
    domain.location = (0.0, -0.10, 0.20)

    flow = create_flow_emitter(wick)
    flow.location = (0.0, -0.10, 0.195)

    # Camera
    cam, focus = setup_camera(scene)
    # Adjust focus to new offset
    focus.location = (0.0, -0.10, 0.215)

    # Light
    flame_light = create_flame_light()
    flame_light.location = (0.0, -0.10, 0.215)

    # Bake sim
    bake_mantaflow(domain)

    # Render a frame where the sim has developed
    scene.frame_set(90)

    # Output
    scene.render.image_settings.file_format = 'PNG'
    scene.render.filepath = RENDER_PATH

    bpy.ops.render.render(write_still=True)
    print(f"Rendered to: {scene.render.filepath}")

    bpy.ops.wm.save_as_mainfile(filepath=BLEND_PATH)
    print(f"Saved .blend to: {BLEND_PATH}")


if __name__ == "__main__":
    main()
