    ramp.color_ramp.elements.new(0.85)
    ramp.color_ramp.elements[2].color = (1.0, 0.45, 0.10, 1.0)   # orange tips

    links.new(attr_flame.outputs.get('Fac'), ramp.inputs.get('Fac'))

    # Emission strength from flame, tuned for candle intensity
    strength = nodes.new('ShaderNodeMath')
    strength.operation = 'MULTIPLY'
    strength.inputs[1].default_value = 18.0
    links.new(attr_flame.outputs.get('Fac'), strength.inputs[0])

    # Many node socket names vary; use .get() everywhere.
    if vol.inputs.get('Emission Strength'):
        links.new(strength.outputs.get('Value'), vol.inputs.get('Emission Strength'))
    if vol.inputs.get('Emission Color'):
        links.new(ramp.outputs.get('Color'), vol.inputs.get('Emission Color'))
    else:
        # Fallback: use Color socket if present.
        if vol.inputs.get('Color'):
            links.new(ramp.outputs.get('Color'), vol.inputs.get('Color'))

    # Mild scattering to show smoke wisps and candle haze
    if vol.inputs.get('Anisotropy'):
        vol.inputs.get('Anisotropy').default_value = 0.35

    links.new(vol.outputs.get('Volume'), out.inputs.get('Volume'))

    # Assign
    if domain_obj.data.materials:
        domain_obj.data.materials[0] = mat
    else:
        domain_obj.data.materials.append(mat)


