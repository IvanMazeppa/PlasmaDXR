def create_mug(name="mug_cup", location=(0.0, 0.0, 0.0)):
    # Body
    bpy.ops.mesh.primitive_cylinder_add(vertices=96, radius=0.045, depth=0.11, location=(location[0], location[1], location[2] + 0.055))
    body = bpy.context.object
    body.name = name

    # Smooth shading
    bpy.ops.object.shade_smooth()

    # Modifiers: solidify -> bevel -> subd
    solid = body.modifiers.new(name='Solidify', type='SOLIDIFY')
    if solid is None:
        print(f"WARNING: Could not add Solidify modifier to {body.name}")
    else:
        solid.thickness = 0.004

    bev = body.modifiers.new(name='Bevel', type='BEVEL')
    if bev is None:
        print(f"WARNING: Could not add Bevel modifier to {body.name}")
    else:
        bev.width = 0.0012
        bev.segments = 2

    subd = body.modifiers.new(name='Subd', type='SUBSURF')
    if subd is None:
        print(f"WARNING: Could not add Subsurf modifier to {body.name}")
    else:
        subd.levels = 2
        subd.render_levels = 2

    # Handle (torus) - intersects the cup for a believable attachment
    bpy.ops.mesh.primitive_torus_add(major_segments=48, minor_segments=16, major_radius=0.030, minor_radius=0.006, location=(location[0] + 0.052, location[1], location[2] + 0.060))
    handle = bpy.context.object
    handle.name = name + "_handle"
    handle.rotation_euler = (math.radians(90.0), 0.0, 0.0)
    bpy.ops.object.shade_smooth()

    h_subd = handle.modifiers.new(name='Subd', type='SUBSURF')
    if h_subd is None:
        print(f"WARNING: Could not add Subsurf modifier to {handle.name}")
    else:
        h_subd.levels = 2
        h_subd.render_levels = 2

    # Join handle into body to avoid separate shading breaks
    bpy.ops.object.select_all(action='DESELECT')
    body.select_set(True)
    handle.select_set(True)
    bpy.context.view_layer.objects.active = body
    bpy.ops.object.join()

    return body


