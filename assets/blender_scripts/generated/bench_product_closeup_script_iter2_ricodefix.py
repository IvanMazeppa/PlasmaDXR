def create_cyclorama(name="Cyclorama", width=3.0, floor_len=2.0, radius=0.65, wall_height=2.0, arc_segments=14, x_segments=2):
    """Create a single seamless studio cyclorama mesh (no plane boundaries).

    Cross-section is in YZ plane:
    - floor: y from -floor_len to 0 at z=0
    - quarter-circle curve: from (0,0) to (radius,radius)
    - wall: y=radius, z from radius to radius+wall_height
    """

    xs = [(-width * 0.5) + (width * i / x_segments) for i in range(x_segments + 1)]

    # Cross-section points (y,z)
    pts = []

    # Floor samples
    floor_steps = 6
    for i in range(floor_steps + 1):
        t = i / floor_steps
        y = -floor_len + t * floor_len
        z = 0.0
        pts.append((y, z))

    # Arc samples (skip first point because it duplicates floor end at y=0,z=0)
    for i in range(1, arc_segments + 1):
        t = i / arc_segments
        theta = (-math.pi / 2.0) + t * (math.pi / 2.0)  # -90 to 0
        y = radius * math.cos(theta)
        z = radius + radius * math.sin(theta)
        pts.append((y, z))

    # Wall samples (skip first point because it duplicates arc end at y=radius,z=radius)
    wall_steps = 6
    for i in range(1, wall_steps + 1):
        t = i / wall_steps
        y = radius
        z = radius + t * wall_height
        pts.append((y, z))

    mesh = bpy.data.meshes.new(name + "_M")
    obj = bpy.data.objects.new(name, mesh)
    bpy.context.collection.objects.link(obj)

    bm = bmesh.new()

    vgrid = []  # [ix][iy]
    for x in xs:
        col = []
        for (y, z) in pts:
            v = bm.verts.new((x, y, z))
            col.append(v)
        vgrid.append(col)

    bm.verts.ensure_lookup_table()

    for ix in range(len(xs) - 1):
        for iy in range(len(pts) - 1):
            v00 = vgrid[ix][iy]
            v10 = vgrid[ix + 1][iy]
            v11 = vgrid[ix + 1][iy + 1]
            v01 = vgrid[ix][iy + 1]
            bm.faces.new((v00, v10, v11, v01))

    bm.normal_update()
    bm.to_mesh(mesh)
    bm.free()

    # Smooth shading
    for p in obj.data.polygons:
        p.use_smooth = True

    # Subdivision for extra smoothness (still one continuous mesh)
    subd = obj.modifiers.new(name='Subd', type='SUBSURF')
    if subd is None:
        print(f"WARNING: Could not add Subsurf modifier to {obj.name}")
    else:
        subd.levels = 2
        subd.render_levels = 2

    return obj


