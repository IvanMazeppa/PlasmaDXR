    bpy.ops.mesh.primitive_uv_sphere_add(segments=128, ring_count=64, radius=1.0, location=(0.0, 0.0, 0.0))
    sun = bpy.context.active_object
    sun.name = "SunPhotosphere"
    shade_smooth(sun)

    subd = sun.modifiers.new(name="Subd", type='SUBSURF')
    subd.levels = 2
    subd.render_levels = 3

    mat_sun = create_photosphere_material()
    if sun.data.materials:
        sun.data.materials[0] = mat_sun
    else:
        sun.data.materials.append(mat_sun)

    # Corona volume shell
    bpy.ops.mesh.primitive_uv_sphere_add(segments=128, ring_count=64, radius=1.28, location=(0.0, 0.0, 0.0))
    corona = bpy.context.active_object
    corona.name = "SunCorona"
    shade_smooth(corona)

    mat_cor = create_corona_material()
    if corona.data.materials:
        corona.data.materials[0] = mat_cor
    else:
        corona.data.materials.append(mat_cor)

    # Make corona not cast shadows (Blender 5 visibility)
    if hasattr(corona, 'visible_shadow'):
        corona.visible_shadow = False

    return sun, corona


