def setup_compositor(scene):
    scene.use_nodes = True
    if not (hasattr(scene, 'node_tree') and scene.node_tree is not None):
        print("WARNING: Compositor not available")
        return

    nt = scene.node_tree
    nt.nodes.clear()

    rl = nt.nodes.new('CompositorNodeRLayers')
    glare = nt.nodes.new('CompositorNodeGlare')
    glare.glare_type = 'FOG_GLOW'
    glare.quality = 'HIGH'
    glare.threshold = 0.45
    glare.size = 7
    glare.mix = 0.12

    comp = nt.nodes.new('CompositorNodeComposite')
    viewer = nt.nodes.new('CompositorNodeViewer')

    nt.links.new(rl.outputs['Image'], glare.inputs['Image'])
    nt.links.new(glare.outputs['Image'], comp.inputs['Image'])
    nt.links.new(glare.outputs['Image'], viewer.inputs['Image'])


def try_bake_fluid(domain_obj):
    if not BAKE_FLUID:
        print("INFO: BAKE_FLUID=False, skipping Mantaflow bake. Preview sheet will be rendered.")
        return False

    # Try Mantaflow bake operators (context-sensitive)
    baked = False
    try:
        set_active(domain_obj)
        override = {
            "scene": bpy.context.scene,
            "active_object": domain_obj,
            "object": domain_obj,
            "selected_objects": [domain_obj],
            "selected_editable_objects": [domain_obj],
            "view_layer": bpy.context.view_layer,
        }
        if hasattr(bpy.context, 'temp_override'):
            with bpy.context.temp_override(**override):
                if hasattr(bpy.ops, 'fluid') and hasattr(bpy.ops.fluid, 'bake_all'):
                    bpy.ops.fluid.free_all()
                    bpy.ops.fluid.bake_all()
                    baked = True
        else:
            # fallback context-less attempt
            if hasattr(bpy.ops, 'fluid') and hasattr(bpy.ops.fluid, 'bake_all'):
                bpy.ops.fluid.free_all()
                bpy.ops.fluid.bake_all()
                baked = True
    except Exception as e:
        print(f"WARNING: Mantaflow bake failed or unavailable: {e}")
        baked = False

    if baked:
        bpy.context.scene.frame_current = BAKE_TO_FRAME
        print(f"INFO: Mantaflow baked; rendering at frame {BAKE_TO_FRAME}.")
    return baked


def main():
    cleanup_scene()

    scene = bpy.context.scene
    setup_render(scene)
    make_world(scene)

    root = ensure_collection(ASSET_NAME)
    env_col = ensure_collection("ENV", parent=root)
    wf_col = ensure_collection("WATERFALL", parent=root)

    impact_point = Vector((0.0, 0.8, 0.15))

    cliff, rocks, pool, river, ground = create_environment(env_col, impact_point)

    # Waterfall visual layers
    sheet = create_waterfall_preview(wf_col)
    emitter, droplet = create_spray_particles(wf_col, impact_point)
    mist = create_mist(wf_col, impact_point)
    rainbow = create_rainbow_card(wf_col, impact_point)

    # Mantaflow liquid setup (hidden by default)
    domain, inflow, outflow = setup_mantaflow_liquid(wf_col, rocks, impact_point)

    # Camera/lighting
    cam = setup_camera(scene, target=impact_point + Vector((0.0, 0.6, 1.4)))
    setup_lighting(scene, env_col, impact_point)

    setup_compositor(scene)

    # Optional bake; if baked, you may hide preview sheet and render the sim mesh instead.
    baked = try_bake_fluid(domain)
    if baked:
        # For a baked render you would normally hide the preview sheet.
        sheet.hide_render = True

    # Render
    scene.render.filepath = OUTPUT_PATH
    bpy.ops.render.render(write_still=True)
    print(f"Rendered to: {scene.render.filepath}")


if __name__ == "__main__":
    main()
