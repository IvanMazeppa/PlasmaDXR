    links = mat.node_tree.links
    for n in list(nodes):
        nodes.remove(n)

    out = nodes.new('ShaderNodeOutputMaterial')
    out.location = (520, 0)
    bsdf = nodes.new('ShaderNodeBsdfPrincipled')
    bsdf.location = (240, 0)

    texcoord = nodes.new('ShaderNodeTexCoord')
    texcoord.location = (-980, -60)
    mapping = nodes.new('ShaderNodeMapping')
    mapping.location = (-760, -60)

    wave = nodes.new('ShaderNodeTexWave')
    wave.location = (-520, 40)
    wave.inputs['Scale'].default_value = 14.0
    wave.inputs['Distortion'].default_value = 3.0
    wave.inputs['Detail'].default_value = 2.0

    noise = nodes.new('ShaderNodeTexNoise')
    noise.location = (-520, -180)
    noise.inputs['Scale'].default_value = 8.0
    noise.inputs['Detail'].default_value = 6.0
    noise.inputs['Roughness'].default_value = 0.55

    # Blender 5.x: ShaderNodeMix replaces MixRGB. Use named sockets.
    mix = nodes.new('ShaderNodeMix')
    mix.data_type = 'RGBA'  # MixRGB was always color mode
    mix.location = (-240, -30)
    mix.data_type = 'RGBA'
    mix.blend_type = 'MULTIPLY'
    mix.inputs['Factor'].default_value = 0.6

    ramp = nodes.new('ShaderNodeValToRGB')
    ramp.location = (-240, 240)
    elems = ramp.color_ramp.elements
    while len(elems) > 2:
        elems.remove(elems[0])
    elems[0].position = 0.35
    elems[0].color = (0.18, 0.09, 0.04, 1.0)
    elems[1].position = 0.8
    elems[1].color = (0.06, 0.03, 0.015, 1.0)

    bump = nodes.new('ShaderNodeBump')
    bump.location = (40, -240)
    bump.inputs['Strength'].default_value = 0.35

    links.new(texcoord.outputs['Object'], mapping.inputs['Vector'])
    links.new(mapping.outputs['Vector'], wave.inputs['Vector'])
    links.new(mapping.outputs['Vector'], noise.inputs['Vector'])

    links.new(wave.outputs['Color'], ramp.inputs['Fac'])

    # Multiply ramp color by subtle noise variation
    a_in = mix.inputs.get('A')
    b_in = mix.inputs.get('B')
    if a_in and b_in:
        links.new(noise.outputs['Color'], a_in)
        links.new(ramp.outputs['Color'], b_in)

    base = bsdf_input(bsdf, 'Base Color')
    if base:
        links.new(mix.outputs['Result'], base)

    links.new(noise.outputs['Fac'], bump.inputs['Height'])
    normal = bsdf_input(bsdf, 'Normal')
    if normal:
        links.new(bump.outputs['Normal'], normal)

    r = bsdf_input(bsdf, 'Roughness')
    if r:
        r.default_value = 0.55

    links.new(bsdf.outputs['BSDF'], out.inputs['Surface'])
    return mat


