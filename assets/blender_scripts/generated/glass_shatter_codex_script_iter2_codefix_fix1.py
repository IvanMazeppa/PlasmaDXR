    weights = [random.uniform(0.7, 1.35) for _ in range(sector_count)]
    weight_total = sum(weights)
    angles = [-math.pi]
    accum = -math.pi
    for weight in weights:
        accum += (math.tau * weight / weight_total)
        angles.append(accum)

    for index in range(sector_count):
        a0 = angles[index]
        a1 = angles[index + 1]
        r_edge_0 = radius_to_boundary(a0) * random.uniform(0.90, 0.985)
        r_edge_1 = radius_to_boundary(a1) * random.uniform(0.90, 0.985)
        core = random.uniform(0.05, 0.14)
        mid = min(random.uniform(0.28, 0.52), min(r_edge_0, r_edge_1) * 0.62)
