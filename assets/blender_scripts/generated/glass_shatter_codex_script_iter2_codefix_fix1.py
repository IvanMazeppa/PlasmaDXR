def polygon_area(poly):
    total = 0.0
    for i in range(len(poly)):
        x1, z1 = poly[i]
        x2, z2 = poly[(i + 1) % len(poly)]
        total += x1 * z2 - x2 * z1
    return abs(total) * 0.5


def build_shard_object(name, poly):
    verts = []
    faces = []
    front_idx = []
    back_idx = []
    half_t = window_thickness * 0.5

    for x, z in poly:
        front_idx.append(len(verts))
        verts.append((x, half_t, z))
    for x, z in poly:
        back_idx.append(len(verts))
        verts.append((x, -half_t, z))

    faces.append(front_idx)
    faces.append(list(reversed(back_idx)))
    for i in range(len(poly)):
        j = (i + 1) % len(poly)
        faces.append([front_idx[i], front_idx[j], back_idx[j], back_idx[i]])

    mesh = bpy.data.meshes.new(f"{name}Mesh")
    mesh.from_pydata(verts, [], faces)
    mesh.update()
    obj = bpy.data.objects.new(name, mesh)
    bpy.context.collection.objects.link(obj)
    return obj


def radius_to_boundary(angle):
    dx = math.cos(angle)
    dz = math.sin(angle)
    candidates = []
    if dx > 1e-6:
        candidates.append((xmax - impact_x) / dx)
    elif dx < -1e-6:
        candidates.append((xmin - impact_x) / dx)
    if dz > 1e-6:
        candidates.append((zmax - impact_z) / dz)
    elif dz < -1e-6:
        candidates.append((zmin - impact_z) / dz)
    positives = [c for c in candidates if c > 0.0]
    return min(positives) if positives else 0.1


def polar_point(angle, radius):
    return (impact_x + math.cos(angle) * radius, impact_z + math.sin(angle) * radius)


