def select_active(obj):
    for o in bpy.context.view_layer.objects:
        o.select_set(False)
    obj.select_set(True)
    bpy.context.view_layer.objects.active = obj


def bake_sim(domain_obj):
    ensure_object_mode()
    select_active(domain_obj)

    # Clear any previous bake
    try:
        bpy.ops.fluid.free_all()
    except Exception as e:
        print("fluid.free_all failed:", e)

    # Bake data first, then mesh + particles (spray)
    try:
        bpy.ops.fluid.bake_data()
    except Exception as e:
        print("fluid.bake_data failed:", e)

    try:
        bpy.ops.fluid.bake_particles()
    except Exception as e:
        print("fluid.bake_particles failed:", e)

    try:
        bpy.ops.fluid.bake_mesh()
    except Exception as e:
        print("fluid.bake_mesh failed:", e)


