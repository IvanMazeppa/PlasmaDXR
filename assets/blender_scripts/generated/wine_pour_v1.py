def create_lathed_glass(name="WineGlass", height=0.22, rim_radius=0.045, base_radius=0.04, thickness=0.0016):
    """Create a Bordeaux-ish wine glass by lathing a 2D profile around Z axis."""

    # Profile points in XZ plane (x=radius, z=height)
    z0 = 0.0
    z_stem_top = height * 0.45
    z_bowl_mid = height * 0.72
    z_rim = height

    profile = [
        (base_radius, z0),
        (base_radius * 0.55, z0 + height * 0.02),
        (0.010, z0 + height * 0.08),
        (0.007, z_stem_top),
        (0.018, z_stem_top + height * 0.06),
        (0.032, z_bowl_mid),
        (rim_radius * 0.92, z_rim - height * 0.03),
        (rim_radius, z_rim),
    ]

    mesh = bpy.data.meshes.new(name + "_M")
    obj = bpy.data.objects.new(name, mesh)
    bpy.context.collection.objects.link(obj)

    bm = bmesh.new()

    verts = []
    for r, z in profile:
        v = bm.verts.new((r, 0.0, z))
        verts.append(v)
    bm.verts.ensure_lookup_table()

    # Create edges along the profile
    for i in range(len(verts) - 1):
        bm.edges.new((verts[i], verts[i + 1]))

    # Spin around Z to create a surface
    geom = verts + list(bm.edges)
    bmesh.ops.spin(
        bm,
        geom=geom,
        angle=math.radians(360.0),
        steps=96,
        axis=(0.0, 0.0, 1.0),
        cent=(0.0, 0.0, 0.0),
    )

    bmesh.ops.remove_doubles(bm, verts=bm.verts, dist=0.00001)

    # Fill rim by creating faces from boundary loops
    bmesh.ops.holes_fill(bm, edges=[e for e in bm.edges if e.is_boundary], sides=0)

    bm.normal_update()
    bm.to_mesh(mesh)
    bm.free()

    # Smooth shading
    mesh.polygons.foreach_set("use_smooth", [True] * len(mesh.polygons))

    # Add thickness and smoothness
    solid = obj.modifiers.new("Solidify", 'SOLIDIFY')
    solid.thickness = thickness
    solid.offset = 1.0

    subsurf = obj.modifiers.new("Subsurf", 'SUBSURF')
    subsurf.levels = 2
    subsurf.render_levels = 2

    # Slight bevel to catch highlights
    bev = obj.modifiers.new("Bevel", 'BEVEL')
    bev.width = thickness * 0.75
    bev.segments = 2
    bev.profile = 0.7

    # Set origin at base
    bpy.context.view_layer.objects.active = obj
    obj.select_set(True)
    bpy.ops.object.origin_set(type='ORIGIN_GEOMETRY', center='BOUNDS')

    return obj


