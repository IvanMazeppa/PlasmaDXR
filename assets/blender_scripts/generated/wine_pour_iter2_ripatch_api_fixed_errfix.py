def look_at(obj, target, roll=0.0):
    """Aim -Z toward target, Y up (camera-style)."""
    from mathutils import Vector, Matrix
    loc = Vector(obj.location)
    tgt = Vector(target)
    direction = (tgt - loc)
    if direction.length < 1e-6:
        return
    direction.normalize()

    # Camera looks down -Z
    z = -direction
    up = Vector((0.0, 0.0, 1.0))
    x = up.cross(z)
    if x.length < 1e-6:
        up = Vector((0.0, 1.0, 0.0))
        x = up.cross(z)
    x.normalize()
    y = z.cross(x)
    y.normalize()

    rot = Matrix((x, y, z)).transposed().to_4x4()
    obj.matrix_world = Matrix.Translation(loc) @ rot

    if abs(roll) > 1e-8:
        obj.rotation_euler.rotate_axis('Z', roll)


