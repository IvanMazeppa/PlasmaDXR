def create_crystal_wine_glass(name="WineGlass"):
    """Create a wine-glass shaped mesh using bmesh spin (lathe).
    This avoids a simple primitive cylinder silhouette.
    """
    import bmesh

    mesh = bpy.data.meshes.new(name + "_Mesh")
    obj = bpy.data.objects.new(name, mesh)
    bpy.context.collection.objects.link(obj)

    bm = bmesh.new()

    # Profile points in XZ plane (Y=0) - from stem bottom to rim
    # Keep X > 0 (radius), Z increasing.
    profile = [
        (0.030, 0.000),  # foot outer
        (0.020, 0.004),
        (0.060, 0.008),  # foot flare
        (0.055, 0.012),
        (0.025, 0.020),
        (0.012, 0.035),  # stem
        (0.010, 0.110),
        (0.014, 0.140),
        (0.035, 0.165),  # bowl start
        (0.060, 0.190),
        (0.072, 0.225),
        (0.070, 0.255),
        (0.058, 0.275),
        (0.045, 0.285),
        (0.042, 0.292),  # rim thickness start
        (0.044, 0.298),  # rim lip
        (0.041, 0.300),  # rim inner-ish (still outer surface)
    ]

    verts = []
    for x, z in profile:
        v = bm.verts.new((x, 0.0, z))
        verts.append(v)
    bm.verts.ensure_lookup_table()

    # Create edges along the profile
    for i in range(len(verts) - 1):
        bm.edges.new((verts[i], verts[i + 1]))

    # Spin (lathe) the profile around Z to create surface
    geom = verts + list(bm.edges)
    bmesh.ops.spin(
        bm,
        geom=geom,
        cent=(0.0, 0.0, 0.0),
        axis=(0.0, 0.0, 1.0),
        angle=math.tau,
        steps=96,
    )

    # Remove doubles
    bmesh.ops.remove_doubles(bm, verts=bm.verts, dist=1e-6)

    # Solidify thickness (bmesh op)
    # Note: this creates thickness by extruding along normals.
    try:
        bmesh.ops.solidify(bm, geom=bm.faces[:], thickness=0.003)
    except Exception as e:
        print(f"WARNING: bmesh solidify failed: {e}")

    # Bevel rim slightly
    rim_edges = []
    # Heuristic: collect edges near top (rim area)
    z_max = max(v.co.z for v in bm.verts)
    for e in bm.edges:
        if (e.verts[0].co.z > z_max - 0.01) and (e.verts[1].co.z > z_max - 0.01):
            rim_edges.append(e)
    if rim_edges:
        try:
            bmesh.ops.bevel(
                bm,
                geom=rim_edges,
                offset=0.001,
                segments=2,
                profile=0.7,
            )
        except Exception as e:
            print(f"WARNING: rim bevel failed: {e}")

    bm.to_mesh(mesh)
    bm.free()

    # Smooth shading
    try:
        for p in obj.data.polygons:
            p.use_smooth = True
    except Exception:
        pass

    return obj


