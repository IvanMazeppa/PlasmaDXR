def setup_physics(objects, mats):
    scene = bpy.context.scene
    scene.frame_start = 1
    scene.frame_end = 120

    # Domain
    bpy.ops.mesh.primitive_cube_add(size=1.0, location=(0.0, 0.0, 0.60))
    domain = bpy.context.object
    domain.name = "LiquidDomain"
    domain.scale = (0.90, 0.90, 1.20)  # final dimensions: 0.9m x 0.9m x 1.2m

    # Domain material: wine liquid (surface)
    domain.active_material = mats['wine']

    dmod = domain.modifiers.new(name='Fluid', type='FLUID')
    if dmod is None:
        print(f"WARNING: Could not add Fluid modifier to {domain.name}")
    else:
        dmod.fluid_type = 'DOMAIN'
        ds = dmod.domain_settings
        ds.domain_type = 'LIQUID'
        ds.resolution_max = 72
        ds.simulation_method = 'FLIP'
        ds.cache_type = 'ALL'
        ds.cache_directory = CACHE_DIR
        ds.cache_frame_start = scene.frame_start
        ds.cache_frame_end = scene.frame_end
        ds.use_adaptive_timesteps = True
        ds.timesteps_min = 1
        ds.timesteps_max = 4
        ds.use_mesh = True

    # Inflow emitter - small hidden cylinder above glass
    bpy.ops.mesh.primitive_cylinder_add(radius=0.012, depth=0.10, location=(0.0, 0.0, 0.80))
    inflow = bpy.context.object
    inflow.name = "WineInflow"
    inflow.hide_render = True
    inflow.display_type = 'WIRE'

    fmod = inflow.modifiers.new(name='Fluid', type='FLUID')
    if fmod is None:
        print(f"WARNING: Could not add Fluid modifier to {inflow.name}")
    else:
        fmod.fluid_type = 'FLOW'
        fs = fmod.flow_settings
        fs.flow_type = 'LIQUID'
        fs.use_plane_init = True  # Planar liquid emitter

        fs.flow_behavior = 'INFLOW'
        fs.use_inflow = True
        fs.use_absolute = True
        fs.subframes = 0
        fs.surface_distance = 0.5
        # Gravity will pull it down; avoid relying on possibly mismatched velocity property types
        fs.use_initial_velocity = False

    # Effectors: glass + tabletop (collision)
    for eff in (objects['glass'], objects['table_top']):
        emod = eff.modifiers.new(name='Fluid', type='FLUID')
        if emod is None:
            print(f"WARNING: Could not add Fluid modifier to {eff.name}")
            continue
        emod.fluid_type = 'EFFECTOR'
        es = emod.effector_settings
        es.effector_type = 'COLLISION'
        es.use_effector = True
        es.subframes = 0
        es.surface_distance = 0.0

    # Ensure depsgraph updated before bake
    bpy.context.view_layer.update()

    return {'domain': domain, 'inflow': inflow}


