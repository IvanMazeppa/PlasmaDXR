    bpy.ops.mesh.primitive_cylinder_add(radius=0.025, depth=0.08, location=(0.38, 0.22, 0.065))
    candle = bpy.context.object
    candle.name = "Candle"

    candle_mat = bpy.data.materials.new("CandleWax")
    bsdf = candle_mat.node_tree.nodes.get('Principled BSDF')
    if bsdf:
        base = bsdf.inputs.get('Base Color')
        rough = bsdf.inputs.get('Roughness')
        subs = bsdf.inputs.get('Subsurface Weight', bsdf.inputs.get('Subsurface'))
        if base:
            base.default_value = (0.85, 0.80, 0.72, 1.0)
