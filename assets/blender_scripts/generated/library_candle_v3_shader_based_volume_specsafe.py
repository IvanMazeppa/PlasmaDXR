def setup_camera(wick_obj):
    bpy.ops.object.camera_add(location=(0.03, 0.14, wick_obj.location.z + 0.07))
    cam = bpy.context.active_object
    cam.name = 'Camera_Macro'

    look_at(cam, wick_obj.location + Vector((0.0, 0.0, 0.02)))
    cam.data.lens = 105

    # Shallow DoF
    try:
        cam.data.dof.use_dof = True
        cam.data.dof.focus_object = wick_obj
        cam.data.dof.aperture_fstop = 1.8
    except Exception:
        pass

    bpy.context.scene.camera = cam
    return cam


def setup_lighting(wick_obj):
    """Flame should be the main light; add minimal fill to avoid pure black."""

    # Tiny warm point light at flame position to ensure visible illumination.
    bpy.ops.object.light_add(type='POINT', location=(0.0, 0.0, wick_obj.location.z + 0.02))
    pl = bpy.context.active_object
    pl.name = 'FlameLight'
    pl.data.color = (1.0, 0.72, 0.45)
    pl.data.energy = 18.0

    # Very subtle cool rim
    bpy.ops.object.light_add(type='POINT', location=(-0.18, 0.12, wick_obj.location.z + 0.02))
    rim = bpy.context.active_object
    rim.name = 'RimCool'
    rim.data.color = (0.35, 0.55, 1.0)
    rim.data.energy = 4.0

    return pl, rim


