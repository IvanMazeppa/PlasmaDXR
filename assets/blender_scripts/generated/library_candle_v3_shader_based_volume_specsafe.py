def make_flame_volume_material(name="MAT_Flame_Volume"):
    """Procedural candle flame volume.

    We avoid any node socket indexing to stay robust.
    """
    mat = bpy.data.materials.new(name)
    nt = ensure_node_tree(mat)
    if nt is None:
        return mat

    nt.nodes.clear()
    out = nt.nodes.new('ShaderNodeOutputMaterial')

    # Coordinate and shaping
    texcoord = nt.nodes.new('ShaderNodeTexCoord')
    mapping = nt.nodes.new('ShaderNodeMapping')
    mapping.inputs[3].default_value = (1.0, 1.0, 2.2)  # stretch Z

    sep = nt.nodes.new('ShaderNodeSeparateXYZ')

    # Radius from X/Y
    multx = nt.nodes.new('ShaderNodeMath'); multx.operation = 'MULTIPLY'
    multy = nt.nodes.new('ShaderNodeMath'); multy.operation = 'MULTIPLY'
    addxy = nt.nodes.new('ShaderNodeMath'); addxy.operation = 'ADD'
    sqrt = nt.nodes.new('ShaderNodeMath'); sqrt.operation = 'SQRT'

    # Vertical gradient (Z)
    z_map = nt.nodes.new('ShaderNodeMapRange')
    z_map.inputs[1].default_value = -0.2
    z_map.inputs[2].default_value = 0.8
    z_map.inputs[3].default_value = 0.0
    z_map.inputs[4].default_value = 1.0
    z_map.clamp = True

    # Core mask: small radius, low z
    r_map = nt.nodes.new('ShaderNodeMapRange')
    r_map.inputs[1].default_value = 0.0
    r_map.inputs[2].default_value = 0.35
    r_map.inputs[3].default_value = 1.0
    r_map.inputs[4].default_value = 0.0
    r_map.clamp = True

    # Noise for flicker
    noise = nt.nodes.new('ShaderNodeTexNoise')
    noise.inputs[2].default_value = 6.0
    noise.inputs[3].default_value = 3.0
    noise.inputs[4].default_value = 0.5

    # Animate noise W for slow hypnotic motion
    if noise.inputs.get('W'):
        noise.inputs['W'].default_value = 0.0
        noise.inputs['W'].keyframe_insert(data_path='default_value', frame=1)
        noise.inputs['W'].default_value = 0.7
        noise.inputs['W'].keyframe_insert(data_path='default_value', frame=60)
        noise.inputs['W'].default_value = 1.4
        noise.inputs['W'].keyframe_insert(data_path='default_value', frame=120)

    # Combine masks
    noise_map = nt.nodes.new('ShaderNodeMapRange')
    noise_map.inputs[1].default_value = 0.25
    noise_map.inputs[2].default_value = 0.75
    noise_map.inputs[3].default_value = 0.0
    noise_map.inputs[4].default_value = 1.0
    noise_map.clamp = True

    mul_mask = nt.nodes.new('ShaderNodeMath'); mul_mask.operation = 'MULTIPLY'
    mul_mask2 = nt.nodes.new('ShaderNodeMath'); mul_mask2.operation = 'MULTIPLY'

    # Color ramp for emission color: blue-white core -> yellow -> orange
    ramp = nt.nodes.new('ShaderNodeValToRGB')
    cr = ramp.color_ramp
    while len(cr.elements) < 3:
        cr.elements.new(0.5)
    cr.elements[0].position = 0.15
    cr.elements[0].color = (0.85, 0.92, 1.0, 1.0)
    cr.elements[1].position = 0.45
    cr.elements[1].color = (1.0, 0.95, 0.45, 1.0)
    cr.elements[2].position = 0.85
    cr.elements[2].color = (1.0, 0.55, 0.18, 1.0)

    # Principled Volume
    pv = nt.nodes.new('ShaderNodeVolumePrincipled')

    # Safe setting by name (avoid index issues)
    safe_set(pv, 'Density', 0.6)
    safe_set(pv, 'Anisotropy', 0.3)
    safe_set(pv, 'Emission Strength', 12.0)

    # Link mapping
    nt.links.new(texcoord.outputs['Object'], mapping.inputs['Vector'])
    nt.links.new(mapping.outputs['Vector'], sep.inputs['Vector'])

    # radius = sqrt(x^2 + y^2)
    nt.links.new(sep.outputs['X'], multx.inputs[0])
    multx.inputs[1].default_value = 1.0
    nt.links.new(sep.outputs['X'], multx.inputs[1])

    nt.links.new(sep.outputs['Y'], multy.inputs[0])
    multy.inputs[1].default_value = 1.0
    nt.links.new(sep.outputs['Y'], multy.inputs[1])

    nt.links.new(multx.outputs[0], addxy.inputs[0])
    nt.links.new(multy.outputs[0], addxy.inputs[1])
    nt.links.new(addxy.outputs[0], sqrt.inputs[0])

    # masks
    nt.links.new(sep.outputs['Z'], z_map.inputs['Value'])
    nt.links.new(sqrt.outputs[0], r_map.inputs['Value'])

    # noise
    nt.links.new(mapping.outputs['Vector'], noise.inputs['Vector'])
    nt.links.new(noise.outputs['Fac'], noise_map.inputs['Value'])

    # final density mask = z_map * r_map * noise_map
    nt.links.new(z_map.outputs['Result'], mul_mask.inputs[0])
    nt.links.new(r_map.outputs['Result'], mul_mask.inputs[1])

    nt.links.new(mul_mask.outputs[0], mul_mask2.inputs[0])
    nt.links.new(noise_map.outputs['Result'], mul_mask2.inputs[1])

    # color factor (use Z for color ramp)
    nt.links.new(z_map.outputs['Result'], ramp.inputs['Fac'])

    if pv.inputs.get('Emission Color') and ramp.outputs.get('Color'):
        nt.links.new(ramp.outputs['Color'], pv.inputs['Emission Color'])

    # drive density and emission with mask
    if pv.inputs.get('Density'):
        # Keep flame airy (volume only)
        dens_mul = nt.nodes.new('ShaderNodeMath'); dens_mul.operation = 'MULTIPLY'
        dens_mul.inputs[1].default_value = 3.0
        nt.links.new(mul_mask2.outputs[0], dens_mul.inputs[0])
        nt.links.new(dens_mul.outputs[0], pv.inputs['Density'])

    if pv.inputs.get('Emission Strength'):
        em_mul = nt.nodes.new('ShaderNodeMath'); em_mul.operation = 'MULTIPLY'
        em_mul.inputs[1].default_value = 25.0
        nt.links.new(mul_mask2.outputs[0], em_mul.inputs[0])
        nt.links.new(em_mul.outputs[0], pv.inputs['Emission Strength'])

    nt.links.new(pv.outputs[0], out.inputs['Volume'])

    return mat


