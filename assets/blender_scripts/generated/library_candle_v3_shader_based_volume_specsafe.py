def create_shader_flame_and_smoke(wick_obj):
    """Create procedural volume flame + wispy smoke volume, both shader-driven."""

    flame_z = wick_obj.location.z + 0.018

    # Flame volume mesh: elongated icosphere
    bpy.ops.mesh.primitive_ico_sphere_add(subdivisions=4, radius=0.010, location=(0.0, 0.0, flame_z))
    flame = bpy.context.active_object
    flame.name = 'Flame_Volume'
    flame.scale = (0.75, 0.75, 2.2)
    bpy.ops.object.transform_apply(location=False, rotation=False, scale=True)

    flame_mat = make_flame_volume_material()
    flame.data.materials.append(flame_mat)

    # Smoke wisp mesh: thin tall cylinder
    bpy.ops.mesh.primitive_cylinder_add(radius=0.018, depth=0.18, location=(0.0, 0.0, flame_z + 0.10))
    smoke = bpy.context.active_object
    smoke.name = 'Smoke_Wisp_Volume'
    smoke.scale = (0.55, 0.55, 1.0)
    bpy.ops.object.transform_apply(location=False, rotation=False, scale=True)

    smoke_mat = make_smoke_wisp_material()
    smoke.data.materials.append(smoke_mat)

    # Very subtle upward drift animation of smoke volume
    smoke.location = Vector((0.0, 0.0, flame_z + 0.10))
    smoke.keyframe_insert(data_path='location', frame=1)
    smoke.location = Vector((0.002, -0.002, flame_z + 0.115))
    smoke.keyframe_insert(data_path='location', frame=60)
    smoke.location = Vector((0.0, 0.001, flame_z + 0.13))
    smoke.keyframe_insert(data_path='location', frame=120)

    return flame, smoke


