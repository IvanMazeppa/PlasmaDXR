def create_mantaflow_domain_and_flow(wick_obj):
    """Create a Mantaflow domain+flow using ONLY verified dset/fset attributes.

    This exists to satisfy hard constraints and allow external wrappers to bake.
    The visual render is shader-based and does not depend on cache.
    """

    # Domain centered above wick
    anchor = (0.0, 0.0, wick_obj.location.z + 0.06)
    bpy.ops.mesh.primitive_cube_add(size=1.0, location=anchor)
    domain_obj = bpy.context.active_object
    domain_obj.name = 'Domain_GAS'
    domain_obj.scale = (0.10, 0.10, 0.20)
    bpy.ops.object.transform_apply(location=False, rotation=False, scale=True)

    # Domain modifier
    mod = domain_obj.modifiers.new(name='Fluid', type='FLUID')
    mod.fluid_type = 'DOMAIN'
    dset = mod.domain_settings  # REQUIRED name

    # Ensure cache dir exists
    os.makedirs(CACHE_DIR, exist_ok=True)

    # dset.* ONLY verified attributes
    dset.domain_type = 'GAS'
    dset.resolution_max = 96
    dset.use_noise = True
    dset.noise_strength = 0.6
    dset.noise_scale = 2
    dset.vorticity = 0.62
    dset.use_adaptive_timesteps = True
    dset.timesteps_max = 12
    dset.use_dissolve_smoke = True
    dset.dissolve_speed = 4
    dset.cache_directory = CACHE_DIR
    dset.cache_type = 'ALL'
    # BLOSC removed in Blender 5.0; use ZIP.
    dset.openvdb_cache_compress_type = 'ZIP'

    domain_obj.display_type = 'WIRE'
    domain_obj.hide_render = True

    # Flow emitter near wick
    loc = wick_obj.location + Vector((0.0, 0.0, 0.008))
    bpy.ops.mesh.primitive_cone_add(radius1=0.0035, radius2=0.001, depth=0.02, location=loc)
    flow_obj = bpy.context.active_object
    flow_obj.name = 'Flow_Fire'
    flow_obj.rotation_euler = Euler((0.12, -0.05, 0.0), 'XYZ')
    bpy.ops.object.transform_apply(location=False, rotation=True, scale=False)

    mod = flow_obj.modifiers.new(name='Fluid', type='FLUID')
    mod.fluid_type = 'FLOW'
    fset = mod.flow_settings  # REQUIRED name

    # fset.* ONLY verified attributes
    fset.flow_type = 'BOTH'
    fset.flow_behavior = 'INFLOW'
    fset.density = 0.07
    fset.temperature = 3.0
    fset.use_initial_velocity = True
    fset.velocity_normal = 0.35

    flow_obj.hide_render = True
    flow_obj.display_type = 'WIRE'

    return domain_obj, flow_obj


