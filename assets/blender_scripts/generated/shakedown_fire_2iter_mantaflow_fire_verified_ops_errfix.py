def look_at(obj, target: Vector, up=Vector((0, 0, 1))):
    loc = obj.matrix_world.to_translation()
    forward = (target - loc).normalized()

    # camera looks down its -Z
    z_axis = -forward
    x_axis = up.cross(z_axis).normalized()
    y_axis = z_axis.cross(x_axis).normalized()

    rot = Matrix((x_axis, y_axis, z_axis)).transposed()
    obj.matrix_world = Matrix.Translation(loc) @ rot.to_4x4()


