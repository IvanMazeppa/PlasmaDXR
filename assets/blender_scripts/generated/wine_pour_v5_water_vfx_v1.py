def create_wine_glass(name="WineGlass", steps=96):
    """Create a thick-walled Bordeaux-style glass via revolved profile (no modifiers)."""
    mesh = bpy.data.meshes.new(name + "_Mesh")
    obj = bpy.data.objects.new(name, mesh)
    bpy.context.collection.objects.link(obj)

    # Profile in XZ plane (Y=0), order: outer rim -> down to base -> inner base -> up to inner rim
    t = 0.002  # wall thickness ~2mm

    outer = [
        (0.045, 0.180),
        (0.056, 0.125),
        (0.050, 0.085),
        (0.030, 0.050),
        (0.012, 0.028),
        (0.010, 0.010),
        (0.040, 0.010),
        (0.042, 0.000),
    ]

    inner = [
        (max(outer[-1][0] - t, 0.001), outer[-1][1] + 0.002),
        (0.038, 0.010),
        (0.008, 0.010),
        (0.010, 0.028),
        (0.028, 0.050),
        (0.048, 0.085),
        (0.052, 0.125),
        (0.043, 0.178),
    ]

    profile = outer + inner

    bm = bmesh.new()
    verts = []
    for r, z in profile:
        v = bm.verts.new((r, 0.0, z))
        verts.append(v)
    bm.verts.ensure_lookup_table()

    edges = []
    for i in range(len(verts) - 1):
        edges.append(bm.edges.new((verts[i], verts[i + 1])))

    geom = verts + edges
    bmesh.ops.spin(
        bm,
        geom=geom,
        angle=math.tau,
        steps=steps,
        axis=(0.0, 0.0, 1.0),
        cent=(0.0, 0.0, 0.0),
    )

    # Weld seam
    bmesh.ops.remove_doubles(bm, verts=bm.verts, dist=0.0001)

    # Recalculate normals
    bmesh.ops.recalc_face_normals(bm, faces=bm.faces)

    bm.to_mesh(mesh)
    bm.free()

    # Smooth shading
    bpy.context.view_layer.objects.active = obj
    obj.select_set(True)
    bpy.ops.object.shade_smooth()
    obj.select_set(False)

    obj.location = (0.0, 0.0, 0.0)
    return obj


