def create_shard(name, points, thickness, mat):
    cx = sum(p[0] for p in points) / len(points)
    cz = sum(p[1] for p in points) / len(points)
    half_t = thickness * 0.5

    front = [(p[0] - cx, half_t, p[1] - cz) for p in points]
    back = [(p[0] - cx, -half_t, p[1] - cz) for p in points]
    verts = front + back

    faces = []
    faces.append(tuple(range(len(points))))
    faces.append(tuple(range(len(points), len(points) * 2)))
    count = len(points)
    for i in range(count):
        n = (i + 1) % count
        faces.append((i, n, count + n, count + i))

    mesh = bpy.data.meshes.new(name + "Mesh")
    mesh.from_pydata(verts, [], faces)
    mesh.update()

    obj = bpy.data.objects.new(name, mesh)
    bpy.context.collection.objects.link(obj)
    obj.location = (cx, 0.0, cz)
    assign_material(obj, mat)
    return obj



