def look_at(obj, target: Vector, roll: float = 0.0):
    direction = (target - obj.location).normalized()
    up = Vector((0.0, 0.0, 1.0))

    if abs(direction.dot(up)) > 0.999:
        up = Vector((0.0, 1.0, 0.0))

    right = direction.cross(up).normalized()
    up2 = right.cross(direction).normalized()

    rot = Matrix((right, up2, -direction)).to_4x4()
    obj.matrix_world = Matrix.Translation(obj.location) @ rot

    if roll != 0.0:
        obj.rotation_euler.rotate_axis('Z', roll)


