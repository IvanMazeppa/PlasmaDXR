import bmesh

def build_thick_bowl(name="Glass_Bowl", thickness=0.002, segments=64):
    # Outer bowl profile (radius, z)
    # A Bordeaux-ish silhouette, scaled for close-up realism.
    outer = [
        (0.018, 0.100),
        (0.026, 0.125),
        (0.038, 0.160),
        (0.046, 0.205),
        (0.044, 0.220),
    ]
    # Inner profile slightly inset
    inner = []
    for r, z in outer:
        inner.append((max(0.001, r - thickness), z - 0.0005))
    # Make inner bottom a bit higher for a solid glass floor
    inner[0] = (inner[0][0], inner[0][1] + 0.006)

    bm = bmesh.new()

    def ring(rad, z):
        verts = []
        for i in range(segments):
            a = (2.0 * math.pi * i) / segments
            verts.append(bm.verts.new((rad * cos(a), rad * sin(a), z)))
        return verts

    rings_outer = [ring(r, z) for (r, z) in outer]
    rings_inner = [ring(r, z) for (r, z) in inner]

    def bridge(ring_a, ring_b, flip=False):
        for i in range(segments):
            v1 = ring_a[i]
            v2 = ring_a[(i + 1) % segments]
            v3 = ring_b[(i + 1) % segments]
            v4 = ring_b[i]
            try:
                if flip:
                    bm.faces.new((v1, v4, v3, v2))
                else:
                    bm.faces.new((v1, v2, v3, v4))
            except ValueError:
                # Face exists
                pass

    # Outer wall
    for k in range(len(rings_outer) - 1):
        bridge(rings_outer[k], rings_outer[k + 1], flip=False)

    # Inner wall (flip normals)
    for k in range(len(rings_inner) - 1):
        bridge(rings_inner[k], rings_inner[k + 1], flip=True)

    # Rim thickness surface
    bridge(rings_outer[-1], rings_inner[-1], flip=False)

    # Bottom thickness ring
    bridge(rings_inner[0], rings_outer[0], flip=False)

    # Outer bottom cap (faces downward)
    try:
        bm.faces.new(tuple(rings_outer[0]))
    except ValueError:
        pass

    # Inner bottom cap (faces upward): reverse loop
    try:
        bm.faces.new(tuple(reversed(rings_inner[0])))
    except ValueError:
        pass

    mesh = bpy.data.meshes.new(name + "_Mesh")
    bm.to_mesh(mesh)
    bm.free()

    obj = bpy.data.objects.new(name, mesh)
    bpy.context.collection.objects.link(obj)

    # Smooth shading
    bpy.context.view_layer.objects.active = obj
    obj.select_set(True)
    try:
        bpy.ops.object.shade_smooth()
    except Exception:
        pass
    obj.select_set(False)

    return obj


