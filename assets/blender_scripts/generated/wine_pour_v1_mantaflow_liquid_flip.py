def create_wine_glass():
    """Create an approximate Bordeaux-style wine glass via lathed profile."""
    mesh = bpy.data.meshes.new("WineGlassMesh")
    obj = bpy.data.objects.new("WineGlass", mesh)
    bpy.context.collection.objects.link(obj)

    bm = bmesh.new()

    # Profile points in XZ plane (radius, height)
    # The first point must not be exactly on axis for spin face generation,
    # but we keep it very small to avoid a hole.
    p = [
        (0.002, 0.000),  # bottom center
        (0.028, 0.004),  # base outer
        (0.030, 0.006),
        (0.024, 0.008),
        (0.010, 0.010),  # stem start
        (0.007, 0.030),
        (0.007, 0.110),  # stem
        (0.014, 0.125),
        (0.022, 0.135),
        (0.036, 0.150),
        (0.048, 0.170),
        (GLASS_MAX_RADIUS, 0.190),
        (0.052, 0.210),
        (0.048, GLASS_HEIGHT),  # rim
    ]

    verts = []
    for r, z in p:
        verts.append(bm.verts.new((r, 0.0, z)))

    edges = []
    for i in range(len(verts) - 1):
        edges.append(bm.edges.new((verts[i], verts[i + 1])))

    bm.normal_update()

    geom = list(edges) + list(verts)

    # Spin around Z axis to form the glass surface
    bmesh.ops.spin(
        bm,
        geom=geom,
        cent=Vector((0.0, 0.0, 0.0)),
        axis=Vector((0.0, 0.0, 1.0)),
        angle=math.tau,
        steps=96,
    )

    # Merge close vertices to clean seam
    bmesh.ops.remove_doubles(bm, verts=bm.verts, dist=0.0001)

    # Recalculate normals
    bmesh.ops.recalc_face_normals(bm, faces=bm.faces)

    bm.to_mesh(mesh)
    bm.free()

    # Add modifiers for thickness and smoothing
    solid = obj.modifiers.new(name="Solidify", type='SOLIDIFY')
    solid.thickness = GLASS_WALL_THICKNESS
    solid.offset = 1.0

    subs = obj.modifiers.new(name="Subsurf", type='SUBSURF')
    subs.levels = 2
    subs.render_levels = 2

    # Smooth shading
    for poly in obj.data.polygons:
        poly.use_smooth = True

    # Material
    m_glass = create_material_glass()
    obj.data.materials.append(m_glass)

    # Position at world origin on table
    obj.location = (0.0, 0.0, 0.0)

    return obj


