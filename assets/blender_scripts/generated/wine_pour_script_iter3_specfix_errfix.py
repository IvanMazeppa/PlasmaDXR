def create_simple_glass_container(col):
    """A robust, simple hollow container: conical frustum with top cap removed + solidify.

    This avoids fragile spin/hole-fill operations that may trigger runtime issues.
    """
    bm = bmesh.new()

    # Bowl-like frustum (cap_ends=True for stability; remove top cap face)
    bmesh.ops.create_cone(
        bm,
        segments=64,
        radius1=0.050,   # top
        radius2=0.018,   # bottom
        depth=0.12,
        cap_ends=True,
    )

    # Move the bowl up so its bottom is above the table
    # (The cone is centered on origin by default; translate to place it)
    bmesh.ops.translate(bm, verts=bm.verts, vec=(0.0, 0.0, 0.14))

    # Remove the top cap face to open the container
    bm.faces.ensure_lookup_table()
    if len(bm.faces) > 0:
        max_z = max(v.co.z for v in bm.verts)
        top_faces = []
        for f in bm.faces:
            cz = sum(v.co.z for v in f.verts) / len(f.verts)
            if cz > (max_z - 1e-4):
                top_faces.append(f)
        if top_faces:
            bmesh.ops.delete(bm, geom=top_faces, context='FACES')

    bmesh.ops.recalc_face_normals(bm, faces=bm.faces)

    glass = new_mesh_object("WineGlass", bm, col)
    glass.location = (0.0, 0.0, TABLE_TOP_Z)

    # Thickness
    solid = glass.modifiers.new("Solidify", type='SOLIDIFY')
    solid.thickness = 0.002
    solid.offset = -1.0

    # Smoothness
    subd = glass.modifiers.new("Subsurf", type='SUBSURF')
    subd.levels = 2
    subd.render_levels = 2

    sm = glass.modifiers.new("Smooth", type='SMOOTH')
    sm.iterations = 2
    sm.factor = 0.5

    return glass


