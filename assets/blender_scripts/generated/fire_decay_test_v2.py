def setup_fire_volume_material(domain_obj):
    mat = bpy.data.materials.new(name="M_FireVolume")
    mat.use_nodes = True  # Deprecated in 5.0, but still works
    nt = mat.node_tree
    nodes, links = nt.nodes, nt.links
    nodes.clear()

    out = nodes.new('ShaderNodeOutputMaterial')
    vol = nodes.new('ShaderNodeVolumePrincipled')
    vinfo = nodes.new('ShaderNodeVolumeInfo')

    # Density from flame grid (scaled)
    dens_mult = nodes.new('ShaderNodeMath')
    dens_mult.operation = 'MULTIPLY'
    dens_mult.inputs[1].default_value = 6.0  # density_scale_in_shader

    # Emission strength from flame grid (scaled)
    emit_mult = nodes.new('ShaderNodeMath')
    emit_mult.operation = 'MULTIPLY'
    emit_mult.inputs[1].default_value = 7.0

    # Temperature mapping: (temp * 1000) + 300  -> 300K..1300K
    temp_mult = nodes.new('ShaderNodeMath')
    temp_mult.operation = 'MULTIPLY'
    temp_mult.inputs[1].default_value = 1000.0

    temp_add = nodes.new('ShaderNodeMath')
    temp_add.operation = 'ADD'
    temp_add.inputs[1].default_value = 300.0

    # Link Volume Info outputs
    # Flame -> Density / Emission Strength
    links.new(vinfo.outputs['Flame'], dens_mult.inputs[0])
    links.new(dens_mult.outputs['Value'], vol.inputs['Density'])

    links.new(vinfo.outputs['Flame'], emit_mult.inputs[0])
    links.new(emit_mult.outputs['Value'], vol.inputs['Emission Strength'])

    # Temperature -> Kelvin -> Principled Temperature
    links.new(vinfo.outputs['Temperature'], temp_mult.inputs[0])
    links.new(temp_mult.outputs['Value'], temp_add.inputs[0])
    links.new(temp_add.outputs['Value'], vol.inputs['Temperature'])

    # Blackbody controls (physically based)
    vol.inputs['Blackbody Intensity'].default_value = 8.0  # Boosted from 1.0 for fire glow
    vol.inputs['Blackbody Tint'].default_value = (1.0, 0.65, 0.22, 1.0)

    # A touch of forward scattering helps flame read volumetric
    if 'Anisotropy' in vol.inputs:
        vol.inputs['Anisotropy'].default_value = 0.15

    links.new(vol.outputs['Volume'], out.inputs['Volume'])

    # Assign material to domain object
    if domain_obj.data and hasattr(domain_obj.data, "materials"):
        if len(domain_obj.data.materials) == 0:
            domain_obj.data.materials.append(mat)
        else:
            domain_obj.data.materials[0] = mat

