    bpy.context.view_layer.objects.active = domain_obj

    fluid_ops = getattr(bpy.ops, 'fluid', None)

    def op_exists(name: str) -> bool:
        return fluid_ops is not None and hasattr(fluid_ops, name)

    def try_op(name: str) -> bool:
        op = getattr(fluid_ops, name)
        try:
            if hasattr(op, 'poll') and not op.poll():
                print(f"INFO: bpy.ops.fluid.{name}.poll() failed; skipping")
                return False
        except Exception:
            pass

        try:
            with bpy.context.temp_override(active_object=domain_obj, object=domain_obj):
                print(f"INFO: Running bpy.ops.fluid.{name}()")
                op()
            return True
        except Exception as e:
            print(f"WARN: bpy.ops.fluid.{name}() failed: {e}")
            return False

    # Prefer explicit data+noise bakes (more controllable than bake_all)
    baked = False
    if op_exists('bake_data'):
        baked = try_op('bake_data')
        if baked and op_exists('bake_noise'):
            try_op('bake_noise')

