def create_internal_constraints(shards):
    root = bpy.data.objects.new('ConstraintAnchors', None)
    root.empty_display_type = 'PLAIN_AXES'
    root.empty_display_size = 0.25
    bpy.context.scene.collection.objects.link(root)

    centers = [obj.matrix_world.translation.copy() for obj in shards]
    tree = kdtree.KDTree(len(shards))
    for index, center in enumerate(centers):
        tree.insert(center, index)
    tree.balance()

    pair_keys = set()
    count = 0
    for i, center in enumerate(centers):
        neighbors = tree.find_n(center, CONSTRAINT_NEIGHBORS + 1)
        for neighbor_co, j, dist in neighbors:
            if i == j or dist > CONSTRAINT_MAX_DISTANCE:
                continue
            key = (min(i, j), max(i, j))
            if key in pair_keys:
                continue
            pair_keys.add(key)
            midpoint = (centers[i] + centers[j]) * 0.5
            threshold = BASE_BREAK_THRESHOLD + (midpoint - IMPACT_POINT).length * DISTANCE_FALLOFF

            bpy.ops.object.empty_add(type='PLAIN_AXES', location=midpoint)
            constraint_obj = bpy.context.active_object
            constraint_obj.name = f'GlassConstraint_{count:04d}'
            constraint_obj.parent = root
            constraint_obj.empty_display_size = 0.03
            bpy.ops.rigidbody.constraint_add()
            rbc = constraint_obj.rigid_body_constraint
            rbc.type = 'FIXED'
            rbc.object1 = 'shard_a'
            rbc.object2 = 'shard_b'
            rbc.use_breaking = True
            rbc.breaking_threshold = '8.0 + dist * 35.0  # Weaker near impact'
            count += 1
    return root, count


def create_edge_constraints(shards, frame_pieces, parent_root):
    count = 0
    left_limit = -WINDOW_WIDTH * 0.5 + EDGE_ANCHOR_BAND
    right_limit = WINDOW_WIDTH * 0.5 - EDGE_ANCHOR_BAND
    bottom_limit = WINDOW_CENTER.z - WINDOW_HEIGHT * 0.5 + EDGE_ANCHOR_BAND
    top_limit = WINDOW_CENTER.z + WINDOW_HEIGHT * 0.5 - EDGE_ANCHOR_BAND

    for shard in shards:
        center = shard.matrix_world.translation.copy()
        target = None
        if center.x <= left_limit:
            target = frame_pieces['left']
        elif center.x >= right_limit:
            target = frame_pieces['right']
        elif center.z <= bottom_limit:
            target = frame_pieces['bottom']
        elif center.z >= top_limit:
            target = frame_pieces['top']

        if target is None:
            continue

        midpoint = (center + target.matrix_world.translation) * 0.5
        threshold = EDGE_BREAK_BASE + (midpoint - IMPACT_POINT).length * EDGE_BREAK_FALLOFF

        bpy.ops.object.empty_add(type='PLAIN_AXES', location=midpoint)
        constraint_obj = bpy.context.active_object
        constraint_obj.name = f'EdgeConstraint_{count:04d}'
        constraint_obj.parent = parent_root
        constraint_obj.empty_display_size = 0.025
        bpy.ops.rigidbody.constraint_add()
        rbc = constraint_obj.rigid_body_constraint
        rbc.type = 'FIXED'
        rbc.object1 = shard
        rbc.object2 = target
        rbc.use_breaking = True
        rbc.breaking_threshold = threshold
        count += 1
    return count


